-- P09 account-level setup. Run once as ACCOUNTADMIN. Replace nothing by hand: run_sql.sh fills <your-verified-email>.
--   P09_OWNER        owns the database and RAW, loads files, owns alerts
--   P09_TRANSFORMER  runs dbt: reads RAW, creates and owns its own schemas
--   P09_READER       reads marts

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS P09_OWNER;
CREATE ROLE IF NOT EXISTS P09_TRANSFORMER;
CREATE ROLE IF NOT EXISTS P09_READER;
GRANT ROLE P09_READER TO ROLE P09_OWNER;
GRANT ROLE P09_READER TO ROLE P09_TRANSFORMER;
GRANT ROLE P09_OWNER TO ROLE SYSADMIN;
GRANT ROLE P09_TRANSFORMER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P09_OWNER TO USER IDENTIFIER($my_user);
GRANT ROLE P09_TRANSFORMER TO USER IDENTIFIER($my_user);
GRANT ROLE P09_READER TO USER IDENTIFIER($my_user);

CREATE RESOURCE MONITOR IF NOT EXISTS P09_RM
  WITH CREDIT_QUOTA = 3
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS P09_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 900
  RESOURCE_MONITOR = P09_RM
  COMMENT = 'P09 loads, dbt runs, alerts';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P09_WH TO ROLE P09_OWNER;
GRANT USAGE ON WAREHOUSE P09_WH TO ROLE P09_TRANSFORMER;
GRANT USAGE ON WAREHOUSE P09_WH TO ROLE P09_READER;

CREATE DATABASE IF NOT EXISTS P09_MARKETS COMMENT = 'P09 crypto and market data modelled with dbt';
GRANT OWNERSHIP ON DATABASE P09_MARKETS TO ROLE P09_OWNER COPY CURRENT GRANTS;

-- dbt creates one schema per layer and per developer or pull request.
GRANT USAGE, CREATE SCHEMA ON DATABASE P09_MARKETS TO ROLE P09_TRANSFORMER;
GRANT USAGE ON DATABASE P09_MARKETS TO ROLE P09_READER;

GRANT EXECUTE ALERT ON ACCOUNT TO ROLE P09_OWNER;

CREATE NOTIFICATION INTEGRATION IF NOT EXISTS P09_EMAIL_INT
  TYPE = EMAIL
  ENABLED = TRUE
  ALLOWED_RECIPIENTS = ('<your-verified-email>');
GRANT USAGE ON INTEGRATION P09_EMAIL_INT TO ROLE P09_OWNER;
