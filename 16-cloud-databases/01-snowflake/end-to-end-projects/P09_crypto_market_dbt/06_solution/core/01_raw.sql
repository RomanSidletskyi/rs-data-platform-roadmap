-- P09 raw layer: stage, file formats, raw tables. Run as P09_OWNER.

USE ROLE P09_OWNER;
USE WAREHOUSE P09_WH;
USE DATABASE P09_MARKETS;

CREATE SCHEMA IF NOT EXISTS RAW COMMENT = 'Files as delivered; read by dbt sources';
CREATE SCHEMA IF NOT EXISTS OPS COMMENT = 'Alerts and run log';

CREATE FILE FORMAT IF NOT EXISTS RAW.FF_JSON TYPE = JSON COMPRESSION = AUTO;
CREATE FILE FORMAT IF NOT EXISTS RAW.FF_CSV
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"';

CREATE STAGE IF NOT EXISTS RAW.MARKET_STAGE
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'coinbase/product=*/ and fred/series=*/';

CREATE TABLE IF NOT EXISTS RAW.COINBASE_CANDLES_RAW (
  PAYLOAD   VARIANT,
  SRC_FILE  STRING,
  LOADED_AT TIMESTAMP_LTZ
);

-- Values stay strings: FRED marks missing days with an empty value, and typing is dbt's job.
CREATE TABLE IF NOT EXISTS RAW.FRED_OBSERVATIONS_RAW (
  SERIES_ID        STRING,
  OBSERVATION_DATE STRING,
  VALUE            STRING,
  SRC_FILE         STRING,
  LOADED_AT        TIMESTAMP_LTZ
);

GRANT USAGE ON SCHEMA RAW TO ROLE P09_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA RAW TO ROLE P09_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW TO ROLE P09_TRANSFORMER;
