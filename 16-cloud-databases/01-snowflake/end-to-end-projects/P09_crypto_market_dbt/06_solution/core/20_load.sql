-- P09 load: COPY new or changed files from the stage. Run as P09_OWNER after ./upload.sh, before dbt.

USE ROLE P09_OWNER;
USE WAREHOUSE P09_WH;
USE DATABASE P09_MARKETS;

COPY INTO RAW.COINBASE_CANDLES_RAW (PAYLOAD, SRC_FILE, LOADED_AT)
FROM (SELECT $1, METADATA$FILENAME, METADATA$START_SCAN_TIME FROM @RAW.MARKET_STAGE/coinbase/)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_JSON')
ON_ERROR = SKIP_FILE;

COPY INTO RAW.FRED_OBSERVATIONS_RAW (SERIES_ID, OBSERVATION_DATE, VALUE, SRC_FILE, LOADED_AT)
FROM (
  SELECT REGEXP_SUBSTR(METADATA$FILENAME, 'series=([A-Z0-9]+)', 1, 1, 'e'), $1, $2, METADATA$FILENAME, METADATA$START_SCAN_TIME
  FROM @RAW.MARKET_STAGE/fred/
)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_CSV')
ON_ERROR = SKIP_FILE;
