-- P02 data quality checks. Run as P02_OWNER after 20_load_and_model.sql.

USE ROLE P02_OWNER;
USE WAREHOUSE P02_WH;
USE DATABASE P02_WEATHER;

WITH coverage AS (
  SELECT CITY_SLUG, YEAR(TS_UTC) AS Y, COUNT(*) AS HOURS,
         DATEDIFF('hour', MIN(TS_UTC), MAX(TS_UTC)) + 1 AS EXPECTED_HOURS
  FROM STG.WEATHER_HOURLY
  GROUP BY 1, 2
),
checks AS (
  SELECT 'missing_hours_within_city_year' AS CHECK_NAME, COALESCE(SUM(EXPECTED_HOURS - HOURS), 0) AS FAILURES
  FROM coverage

  UNION ALL
  SELECT 'duplicate_city_hour', COUNT(*)
  FROM (SELECT CITY_SLUG, TS_UTC FROM STG.WEATHER_HOURLY GROUP BY 1, 2 HAVING COUNT(*) > 1)

  UNION ALL
  SELECT 'temperature_out_of_physical_range', COUNT(*)
  FROM STG.WEATHER_HOURLY WHERE TEMPERATURE_C NOT BETWEEN -80 AND 60

  UNION ALL
  SELECT 'humidity_out_of_range', COUNT(*)
  FROM STG.WEATHER_HOURLY WHERE HUMIDITY_PCT NOT BETWEEN 0 AND 100

  UNION ALL
  SELECT 'negative_precipitation', COUNT(*)
  FROM STG.WEATHER_HOURLY WHERE PRECIPITATION_MM < 0

  UNION ALL
  SELECT 'null_temperature', COUNT(*)
  FROM STG.WEATHER_HOURLY WHERE TEMPERATURE_C IS NULL

  UNION ALL
  SELECT 'unknown_city', COUNT(*)
  FROM STG.WEATHER_HOURLY h WHERE NOT EXISTS (SELECT 1 FROM STG.CITY c WHERE c.CITY_SLUG = h.CITY_SLUG)
)
SELECT CHECK_NAME, FAILURES, IFF(FAILURES = 0, 'PASS', 'FAIL') AS RESULT
FROM checks
ORDER BY RESULT, CHECK_NAME;
