-- P02 account-level setup. Run once as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS P02_OWNER;
CREATE ROLE IF NOT EXISTS P02_READER;
GRANT ROLE P02_READER TO ROLE P02_OWNER;
GRANT ROLE P02_OWNER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P02_OWNER TO USER IDENTIFIER($my_user);
GRANT ROLE P02_READER TO USER IDENTIFIER($my_user);

CREATE RESOURCE MONITOR IF NOT EXISTS P02_RM
  WITH CREDIT_QUOTA = 3
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

-- Notebooks keep their warehouse busy while a session is open; a short suspend limits idle cost.
CREATE WAREHOUSE IF NOT EXISTS P02_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 900
  RESOURCE_MONITOR = P02_RM
  COMMENT = 'P02 loading, notebook queries, dashboards';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P02_WH TO ROLE P02_OWNER;
GRANT USAGE ON WAREHOUSE P02_WH TO ROLE P02_READER;

CREATE DATABASE IF NOT EXISTS P02_WEATHER COMMENT = 'P02 weather EDA with notebooks';
GRANT OWNERSHIP ON DATABASE P02_WEATHER TO ROLE P02_OWNER COPY CURRENT GRANTS;
