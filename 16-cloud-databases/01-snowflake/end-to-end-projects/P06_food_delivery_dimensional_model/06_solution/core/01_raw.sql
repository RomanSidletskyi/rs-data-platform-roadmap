-- P06 raw layer: stage, typed raw tables that keep every extracted row, append-only streams. Run as P06_OWNER.

USE ROLE P06_OWNER;
USE WAREHOUSE P06_WH;
USE DATABASE P06_FOOD;

CREATE SCHEMA IF NOT EXISTS RAW  COMMENT = 'Every extracted row, as delivered, with file lineage';
CREATE SCHEMA IF NOT EXISTS STG  COMMENT = 'Work tables for the current batch';
CREATE SCHEMA IF NOT EXISTS CORE COMMENT = 'Dimensions and facts';
CREATE SCHEMA IF NOT EXISTS MART COMMENT = 'Analyst-facing views and dynamic tables';
CREATE SCHEMA IF NOT EXISTS PIPE COMMENT = 'Task graph';
CREATE SCHEMA IF NOT EXISTS OPS  COMMENT = 'Run log';

-- PARSE_HEADER lets COPY match CSV columns to table columns by name, so column order in files does not matter.
CREATE FILE FORMAT IF NOT EXISTS RAW.FF_CSV
  TYPE = CSV
  PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE;

CREATE STAGE IF NOT EXISTS RAW.EXTRACT_STAGE
  FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_CSV')
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Daily extracts: day=YYYY-MM-DD/<table>.csv';

CREATE TABLE IF NOT EXISTS RAW.CUSTOMERS (
  CUSTOMER_ID NUMBER, FULL_NAME STRING, EMAIL STRING, CITY STRING, LOYALTY_TIER STRING,
  SIGNUP_DATE DATE, IS_DELETED BOOLEAN, UPDATED_AT TIMESTAMP_NTZ,
  SRC_FILE STRING, LOADED_AT TIMESTAMP_LTZ
);
CREATE TABLE IF NOT EXISTS RAW.RESTAURANTS (
  RESTAURANT_ID NUMBER, NAME STRING, CITY STRING, CUISINE STRING, PRICE_TIER NUMBER,
  RATING NUMBER(3, 1), IS_ACTIVE BOOLEAN, UPDATED_AT TIMESTAMP_NTZ,
  SRC_FILE STRING, LOADED_AT TIMESTAMP_LTZ
);
CREATE TABLE IF NOT EXISTS RAW.MENU_ITEMS (
  ITEM_ID NUMBER, RESTAURANT_ID NUMBER, NAME STRING, CATEGORY STRING, PRICE NUMBER(10, 2),
  IS_AVAILABLE BOOLEAN, UPDATED_AT TIMESTAMP_NTZ,
  SRC_FILE STRING, LOADED_AT TIMESTAMP_LTZ
);
CREATE TABLE IF NOT EXISTS RAW.COURIERS (
  COURIER_ID NUMBER, NAME STRING, CITY STRING, VEHICLE STRING, UPDATED_AT TIMESTAMP_NTZ,
  SRC_FILE STRING, LOADED_AT TIMESTAMP_LTZ
);
CREATE TABLE IF NOT EXISTS RAW.ORDERS (
  ORDER_ID NUMBER, CUSTOMER_ID NUMBER, RESTAURANT_ID NUMBER, COURIER_ID NUMBER, STATUS STRING,
  PLACED_AT TIMESTAMP_NTZ, ACCEPTED_AT TIMESTAMP_NTZ, PICKED_UP_AT TIMESTAMP_NTZ,
  DELIVERED_AT TIMESTAMP_NTZ, CANCELLED_AT TIMESTAMP_NTZ,
  DELIVERY_FEE NUMBER(10, 2), TIP NUMBER(10, 2), UPDATED_AT TIMESTAMP_NTZ,
  SRC_FILE STRING, LOADED_AT TIMESTAMP_LTZ
);
CREATE TABLE IF NOT EXISTS RAW.ORDER_ITEMS (
  ORDER_ID NUMBER, LINE_NO NUMBER, ITEM_ID NUMBER, QUANTITY NUMBER, UNIT_PRICE NUMBER(10, 2),
  UPDATED_AT TIMESTAMP_NTZ,
  SRC_FILE STRING, LOADED_AT TIMESTAMP_LTZ
);

-- RAW only ever receives inserts, so append-only streams are enough and cheaper to compute.
CREATE STREAM IF NOT EXISTS RAW.CUSTOMERS_STREAM   ON TABLE RAW.CUSTOMERS   APPEND_ONLY = TRUE;
CREATE STREAM IF NOT EXISTS RAW.RESTAURANTS_STREAM ON TABLE RAW.RESTAURANTS APPEND_ONLY = TRUE;
CREATE STREAM IF NOT EXISTS RAW.MENU_ITEMS_STREAM  ON TABLE RAW.MENU_ITEMS  APPEND_ONLY = TRUE;
CREATE STREAM IF NOT EXISTS RAW.COURIERS_STREAM    ON TABLE RAW.COURIERS    APPEND_ONLY = TRUE;
CREATE STREAM IF NOT EXISTS RAW.ORDERS_STREAM      ON TABLE RAW.ORDERS      APPEND_ONLY = TRUE;
CREATE STREAM IF NOT EXISTS RAW.ORDER_ITEMS_STREAM ON TABLE RAW.ORDER_ITEMS APPEND_ONLY = TRUE;

CREATE TABLE IF NOT EXISTS OPS.RUN_LOG (
  RUN_AT        TIMESTAMP_LTZ,
  GRAPH_RUN_ID  STRING,
  STEP          STRING,
  ROWS_AFFECTED NUMBER,
  NOTE          STRING
);
