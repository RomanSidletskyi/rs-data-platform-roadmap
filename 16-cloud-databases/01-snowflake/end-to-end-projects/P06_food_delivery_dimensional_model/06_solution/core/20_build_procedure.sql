-- P06 build procedure: one batch from the RAW streams into dimensions and facts, in one transaction. Run as P06_OWNER.
-- Called by PIPE.BUILD_CORE; can also be called by hand: CALL CORE.SP_BUILD_CORE('manual');

USE ROLE P06_OWNER;
USE WAREHOUSE P06_WH;
USE DATABASE P06_FOOD;

CREATE OR REPLACE PROCEDURE CORE.SP_BUILD_CORE(RUN_ID STRING)
RETURNS STRING
LANGUAGE SQL
COMMENT = 'Streams to SCD1 and SCD2 dimensions, inferred members, accumulating order fact, order line fact'
AS
$$
DECLARE
  customer_versions   NUMBER DEFAULT 0;
  restaurant_versions NUMBER DEFAULT 0;
  late_changes        NUMBER DEFAULT 0;
  inferred            NUMBER DEFAULT 0;
  orders              NUMBER DEFAULT 0;
  lines               NUMBER DEFAULT 0;
  summary             STRING;
BEGIN
  BEGIN TRANSACTION;

  ------------------------------------------------------------------------------------------------
  -- 1. Freeze the batch. Each stream is read by exactly one statement in this transaction.
  ------------------------------------------------------------------------------------------------
  DELETE FROM STG.CUSTOMER_CHANGES;
  INSERT INTO STG.CUSTOMER_CHANGES
  SELECT DISTINCT CUSTOMER_ID, FULL_NAME, EMAIL, CITY, LOYALTY_TIER, SIGNUP_DATE, IS_DELETED, UPDATED_AT,
         HASH(CITY, LOYALTY_TIER, IS_DELETED)
  FROM RAW.CUSTOMERS_STREAM;

  DELETE FROM STG.RESTAURANT_CHANGES;
  INSERT INTO STG.RESTAURANT_CHANGES
  SELECT DISTINCT RESTAURANT_ID, NAME, RATING, CITY, CUISINE, PRICE_TIER, IS_ACTIVE, UPDATED_AT,
         HASH(CITY, CUISINE, PRICE_TIER, IS_ACTIVE)
  FROM RAW.RESTAURANTS_STREAM;

  DELETE FROM STG.MENU_ITEM_BATCH;
  INSERT INTO STG.MENU_ITEM_BATCH
  SELECT * FROM RAW.MENU_ITEMS_STREAM
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ITEM_ID ORDER BY UPDATED_AT DESC) = 1;

  DELETE FROM STG.COURIER_BATCH;
  INSERT INTO STG.COURIER_BATCH
  SELECT * FROM RAW.COURIERS_STREAM
  QUALIFY ROW_NUMBER() OVER (PARTITION BY COURIER_ID ORDER BY UPDATED_AT DESC) = 1;

  -- Latest state per order; exact duplicates in the extract collapse here.
  DELETE FROM STG.ORDER_BATCH;
  INSERT INTO STG.ORDER_BATCH
  SELECT * FROM RAW.ORDERS_STREAM
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_ID ORDER BY UPDATED_AT DESC, LOADED_AT DESC) = 1;

  DELETE FROM STG.ORDER_ITEM_BATCH;
  INSERT INTO STG.ORDER_ITEM_BATCH
  SELECT * FROM RAW.ORDER_ITEMS_STREAM
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_ID, LINE_NO ORDER BY UPDATED_AT DESC, LOADED_AT DESC) = 1;

  ------------------------------------------------------------------------------------------------
  -- 2. SCD1 dimensions: overwrite in place.
  ------------------------------------------------------------------------------------------------
  MERGE INTO CORE.DIM_MENU_ITEM t
  USING STG.MENU_ITEM_BATCH s ON t.ITEM_ID = s.ITEM_ID
  WHEN MATCHED AND s.UPDATED_AT > t.UPDATED_AT THEN UPDATE SET
    RESTAURANT_ID = s.RESTAURANT_ID, NAME = s.NAME, CATEGORY = s.CATEGORY, CURRENT_PRICE = s.PRICE,
    IS_AVAILABLE = s.IS_AVAILABLE, UPDATED_AT = s.UPDATED_AT
  WHEN NOT MATCHED THEN INSERT (ITEM_ID, RESTAURANT_ID, NAME, CATEGORY, CURRENT_PRICE, IS_AVAILABLE, UPDATED_AT)
    VALUES (s.ITEM_ID, s.RESTAURANT_ID, s.NAME, s.CATEGORY, s.PRICE, s.IS_AVAILABLE, s.UPDATED_AT);

  MERGE INTO CORE.DIM_COURIER t
  USING STG.COURIER_BATCH s ON t.COURIER_ID = s.COURIER_ID
  WHEN MATCHED AND s.UPDATED_AT > t.UPDATED_AT THEN UPDATE SET
    NAME = s.NAME, CITY = s.CITY, VEHICLE = s.VEHICLE, UPDATED_AT = s.UPDATED_AT
  WHEN NOT MATCHED THEN INSERT (COURIER_ID, NAME, CITY, VEHICLE, UPDATED_AT)
    VALUES (s.COURIER_ID, s.NAME, s.CITY, s.VEHICLE, s.UPDATED_AT);

  ------------------------------------------------------------------------------------------------
  -- 3. SCD2 customers.
  --    a) keep only rows whose tracked attributes differ from the version before them
  --    b) close the current version
  --    c) an inferred member is completed in place, so facts that already point to it stay valid
  --    d) insert the new versions
  --    e) overwrite SCD1 attributes on all versions
  ------------------------------------------------------------------------------------------------
  SELECT COUNT(*) INTO :late_changes
  FROM STG.CUSTOMER_CHANGES c
  JOIN CORE.DIM_CUSTOMER d ON d.CUSTOMER_ID = c.CUSTOMER_ID AND d.IS_CURRENT AND NOT d.IS_INFERRED
  WHERE c.UPDATED_AT <= d.VALID_FROM AND c.ATTR_HASH <> d.ATTR_HASH;

  DELETE FROM STG.CUSTOMER_VERSIONS;
  INSERT INTO STG.CUSTOMER_VERSIONS
  WITH cur AS (
    SELECT CUSTOMER_ID, ATTR_HASH, VALID_FROM, IS_INFERRED
    FROM CORE.DIM_CUSTOMER
    WHERE IS_CURRENT AND CUSTOMER_SK > 0
  ),
  candidates AS (
    SELECT c.*, cur.ATTR_HASH AS CUR_HASH, cur.CUSTOMER_ID IS NOT NULL AS CUR_EXISTS,
           COALESCE(cur.IS_INFERRED, FALSE) AS CUR_INFERRED
    FROM STG.CUSTOMER_CHANGES c
    LEFT JOIN cur ON cur.CUSTOMER_ID = c.CUSTOMER_ID
    -- A change older than the current version would rewrite history: counted above and skipped (ADR-003).
    WHERE cur.CUSTOMER_ID IS NULL OR cur.IS_INFERRED OR c.UPDATED_AT > cur.VALID_FROM
  ),
  kept AS (
    SELECT * FROM candidates
    QUALIFY ATTR_HASH IS DISTINCT FROM COALESCE(
      LAG(ATTR_HASH) OVER (PARTITION BY CUSTOMER_ID ORDER BY UPDATED_AT),
      IFF(CUR_INFERRED, NULL, CUR_HASH))
  )
  SELECT
    CUSTOMER_ID, FULL_NAME, EMAIL, CITY, LOYALTY_TIER, SIGNUP_DATE, IS_DELETED, ATTR_HASH,
    -- The first version of a new key is valid from the beginning of time, so earlier facts still find it.
    IFF(NOT CUR_EXISTS AND ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY UPDATED_AT) = 1,
        '1900-01-01'::TIMESTAMP_NTZ, UPDATED_AT),
    LEAD(UPDATED_AT) OVER (PARTITION BY CUSTOMER_ID ORDER BY UPDATED_AT),
    ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY UPDATED_AT) = 1,
    CUR_INFERRED
  FROM kept;
  customer_versions := SQLROWCOUNT;

  UPDATE CORE.DIM_CUSTOMER d
  SET VALID_TO = v.VALID_FROM, IS_CURRENT = FALSE
  FROM STG.CUSTOMER_VERSIONS v
  WHERE d.CUSTOMER_ID = v.CUSTOMER_ID AND v.IS_FIRST AND d.IS_CURRENT AND NOT d.IS_INFERRED;

  UPDATE CORE.DIM_CUSTOMER d
  SET FULL_NAME = v.FULL_NAME, EMAIL = v.EMAIL, CITY = v.CITY, LOYALTY_TIER = v.LOYALTY_TIER,
      SIGNUP_DATE = v.SIGNUP_DATE, IS_DELETED = v.IS_DELETED, ATTR_HASH = v.ATTR_HASH,
      VALID_TO = COALESCE(v.NEXT_FROM, '9999-12-31'::TIMESTAMP_NTZ), IS_CURRENT = v.NEXT_FROM IS NULL,
      IS_INFERRED = FALSE, LOADED_AT = CURRENT_TIMESTAMP()
  FROM STG.CUSTOMER_VERSIONS v
  WHERE d.CUSTOMER_ID = v.CUSTOMER_ID AND v.IS_FIRST AND d.IS_CURRENT AND d.IS_INFERRED;

  INSERT INTO CORE.DIM_CUSTOMER (CUSTOMER_ID, FULL_NAME, EMAIL, CITY, LOYALTY_TIER, SIGNUP_DATE, IS_DELETED,
                                 ATTR_HASH, VALID_FROM, VALID_TO, IS_CURRENT, IS_INFERRED, LOADED_AT)
  SELECT CUSTOMER_ID, FULL_NAME, EMAIL, CITY, LOYALTY_TIER, SIGNUP_DATE, IS_DELETED, ATTR_HASH,
         VALID_FROM, COALESCE(NEXT_FROM, '9999-12-31'::TIMESTAMP_NTZ), NEXT_FROM IS NULL, FALSE, CURRENT_TIMESTAMP()
  FROM STG.CUSTOMER_VERSIONS
  WHERE NOT (IS_FIRST AND CUR_INFERRED);

  UPDATE CORE.DIM_CUSTOMER d
  SET FULL_NAME = c.FULL_NAME, EMAIL = c.EMAIL
  FROM (
    SELECT CUSTOMER_ID, FULL_NAME, EMAIL FROM STG.CUSTOMER_CHANGES
    QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY UPDATED_AT DESC) = 1
  ) c
  WHERE d.CUSTOMER_ID = c.CUSTOMER_ID
    AND (d.FULL_NAME IS DISTINCT FROM c.FULL_NAME OR d.EMAIL IS DISTINCT FROM c.EMAIL);

  ------------------------------------------------------------------------------------------------
  -- 4. SCD2 restaurants: same pattern.
  ------------------------------------------------------------------------------------------------
  DELETE FROM STG.RESTAURANT_VERSIONS;
  INSERT INTO STG.RESTAURANT_VERSIONS
  WITH cur AS (
    SELECT RESTAURANT_ID, ATTR_HASH, VALID_FROM, IS_INFERRED
    FROM CORE.DIM_RESTAURANT
    WHERE IS_CURRENT AND RESTAURANT_SK > 0
  ),
  candidates AS (
    SELECT c.*, cur.ATTR_HASH AS CUR_HASH, cur.RESTAURANT_ID IS NOT NULL AS CUR_EXISTS,
           COALESCE(cur.IS_INFERRED, FALSE) AS CUR_INFERRED
    FROM STG.RESTAURANT_CHANGES c
    LEFT JOIN cur ON cur.RESTAURANT_ID = c.RESTAURANT_ID
    WHERE cur.RESTAURANT_ID IS NULL OR cur.IS_INFERRED OR c.UPDATED_AT > cur.VALID_FROM
  ),
  kept AS (
    SELECT * FROM candidates
    QUALIFY ATTR_HASH IS DISTINCT FROM COALESCE(
      LAG(ATTR_HASH) OVER (PARTITION BY RESTAURANT_ID ORDER BY UPDATED_AT),
      IFF(CUR_INFERRED, NULL, CUR_HASH))
  )
  SELECT
    RESTAURANT_ID, NAME, RATING, CITY, CUISINE, PRICE_TIER, IS_ACTIVE, ATTR_HASH,
    IFF(NOT CUR_EXISTS AND ROW_NUMBER() OVER (PARTITION BY RESTAURANT_ID ORDER BY UPDATED_AT) = 1,
        '1900-01-01'::TIMESTAMP_NTZ, UPDATED_AT),
    LEAD(UPDATED_AT) OVER (PARTITION BY RESTAURANT_ID ORDER BY UPDATED_AT),
    ROW_NUMBER() OVER (PARTITION BY RESTAURANT_ID ORDER BY UPDATED_AT) = 1,
    CUR_INFERRED
  FROM kept;
  restaurant_versions := SQLROWCOUNT;

  UPDATE CORE.DIM_RESTAURANT d
  SET VALID_TO = v.VALID_FROM, IS_CURRENT = FALSE
  FROM STG.RESTAURANT_VERSIONS v
  WHERE d.RESTAURANT_ID = v.RESTAURANT_ID AND v.IS_FIRST AND d.IS_CURRENT AND NOT d.IS_INFERRED;

  INSERT INTO CORE.DIM_RESTAURANT (RESTAURANT_ID, NAME, RATING, CITY, CUISINE, PRICE_TIER, IS_ACTIVE,
                                   ATTR_HASH, VALID_FROM, VALID_TO, IS_CURRENT, IS_INFERRED, LOADED_AT)
  SELECT RESTAURANT_ID, NAME, RATING, CITY, CUISINE, PRICE_TIER, IS_ACTIVE, ATTR_HASH,
         VALID_FROM, COALESCE(NEXT_FROM, '9999-12-31'::TIMESTAMP_NTZ), NEXT_FROM IS NULL, FALSE, CURRENT_TIMESTAMP()
  FROM STG.RESTAURANT_VERSIONS;

  UPDATE CORE.DIM_RESTAURANT d
  SET NAME = c.NAME, RATING = c.RATING
  FROM (
    SELECT RESTAURANT_ID, NAME, RATING FROM STG.RESTAURANT_CHANGES
    QUALIFY ROW_NUMBER() OVER (PARTITION BY RESTAURANT_ID ORDER BY UPDATED_AT DESC) = 1
  ) c
  WHERE d.RESTAURANT_ID = c.RESTAURANT_ID
    AND (d.NAME IS DISTINCT FROM c.NAME OR d.RATING IS DISTINCT FROM c.RATING);

  ------------------------------------------------------------------------------------------------
  -- 5. Late-arriving customers: an order arrived before its customer. Create an inferred member now;
  --    step 3 completes it when the customer record arrives.
  ------------------------------------------------------------------------------------------------
  INSERT INTO CORE.DIM_CUSTOMER (CUSTOMER_ID, FULL_NAME, CITY, LOYALTY_TIER, IS_DELETED,
                                 VALID_FROM, VALID_TO, IS_CURRENT, IS_INFERRED, LOADED_AT)
  SELECT DISTINCT b.CUSTOMER_ID, 'Inferred', 'Unknown', 'Unknown', FALSE,
         '1900-01-01'::TIMESTAMP_NTZ, '9999-12-31'::TIMESTAMP_NTZ, TRUE, TRUE, CURRENT_TIMESTAMP()
  FROM STG.ORDER_BATCH b
  WHERE NOT EXISTS (SELECT 1 FROM CORE.DIM_CUSTOMER d WHERE d.CUSTOMER_ID = b.CUSTOMER_ID);
  inferred := SQLROWCOUNT;

  ------------------------------------------------------------------------------------------------
  -- 6. Order fact (accumulating snapshot). Keys are resolved as of PLACED_AT on first sight only.
  --    Overlapping SCD2 ranges would match twice and make this MERGE fail as nondeterministic.
  ------------------------------------------------------------------------------------------------
  MERGE INTO CORE.FACT_ORDER t
  USING (
    SELECT b.*,
           COALESCE(c.CUSTOMER_SK, -1)   AS CUSTOMER_SK,
           COALESCE(r.RESTAURANT_SK, -1) AS RESTAURANT_SK,
           COALESCE(k.COURIER_SK, -1)    AS COURIER_SK,
           TO_NUMBER(TO_CHAR(b.PLACED_AT, 'YYYYMMDD')) AS ORDER_DATE_KEY,
           DATEDIFF('minute', b.PLACED_AT, b.DELIVERED_AT) AS MINUTES_TO_DELIVER
    FROM STG.ORDER_BATCH b
    LEFT JOIN CORE.DIM_CUSTOMER c
      ON c.CUSTOMER_ID = b.CUSTOMER_ID AND b.PLACED_AT >= c.VALID_FROM AND b.PLACED_AT < c.VALID_TO
    LEFT JOIN CORE.DIM_RESTAURANT r
      ON r.RESTAURANT_ID = b.RESTAURANT_ID AND b.PLACED_AT >= r.VALID_FROM AND b.PLACED_AT < r.VALID_TO
    LEFT JOIN CORE.DIM_COURIER k
      ON k.COURIER_ID = b.COURIER_ID
  ) s
  ON t.ORDER_ID = s.ORDER_ID
  WHEN MATCHED AND s.UPDATED_AT > t.SOURCE_UPDATED_AT THEN UPDATE SET
    STATUS = s.STATUS, ACCEPTED_AT = s.ACCEPTED_AT, PICKED_UP_AT = s.PICKED_UP_AT,
    DELIVERED_AT = s.DELIVERED_AT, CANCELLED_AT = s.CANCELLED_AT, MINUTES_TO_DELIVER = s.MINUTES_TO_DELIVER,
    DELIVERY_FEE = s.DELIVERY_FEE, TIP = s.TIP,
    TOTAL_AMOUNT = COALESCE(t.ITEMS_AMOUNT, 0) + s.DELIVERY_FEE + s.TIP,
    SOURCE_UPDATED_AT = s.UPDATED_AT, UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (
    ORDER_ID, CUSTOMER_SK, RESTAURANT_SK, COURIER_SK, ORDER_DATE_KEY, STATUS, PLACED_AT, ACCEPTED_AT,
    PICKED_UP_AT, DELIVERED_AT, CANCELLED_AT, MINUTES_TO_DELIVER, ITEMS_AMOUNT, DELIVERY_FEE, TIP,
    TOTAL_AMOUNT, SOURCE_UPDATED_AT, UPDATED_AT
  ) VALUES (
    s.ORDER_ID, s.CUSTOMER_SK, s.RESTAURANT_SK, s.COURIER_SK, s.ORDER_DATE_KEY, s.STATUS, s.PLACED_AT,
    s.ACCEPTED_AT, s.PICKED_UP_AT, s.DELIVERED_AT, s.CANCELLED_AT, s.MINUTES_TO_DELIVER, 0, s.DELIVERY_FEE,
    s.TIP, s.DELIVERY_FEE + s.TIP, s.UPDATED_AT, CURRENT_TIMESTAMP()
  );
  orders := SQLROWCOUNT;

  ------------------------------------------------------------------------------------------------
  -- 7. Order line fact. The price is the one on the line, not the menu's current price.
  ------------------------------------------------------------------------------------------------
  MERGE INTO CORE.FACT_ORDER_ITEM t
  USING (
    SELECT i.ORDER_ID, i.LINE_NO, COALESCE(m.ITEM_SK, -1) AS ITEM_SK, f.RESTAURANT_SK, f.CUSTOMER_SK,
           f.ORDER_DATE_KEY, i.QUANTITY, i.UNIT_PRICE, i.QUANTITY * i.UNIT_PRICE AS LINE_AMOUNT
    FROM STG.ORDER_ITEM_BATCH i
    JOIN CORE.FACT_ORDER f ON f.ORDER_ID = i.ORDER_ID
    LEFT JOIN CORE.DIM_MENU_ITEM m ON m.ITEM_ID = i.ITEM_ID
  ) s
  ON t.ORDER_ID = s.ORDER_ID AND t.LINE_NO = s.LINE_NO
  WHEN NOT MATCHED THEN INSERT (ORDER_ID, LINE_NO, ITEM_SK, RESTAURANT_SK, CUSTOMER_SK, ORDER_DATE_KEY, QUANTITY, UNIT_PRICE, LINE_AMOUNT)
    VALUES (s.ORDER_ID, s.LINE_NO, s.ITEM_SK, s.RESTAURANT_SK, s.CUSTOMER_SK, s.ORDER_DATE_KEY, s.QUANTITY, s.UNIT_PRICE, s.LINE_AMOUNT);
  lines := SQLROWCOUNT;

  UPDATE CORE.FACT_ORDER f
  SET ITEMS_AMOUNT = x.AMOUNT, TOTAL_AMOUNT = x.AMOUNT + f.DELIVERY_FEE + f.TIP
  FROM (
    SELECT ORDER_ID, SUM(LINE_AMOUNT) AS AMOUNT
    FROM CORE.FACT_ORDER_ITEM
    WHERE ORDER_ID IN (SELECT ORDER_ID FROM STG.ORDER_ITEM_BATCH)
    GROUP BY ORDER_ID
  ) x
  WHERE f.ORDER_ID = x.ORDER_ID;

  summary := customer_versions || ' customer versions, ' || restaurant_versions || ' restaurant versions, '
          || late_changes || ' late customer changes skipped, ' || inferred || ' inferred customers, '
          || orders || ' orders merged, ' || lines || ' lines inserted';
  INSERT INTO OPS.RUN_LOG SELECT CURRENT_TIMESTAMP(), :RUN_ID, 'BUILD_CORE', :orders, :summary;

  COMMIT;
  RETURN summary;
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END;
$$;
