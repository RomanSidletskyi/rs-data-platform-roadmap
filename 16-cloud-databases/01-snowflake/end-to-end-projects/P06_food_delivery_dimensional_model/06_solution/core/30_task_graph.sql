-- P06 task graph in schema PIPE: LOAD_RAW (root) -> BUILD_CORE, plus a finalizer. Run as P06_OWNER.
-- The root runs daily at 06:00 UTC; during the project start it by hand after each upload.

USE ROLE P06_OWNER;
USE WAREHOUSE P06_WH;
USE DATABASE P06_FOOD;

ALTER TASK IF EXISTS PIPE.LOAD_RAW SUSPEND;

CREATE OR REPLACE TASK PIPE.LOAD_RAW
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  SCHEDULE = 'USING CRON 0 6 * * * UTC'
  COMMENT = 'Root: COPY new extract files into RAW; load metadata skips files already loaded'
AS
EXECUTE IMMEDIATE $$
BEGIN
  COPY INTO RAW.CUSTOMERS FROM @RAW.EXTRACT_STAGE
    PATTERN = '.*customers[.]csv[.]gz' MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    INCLUDE_METADATA = (SRC_FILE = METADATA$FILENAME, LOADED_AT = METADATA$START_SCAN_TIME) ON_ERROR = SKIP_FILE;
  COPY INTO RAW.RESTAURANTS FROM @RAW.EXTRACT_STAGE
    PATTERN = '.*restaurants[.]csv[.]gz' MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    INCLUDE_METADATA = (SRC_FILE = METADATA$FILENAME, LOADED_AT = METADATA$START_SCAN_TIME) ON_ERROR = SKIP_FILE;
  COPY INTO RAW.MENU_ITEMS FROM @RAW.EXTRACT_STAGE
    PATTERN = '.*menu_items[.]csv[.]gz' MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    INCLUDE_METADATA = (SRC_FILE = METADATA$FILENAME, LOADED_AT = METADATA$START_SCAN_TIME) ON_ERROR = SKIP_FILE;
  COPY INTO RAW.COURIERS FROM @RAW.EXTRACT_STAGE
    PATTERN = '.*couriers[.]csv[.]gz' MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    INCLUDE_METADATA = (SRC_FILE = METADATA$FILENAME, LOADED_AT = METADATA$START_SCAN_TIME) ON_ERROR = SKIP_FILE;
  COPY INTO RAW.ORDERS FROM @RAW.EXTRACT_STAGE
    PATTERN = '.*/orders[.]csv[.]gz' MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    INCLUDE_METADATA = (SRC_FILE = METADATA$FILENAME, LOADED_AT = METADATA$START_SCAN_TIME) ON_ERROR = SKIP_FILE;
  COPY INTO RAW.ORDER_ITEMS FROM @RAW.EXTRACT_STAGE
    PATTERN = '.*order_items[.]csv[.]gz' MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    INCLUDE_METADATA = (SRC_FILE = METADATA$FILENAME, LOADED_AT = METADATA$START_SCAN_TIME) ON_ERROR = SKIP_FILE;

  INSERT INTO OPS.RUN_LOG
  SELECT CURRENT_TIMESTAMP(), SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'), 'LOAD_RAW', NULL, 'copy finished';
END;
$$;

-- The graph version does not include the procedure body: changing SP_BUILD_CORE takes effect on the next call.
CREATE OR REPLACE TASK PIPE.BUILD_CORE
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  COMMENT = 'Dimensions and facts from the RAW streams, one transaction'
  AFTER PIPE.LOAD_RAW
AS
EXECUTE IMMEDIATE $$
DECLARE
  run_id STRING;
BEGIN
  run_id := (SELECT SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'));
  CALL CORE.SP_BUILD_CORE(:run_id);
END;
$$;

CREATE OR REPLACE TASK PIPE.FINALIZE_RUN
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  COMMENT = 'Model integrity checks after every graph run'
  FINALIZE = PIPE.LOAD_RAW
AS
  INSERT INTO OPS.RUN_LOG
  SELECT CURRENT_TIMESTAMP(), SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'), 'FINALIZE_RUN',
         (SELECT SUM(FAILURES) FROM OPS.V_MODEL_CHECKS), 'model check failures';

SELECT SYSTEM$TASK_DEPENDENTS_ENABLE('P06_FOOD.PIPE.LOAD_RAW');
SHOW TASKS IN SCHEMA PIPE;
