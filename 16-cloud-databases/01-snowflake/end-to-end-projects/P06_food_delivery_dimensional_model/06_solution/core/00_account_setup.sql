-- P06 account-level setup. Run once as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS P06_OWNER;
CREATE ROLE IF NOT EXISTS P06_READER;
GRANT ROLE P06_READER TO ROLE P06_OWNER;
GRANT ROLE P06_OWNER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P06_OWNER TO USER IDENTIFIER($my_user);
GRANT ROLE P06_READER TO USER IDENTIFIER($my_user);

CREATE RESOURCE MONITOR IF NOT EXISTS P06_RM
  WITH CREDIT_QUOTA = 3
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS P06_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 900
  RESOURCE_MONITOR = P06_RM
  COMMENT = 'P06 dynamic table refreshes, dashboards, ad hoc';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P06_WH TO ROLE P06_OWNER;
GRANT USAGE ON WAREHOUSE P06_WH TO ROLE P06_READER;

CREATE DATABASE IF NOT EXISTS P06_FOOD COMMENT = 'P06 food delivery dimensional model';
GRANT OWNERSHIP ON DATABASE P06_FOOD TO ROLE P06_OWNER COPY CURRENT GRANTS;

GRANT EXECUTE TASK, EXECUTE MANAGED TASK ON ACCOUNT TO ROLE P06_OWNER;
