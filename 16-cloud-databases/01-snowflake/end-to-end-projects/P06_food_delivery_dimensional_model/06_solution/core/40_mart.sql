-- P06 mart: analyst views and a dynamic table for daily KPIs. Run as P06_OWNER after the first graph run.

USE ROLE P06_OWNER;
USE WAREHOUSE P06_WH;
USE DATABASE P06_FOOD;

-- One wide row per order with the dimension versions that were valid when it was placed.
CREATE OR REPLACE VIEW MART.V_ORDER AS
SELECT
  f.ORDER_ID, d.CALENDAR_DATE AS ORDER_DATE, d.DAY_NAME, d.IS_WEEKEND,
  f.STATUS, f.PLACED_AT, f.DELIVERED_AT, f.MINUTES_TO_DELIVER,
  f.ITEMS_AMOUNT, f.DELIVERY_FEE, f.TIP, f.TOTAL_AMOUNT,
  c.CUSTOMER_ID, c.CITY AS CUSTOMER_CITY, c.LOYALTY_TIER AS LOYALTY_TIER_AT_ORDER, c.IS_INFERRED AS CUSTOMER_WAS_INFERRED,
  r.RESTAURANT_ID, r.NAME AS RESTAURANT_NAME, r.CITY AS RESTAURANT_CITY, r.CUISINE AS CUISINE_AT_ORDER,
  r.PRICE_TIER AS PRICE_TIER_AT_ORDER,
  k.COURIER_ID, k.VEHICLE AS COURIER_VEHICLE_NOW
FROM CORE.FACT_ORDER f
JOIN CORE.DIM_DATE d       ON d.DATE_KEY = f.ORDER_DATE_KEY
JOIN CORE.DIM_CUSTOMER c   ON c.CUSTOMER_SK = f.CUSTOMER_SK
JOIN CORE.DIM_RESTAURANT r ON r.RESTAURANT_SK = f.RESTAURANT_SK
JOIN CORE.DIM_COURIER k    ON k.COURIER_SK = f.COURIER_SK;

-- The SCD2 question in one view: revenue by loyalty tier as it was at order time versus as it is today.
CREATE OR REPLACE VIEW MART.V_REVENUE_BY_TIER AS
SELECT
  f.ORDER_DATE_KEY,
  c_then.LOYALTY_TIER AS TIER_AT_ORDER,
  c_now.LOYALTY_TIER  AS TIER_TODAY,
  COUNT(*)            AS ORDERS,
  SUM(f.TOTAL_AMOUNT) AS REVENUE
FROM CORE.FACT_ORDER f
JOIN CORE.DIM_CUSTOMER c_then ON c_then.CUSTOMER_SK = f.CUSTOMER_SK
JOIN CORE.DIM_CUSTOMER c_now  ON c_now.CUSTOMER_ID = c_then.CUSTOMER_ID AND c_now.IS_CURRENT
WHERE f.STATUS = 'delivered'
GROUP BY 1, 2, 3;

CREATE OR REPLACE DYNAMIC TABLE MART.DT_DAILY_KPI
  TARGET_LAG = '1 hour'
  WAREHOUSE = P06_WH
  REFRESH_MODE = INCREMENTAL
  COMMENT = 'Daily KPIs per restaurant city and cuisine at order time'
AS
SELECT
  f.ORDER_DATE_KEY,
  r.CITY                               AS RESTAURANT_CITY,
  r.CUISINE                            AS CUISINE_AT_ORDER,
  COUNT(*)                             AS ORDERS,
  COUNT_IF(f.STATUS = 'delivered')     AS DELIVERED,
  COUNT_IF(f.STATUS = 'cancelled')     AS CANCELLED,
  SUM(IFF(f.STATUS = 'delivered', f.TOTAL_AMOUNT, 0)) AS GMV,
  AVG(f.MINUTES_TO_DELIVER)            AS AVG_MINUTES_TO_DELIVER
FROM CORE.FACT_ORDER f
JOIN CORE.DIM_RESTAURANT r ON r.RESTAURANT_SK = f.RESTAURANT_SK
GROUP BY 1, 2, 3;

GRANT SELECT ON VIEW MART.V_ORDER TO ROLE P06_READER;
GRANT SELECT ON VIEW MART.V_REVENUE_BY_TIER TO ROLE P06_READER;
GRANT SELECT ON DYNAMIC TABLE MART.DT_DAILY_KPI TO ROLE P06_READER;

-- Dashboard tiles (Snowsight, as P06_READER).
-- 1. Orders and GMV per day
SELECT ORDER_DATE_KEY, SUM(ORDERS) AS ORDERS, SUM(GMV) AS GMV FROM MART.DT_DAILY_KPI GROUP BY 1 ORDER BY 1;
-- 2. Delivery time by city
SELECT RESTAURANT_CITY, ROUND(AVG(AVG_MINUTES_TO_DELIVER), 1) AS AVG_MINUTES FROM MART.DT_DAILY_KPI GROUP BY 1 ORDER BY 2;
-- 3. Cancellation rate by cuisine
SELECT CUISINE_AT_ORDER, ROUND(100 * SUM(CANCELLED) / SUM(ORDERS), 2) AS CANCEL_PCT FROM MART.DT_DAILY_KPI GROUP BY 1 ORDER BY 2 DESC;
-- 4. As-was versus as-is: revenue that moved tier
SELECT TIER_AT_ORDER, TIER_TODAY, SUM(REVENUE) AS REVENUE FROM MART.V_REVENUE_BY_TIER WHERE TIER_AT_ORDER <> TIER_TODAY GROUP BY 1, 2;
