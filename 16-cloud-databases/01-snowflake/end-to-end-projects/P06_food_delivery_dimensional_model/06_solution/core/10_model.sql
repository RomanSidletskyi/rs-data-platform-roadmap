-- Model integrity rules. Every FAILURES value must be 0; the finalizer logs the total after each run.
CREATE OR REPLACE VIEW OPS.V_MODEL_CHECKS AS
WITH cust AS (
  SELECT *, LEAD(VALID_FROM) OVER (PARTITION BY CUSTOMER_ID ORDER BY VALID_FROM) AS NEXT_FROM
  FROM CORE.DIM_CUSTOMER WHERE CUSTOMER_SK > 0
),
rest AS (
  SELECT *, LEAD(VALID_FROM) OVER (PARTITION BY RESTAURANT_ID ORDER BY VALID_FROM) AS NEXT_FROM
  FROM CORE.DIM_RESTAURANT WHERE RESTAURANT_SK > 0
),
raw_orders AS (
  SELECT ORDER_ID, STATUS FROM RAW.ORDERS
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_ID ORDER BY UPDATED_AT DESC) = 1
)
SELECT 'customer_not_exactly_one_current' AS CHECK_NAME, COUNT(*) AS FAILURES
FROM (SELECT CUSTOMER_ID FROM cust GROUP BY 1 HAVING COUNT_IF(IS_CURRENT) <> 1)
UNION ALL
SELECT 'customer_version_gap_or_overlap', COUNT(*) FROM cust WHERE NEXT_FROM IS NOT NULL AND VALID_TO <> NEXT_FROM
UNION ALL
SELECT 'customer_open_version_not_last', COUNT(*) FROM cust WHERE NEXT_FROM IS NOT NULL AND (IS_CURRENT OR VALID_TO = '9999-12-31')
UNION ALL
SELECT 'restaurant_not_exactly_one_current', COUNT(*)
FROM (SELECT RESTAURANT_ID FROM rest GROUP BY 1 HAVING COUNT_IF(IS_CURRENT) <> 1)
UNION ALL
SELECT 'restaurant_version_gap_or_overlap', COUNT(*) FROM rest WHERE NEXT_FROM IS NOT NULL AND VALID_TO <> NEXT_FROM
UNION ALL
SELECT 'inferred_customer_with_arrived_record', COUNT(*)
FROM cust c WHERE c.IS_INFERRED AND EXISTS (SELECT 1 FROM RAW.CUSTOMERS r WHERE r.CUSTOMER_ID = c.CUSTOMER_ID)
UNION ALL
SELECT 'fact_order_unknown_customer_or_restaurant', COUNT(*)
FROM CORE.FACT_ORDER WHERE CUSTOMER_SK = -1 OR RESTAURANT_SK = -1
UNION ALL
SELECT 'fact_order_missing_or_extra', ABS((SELECT COUNT(*) FROM raw_orders) - (SELECT COUNT(*) FROM CORE.FACT_ORDER))
UNION ALL
SELECT 'fact_order_status_differs_from_source', COUNT(*)
FROM CORE.FACT_ORDER f JOIN raw_orders r ON r.ORDER_ID = f.ORDER_ID WHERE f.STATUS <> r.STATUS
UNION ALL
SELECT 'fact_order_duplicate', COUNT(*)
FROM (SELECT ORDER_ID FROM CORE.FACT_ORDER GROUP BY 1 HAVING COUNT(*) > 1)
UNION ALL
SELECT 'items_amount_differs_from_lines', COUNT(*)
FROM CORE.FACT_ORDER f
LEFT JOIN (SELECT ORDER_ID, SUM(LINE_AMOUNT) AS AMOUNT FROM CORE.FACT_ORDER_ITEM GROUP BY 1) l ON l.ORDER_ID = f.ORDER_ID
WHERE f.ITEMS_AMOUNT IS DISTINCT FROM COALESCE(l.AMOUNT, 0);

