  PICKED_UP_AT       TIMESTAMP_NTZ,
  DELIVERED_AT       TIMESTAMP_NTZ,
  CANCELLED_AT       TIMESTAMP_NTZ,
  MINUTES_TO_DELIVER NUMBER,
  ITEMS_AMOUNT       NUMBER(12, 2),
  DELIVERY_FEE       NUMBER(10, 2),
  TIP                NUMBER(10, 2),
  TOTAL_AMOUNT       NUMBER(12, 2),
  SOURCE_UPDATED_AT  TIMESTAMP_NTZ,
  UPDATED_AT         TIMESTAMP_LTZ
