-- P06 dimensional model: dimensions with unknown members, facts, date dimension, work tables. Run as P06_OWNER.

USE ROLE P06_OWNER;
USE WAREHOUSE P06_WH;
USE DATABASE P06_FOOD;

CREATE SEQUENCE IF NOT EXISTS CORE.SEQ_CUSTOMER;
CREATE SEQUENCE IF NOT EXISTS CORE.SEQ_RESTAURANT;
CREATE SEQUENCE IF NOT EXISTS CORE.SEQ_MENU_ITEM;
CREATE SEQUENCE IF NOT EXISTS CORE.SEQ_COURIER;

-- SCD2: CITY, LOYALTY_TIER, IS_DELETED keep history. SCD1: FULL_NAME, EMAIL are overwritten on all versions.
CREATE TABLE IF NOT EXISTS CORE.DIM_CUSTOMER (
  CUSTOMER_SK  NUMBER DEFAULT CORE.SEQ_CUSTOMER.NEXTVAL,
  CUSTOMER_ID  NUMBER,
  FULL_NAME    STRING,
  EMAIL        STRING,
  CITY         STRING,
  LOYALTY_TIER STRING,
  SIGNUP_DATE  DATE,
  IS_DELETED   BOOLEAN,
  ATTR_HASH    NUMBER,
  VALID_FROM   TIMESTAMP_NTZ,
  VALID_TO     TIMESTAMP_NTZ,
  IS_CURRENT   BOOLEAN,
  IS_INFERRED  BOOLEAN,
  LOADED_AT    TIMESTAMP_LTZ
);

-- SCD2: CITY, CUISINE, PRICE_TIER, IS_ACTIVE. SCD1: NAME, RATING.
CREATE TABLE IF NOT EXISTS CORE.DIM_RESTAURANT (
  RESTAURANT_SK NUMBER DEFAULT CORE.SEQ_RESTAURANT.NEXTVAL,
  RESTAURANT_ID NUMBER,
  NAME          STRING,
  RATING        NUMBER(3, 1),
  CITY          STRING,
  CUISINE       STRING,
  PRICE_TIER    NUMBER,
  IS_ACTIVE     BOOLEAN,
  ATTR_HASH     NUMBER,
  VALID_FROM    TIMESTAMP_NTZ,
  VALID_TO      TIMESTAMP_NTZ,
  IS_CURRENT    BOOLEAN,
  IS_INFERRED   BOOLEAN,
  LOADED_AT     TIMESTAMP_LTZ
);

-- SCD1: the price paid lives on the order line, so the menu only needs its current state.
CREATE TABLE IF NOT EXISTS CORE.DIM_MENU_ITEM (
  ITEM_SK       NUMBER DEFAULT CORE.SEQ_MENU_ITEM.NEXTVAL,
  ITEM_ID       NUMBER,
  RESTAURANT_ID NUMBER,
  NAME          STRING,
  CATEGORY      STRING,
  CURRENT_PRICE NUMBER(10, 2),
  IS_AVAILABLE  BOOLEAN,
  UPDATED_AT    TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS CORE.DIM_COURIER (
  COURIER_SK NUMBER DEFAULT CORE.SEQ_COURIER.NEXTVAL,
  COURIER_ID NUMBER,
  NAME       STRING,
  CITY       STRING,
  VEHICLE    STRING,
  UPDATED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS CORE.DIM_DATE AS
SELECT
  TO_NUMBER(TO_CHAR(d, 'YYYYMMDD')) AS DATE_KEY,
  d                                  AS CALENDAR_DATE,
  YEAR(d)                            AS YEAR,
  MONTH(d)                           AS MONTH,
  DAYNAME(d)                         AS DAY_NAME,
  DAYOFWEEKISO(d) IN (6, 7)          AS IS_WEEKEND
FROM (
  SELECT DATEADD(day, SEQ4(), '2024-01-01'::DATE) AS d
  FROM TABLE(GENERATOR(ROWCOUNT => 1096))
);

-- Unknown members: facts point here instead of NULL when a key cannot be resolved.
INSERT INTO CORE.DIM_CUSTOMER (CUSTOMER_SK, CUSTOMER_ID, FULL_NAME, CITY, LOYALTY_TIER, IS_DELETED, VALID_FROM, VALID_TO, IS_CURRENT, IS_INFERRED)
SELECT -1, NULL, 'Unknown', 'Unknown', 'Unknown', FALSE, '1900-01-01', '9999-12-31', TRUE, FALSE
WHERE NOT EXISTS (SELECT 1 FROM CORE.DIM_CUSTOMER WHERE CUSTOMER_SK = -1);
INSERT INTO CORE.DIM_RESTAURANT (RESTAURANT_SK, RESTAURANT_ID, NAME, CITY, CUISINE, IS_ACTIVE, VALID_FROM, VALID_TO, IS_CURRENT, IS_INFERRED)
SELECT -1, NULL, 'Unknown', 'Unknown', 'Unknown', FALSE, '1900-01-01', '9999-12-31', TRUE, FALSE
WHERE NOT EXISTS (SELECT 1 FROM CORE.DIM_RESTAURANT WHERE RESTAURANT_SK = -1);
INSERT INTO CORE.DIM_MENU_ITEM (ITEM_SK, ITEM_ID, NAME, CATEGORY)
SELECT -1, NULL, 'Unknown', 'Unknown'
WHERE NOT EXISTS (SELECT 1 FROM CORE.DIM_MENU_ITEM WHERE ITEM_SK = -1);
INSERT INTO CORE.DIM_COURIER (COURIER_SK, COURIER_ID, NAME, CITY, VEHICLE)
SELECT -1, NULL, 'Unknown', 'Unknown', 'Unknown'
WHERE NOT EXISTS (SELECT 1 FROM CORE.DIM_COURIER WHERE COURIER_SK = -1);

-- Accumulating snapshot: one row per order, milestones filled in as later extracts arrive.
-- Dimension keys are resolved once, as of PLACED_AT, and never change afterwards.
