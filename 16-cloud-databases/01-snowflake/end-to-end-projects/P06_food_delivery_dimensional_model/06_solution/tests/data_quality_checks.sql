-- P06 checks. Run as P06_OWNER after any graph run.

USE ROLE P06_OWNER;
USE WAREHOUSE P06_WH;
USE DATABASE P06_FOOD;

SELECT CHECK_NAME, FAILURES, IFF(FAILURES = 0, 'PASS', 'FAIL') AS RESULT
FROM OPS.V_MODEL_CHECKS
ORDER BY RESULT, CHECK_NAME;

-- Not pass or fail, but read it: how much history the model holds, and how many members are still inferred.
SELECT 'customers' AS DIM, COUNT(DISTINCT CUSTOMER_ID) AS KEYS, COUNT(*) AS VERSIONS,
       COUNT_IF(IS_INFERRED) AS STILL_INFERRED
FROM CORE.DIM_CUSTOMER WHERE CUSTOMER_SK > 0
UNION ALL
SELECT 'restaurants', COUNT(DISTINCT RESTAURANT_ID), COUNT(*), COUNT_IF(IS_INFERRED)
FROM CORE.DIM_RESTAURANT WHERE RESTAURANT_SK > 0;

-- Per run: versions created, late changes skipped, inferred customers created.
SELECT RUN_AT, NOTE FROM OPS.RUN_LOG WHERE STEP = 'BUILD_CORE' ORDER BY RUN_AT DESC LIMIT 20;
