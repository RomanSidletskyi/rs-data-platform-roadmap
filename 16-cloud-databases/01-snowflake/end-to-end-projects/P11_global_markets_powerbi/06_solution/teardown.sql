-- P11 teardown. Run as ACCOUNTADMIN. Cloud resources are separate:
--   az group delete --name "$P11_RG", or the clean-up commands listed in aws/01_provision.sh.

USE ROLE ACCOUNTADMIN;

DROP DATABASE IF EXISTS P11_MARKETS;
DROP USER IF EXISTS P11_POWERBI_SVC;
DROP INTEGRATION IF EXISTS P11_AZURE_STORAGE_INT;
DROP INTEGRATION IF EXISTS P11_AZURE_QUEUE_INT;
DROP INTEGRATION IF EXISTS P11_AWS_STORAGE_INT;
DROP WAREHOUSE IF EXISTS P11_WH;
DROP WAREHOUSE IF EXISTS P11_BI_WH;
DROP RESOURCE MONITOR IF EXISTS P11_RM;
DROP ROLE IF EXISTS P11_BI_READER;
DROP ROLE IF EXISTS P11_OWNER;

SHOW USERS LIKE 'P11_%';
SHOW INTEGRATIONS LIKE 'P11_%';
