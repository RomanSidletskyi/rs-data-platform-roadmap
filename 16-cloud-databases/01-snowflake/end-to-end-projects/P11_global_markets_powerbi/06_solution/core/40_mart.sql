-- P11 consumer layer: a star of views over CORE for Power BI. Run as P11_OWNER after the first build.
-- Views run with the owner's rights, so P11_BI_READER needs SELECT on MART only, never on CORE or RAW.

USE ROLE P11_OWNER;
USE WAREHOUSE P11_WH;
USE DATABASE P11_MARKETS;

-- Grain: one comparable price per month, market, commodity, price type, and unit.
CREATE OR REPLACE VIEW MART.FACT_FOOD_PRICE
  COMMENT = 'Monthly WFP prices per kg or litre in local currency, USD, and EUR; comparable units only, since 2015'
AS
SELECT
  COUNTRY_ISO3 || '|' || MONTH || '|' || MARKET_ID || '|' || COMMODITY_ID || '|' || PRICE_TYPE || '|' || UNIT AS PRICE_KEY,
  TO_DATE(MONTH || '-01') AS MONTH_START,
  COUNTRY_ISO3,
  MARKET_ID,
  COMMODITY_ID,
  PRICE_TYPE,
  PRICE_FLAG,
  UNIT,
  BASE_UNIT,
  CURRENCY,
  PRICE_LOCAL_PER_BASE,
  PRICE_USD_PER_BASE,
  PRICE_EUR_PER_BASE,
  FX_SOURCE
FROM CORE.FOOD_PRICE
WHERE IS_COMPARABLE
  AND PRICE_USD_PER_BASE IS NOT NULL
  AND MONTH >= '2015-01';

CREATE OR REPLACE VIEW MART.DIM_COUNTRY AS
SELECT
  p.COUNTRY_ISO3,
  COALESCE(MAX(c.COUNTRY_NAME), p.COUNTRY_ISO3) AS COUNTRY_NAME,
  MAX(p.CURRENCY)                                AS CURRENCY,
  BOOLOR_AGG(p.FX_SOURCE = 'ECB')                AS HAS_ECB_RATE
FROM CORE.FOOD_PRICE p
LEFT JOIN CORE.COUNTRY_YEAR c ON c.COUNTRY_ISO3 = p.COUNTRY_ISO3
GROUP BY p.COUNTRY_ISO3;

-- WFP renames markets and commodities over time; the latest name wins, the id stays.
CREATE OR REPLACE VIEW MART.DIM_MARKET AS
SELECT MARKET_ID, MARKET, ADMIN1, COUNTRY_ISO3, LATITUDE, LONGITUDE
FROM CORE.FOOD_PRICE
QUALIFY ROW_NUMBER() OVER (PARTITION BY MARKET_ID ORDER BY MONTH DESC) = 1;

CREATE OR REPLACE VIEW MART.DIM_COMMODITY AS
SELECT COMMODITY_ID, COMMODITY, CATEGORY
FROM CORE.FOOD_PRICE
QUALIFY ROW_NUMBER() OVER (PARTITION BY COMMODITY_ID ORDER BY MONTH DESC) = 1;

CREATE OR REPLACE VIEW MART.DIM_MONTH AS
WITH bounds AS (SELECT MIN(MONTH_START) AS FIRST_MONTH, MAX(MONTH_START) AS LAST_MONTH FROM MART.FACT_FOOD_PRICE),
months AS (
  SELECT DATEADD(month, ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1, b.FIRST_MONTH) AS MONTH_START, b.LAST_MONTH
  FROM bounds b, TABLE(GENERATOR(ROWCOUNT => 1200))
)
SELECT MONTH_START, YEAR(MONTH_START) AS YEAR, MONTH(MONTH_START) AS MONTH_NUMBER, TO_CHAR(MONTH_START, 'YYYY-MM') AS MONTH_LABEL
FROM months
WHERE MONTH_START <= LAST_MONTH;

CREATE OR REPLACE VIEW MART.FACT_COUNTRY_YEAR AS
SELECT COUNTRY_ISO3, YEAR, CPI_INDEX_2010, CPI_INFLATION_PCT, GDP_PER_CAPITA_USD, POPULATION, OFFICIAL_LCU_PER_USD
FROM CORE.COUNTRY_YEAR
WHERE COUNTRY_ISO3 IN (SELECT COUNTRY_ISO3 FROM MART.DIM_COUNTRY);

-- Shared year dimension: monthly prices and yearly indicators meet here, not through each other.
CREATE OR REPLACE VIEW MART.DIM_YEAR AS
SELECT DISTINCT YEAR FROM MART.DIM_MONTH
UNION
SELECT DISTINCT YEAR FROM MART.FACT_COUNTRY_YEAR;

-- Food prices against general inflation: did staples get more expensive than everything else?
-- Median across markets: if the set of reporting markets changes, the median moves too (composition effect).
CREATE OR REPLACE VIEW MART.FOOD_VS_CPI_YEARLY AS
WITH yearly AS (
  SELECT COUNTRY_ISO3, COMMODITY_ID, PRICE_TYPE, BASE_UNIT, YEAR(MONTH_START) AS YEAR,
         MEDIAN(PRICE_LOCAL_PER_BASE) AS MEDIAN_LOCAL_PER_BASE,
         COUNT(DISTINCT MONTH_START)  AS MONTHS_OBSERVED,
         COUNT(DISTINCT MARKET_ID)    AS MARKETS_OBSERVED
  FROM MART.FACT_FOOD_PRICE
  GROUP BY COUNTRY_ISO3, COMMODITY_ID, PRICE_TYPE, BASE_UNIT, YEAR(MONTH_START)
  HAVING COUNT(DISTINCT MONTH_START) >= 6
),
with_previous AS (
  SELECT y.*,
         LAG(YEAR) OVER (PARTITION BY COUNTRY_ISO3, COMMODITY_ID, PRICE_TYPE, BASE_UNIT ORDER BY YEAR) AS PREVIOUS_YEAR,
         LAG(MEDIAN_LOCAL_PER_BASE) OVER (PARTITION BY COUNTRY_ISO3, COMMODITY_ID, PRICE_TYPE, BASE_UNIT ORDER BY YEAR) AS PREVIOUS_MEDIAN
  FROM yearly y
)
SELECT
  w.COUNTRY_ISO3, w.COMMODITY_ID, w.PRICE_TYPE, w.BASE_UNIT, w.YEAR,
  w.MEDIAN_LOCAL_PER_BASE, w.MONTHS_OBSERVED, w.MARKETS_OBSERVED,
  IFF(w.PREVIOUS_YEAR = w.YEAR - 1, 100 * (w.MEDIAN_LOCAL_PER_BASE / w.PREVIOUS_MEDIAN - 1), NULL) AS FOOD_PRICE_YOY_PCT,
  c.CPI_INFLATION_PCT,
  FOOD_PRICE_YOY_PCT - c.CPI_INFLATION_PCT AS REAL_FOOD_PRICE_GAP_PP
FROM with_previous w
LEFT JOIN CORE.COUNTRY_YEAR c ON c.COUNTRY_ISO3 = w.COUNTRY_ISO3 AND c.YEAR = w.YEAR;

