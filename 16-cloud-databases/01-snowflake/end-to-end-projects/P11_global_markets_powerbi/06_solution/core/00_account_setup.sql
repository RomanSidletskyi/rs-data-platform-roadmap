-- P11 account-level setup. Run once as ACCOUNTADMIN through run_sql.sh, which fills <powerbi-public-key>.
--   P11_OWNER      owns the database, pipes, procedure, task, semantic view
--   P11_BI_READER  what Power BI uses: read MART views and the semantic view, on its own warehouse

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS P11_OWNER;
CREATE ROLE IF NOT EXISTS P11_BI_READER;
GRANT ROLE P11_BI_READER TO ROLE P11_OWNER;
GRANT ROLE P11_OWNER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P11_OWNER TO USER IDENTIFIER($my_user);

-- One monitor for both warehouses: the budget is the project's, not the pipeline's.
CREATE RESOURCE MONITOR IF NOT EXISTS P11_RM
  WITH CREDIT_QUOTA = 3
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS P11_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800 RESOURCE_MONITOR = P11_RM
  COMMENT = 'P11 loads and the Snowpark build';

-- A separate warehouse makes BI cost visible on its own line and lets you size it independently.
CREATE WAREHOUSE IF NOT EXISTS P11_BI_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 600 RESOURCE_MONITOR = P11_RM
  COMMENT = 'P11 Power BI refreshes and queries';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P11_WH TO ROLE P11_OWNER;
GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P11_BI_WH TO ROLE P11_OWNER;
GRANT USAGE ON WAREHOUSE P11_BI_WH TO ROLE P11_BI_READER;

CREATE DATABASE IF NOT EXISTS P11_MARKETS COMMENT = 'P11 global food prices, FX, and indicators for Power BI';
GRANT OWNERSHIP ON DATABASE P11_MARKETS TO ROLE P11_OWNER COPY CURRENT GRANTS;

GRANT EXECUTE TASK ON ACCOUNT TO ROLE P11_OWNER;

-- Power BI signs in with a key pair (connector implementation 2.0). No password, one role, one warehouse.
-- DEFAULT_NAMESPACE avoids "object does not exist" errors from the connector's metadata queries.
CREATE USER IF NOT EXISTS P11_POWERBI_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = P11_BI_READER
  DEFAULT_WAREHOUSE = P11_BI_WH
  DEFAULT_NAMESPACE = 'P11_MARKETS.MART'
  RSA_PUBLIC_KEY = '<powerbi-public-key>'
  COMMENT = 'P11 Power BI semantic model refresh';
ALTER USER P11_POWERBI_SVC SET RSA_PUBLIC_KEY = '<powerbi-public-key>';
GRANT ROLE P11_BI_READER TO USER P11_POWERBI_SVC;
