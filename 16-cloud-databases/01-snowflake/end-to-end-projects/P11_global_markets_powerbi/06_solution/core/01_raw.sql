-- P11 schemas, raw layer, streams, and parsing views. Run as P11_OWNER after 00_account_setup.sql.
-- The landing stage starts internal; azure/11 or aws/11 replace it with an external stage of the same name.

USE ROLE P11_OWNER;
USE WAREHOUSE P11_WH;
USE DATABASE P11_MARKETS;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS CORE;
CREATE SCHEMA IF NOT EXISTS MART;
CREATE SCHEMA IF NOT EXISTS SEM;
CREATE SCHEMA IF NOT EXISTS OPS;

-- Columns are matched by header name, so a reordered or extended source file still loads correctly.
CREATE FILE FORMAT IF NOT EXISTS RAW.FF_CSV_HEADER
  TYPE = CSV PARSE_HEADER = TRUE FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE EMPTY_FIELD_AS_NULL = TRUE;
-- World Bank answers [metadata, rows]: stripping the outer array yields one metadata row and one array row.
CREATE FILE FORMAT IF NOT EXISTS RAW.FF_JSON_ARRAY TYPE = JSON STRIP_OUTER_ARRAY = TRUE;

CREATE STAGE IF NOT EXISTS RAW.LANDING_STAGE COMMENT = 'wfp/, ecb/, worldbank/ under the landing root markets/';
CREATE STAGE IF NOT EXISTS OPS.CODE_STAGE COMMENT = 'markets_pipeline.zip for the Snowpark procedure';

-- RAW keeps every file version as delivered: strings, file name, row number, file time, load time.
CREATE TABLE IF NOT EXISTS RAW.WFP_PRICE_RAW (
  DATE STRING, ADMIN1 STRING, ADMIN2 STRING, MARKET STRING, MARKET_ID STRING, LATITUDE STRING, LONGITUDE STRING,
  CATEGORY STRING, COMMODITY STRING, COMMODITY_ID STRING, UNIT STRING, PRICEFLAG STRING, PRICETYPE STRING,
  CURRENCY STRING, PRICE STRING, USDPRICE STRING,
  SRC_FILE STRING, SRC_ROW NUMBER, FILE_LAST_MODIFIED TIMESTAMP_LTZ, LOADED_AT TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS RAW.ECB_FX_RAW (
  KEY STRING, FREQ STRING, CURRENCY STRING, CURRENCY_DENOM STRING, EXR_TYPE STRING, EXR_SUFFIX STRING,
  TIME_PERIOD STRING, OBS_VALUE STRING,
  SRC_FILE STRING, SRC_ROW NUMBER, FILE_LAST_MODIFIED TIMESTAMP_LTZ, LOADED_AT TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS RAW.WB_INDICATOR_RAW (
  V VARIANT, SRC_FILE STRING, FILE_LAST_MODIFIED TIMESTAMP_LTZ, LOADED_AT TIMESTAMP_LTZ
);

-- Streams only signal "new files arrived" to the task; the build itself reads the latest snapshot.
CREATE STREAM IF NOT EXISTS RAW.WFP_STREAM ON TABLE RAW.WFP_PRICE_RAW APPEND_ONLY = TRUE;
CREATE STREAM IF NOT EXISTS RAW.ECB_STREAM ON TABLE RAW.ECB_FX_RAW APPEND_ONLY = TRUE;
CREATE STREAM IF NOT EXISTS RAW.WB_STREAM ON TABLE RAW.WB_INDICATOR_RAW APPEND_ONLY = TRUE;

-- The path carries the country and the source version; the CSV does not.
CREATE OR REPLACE VIEW RAW.WFP_PRICE_V AS
SELECT
  r.*,
  REGEXP_SUBSTR(r.SRC_FILE, 'country=([A-Z]{3})', 1, 1, 'e')  AS COUNTRY_ISO3,
  REGEXP_SUBSTR(r.SRC_FILE, 'version=([0-9T]+)', 1, 1, 'e')   AS SOURCE_VERSION
FROM RAW.WFP_PRICE_RAW r;

-- Each WFP file is a full history of one country: the newest version replaces all older ones.
-- Exactly one file wins, even if the same version was loaded twice (internal stage first, cloud stage later).
CREATE OR REPLACE VIEW RAW.WFP_PRICE_LATEST_V AS
SELECT *
FROM RAW.WFP_PRICE_V
QUALIFY DENSE_RANK() OVER (PARTITION BY COUNTRY_ISO3 ORDER BY SOURCE_VERSION DESC, FILE_LAST_MODIFIED DESC, SRC_FILE DESC) = 1;

-- ECB files are full series snapshots too: use the newest file.
CREATE OR REPLACE VIEW RAW.ECB_FX_V AS
SELECT CURRENCY, TIME_PERIOD AS MONTH, TRY_TO_DOUBLE(OBS_VALUE) AS UNITS_PER_EUR, SRC_FILE
FROM RAW.ECB_FX_RAW
WHERE FREQ = 'M' AND CURRENCY_DENOM = 'EUR'
QUALIFY DENSE_RANK() OVER (ORDER BY FILE_LAST_MODIFIED DESC, SRC_FILE DESC) = 1;

CREATE OR REPLACE VIEW RAW.WB_INDICATOR_V AS
SELECT
  r.INDICATOR_ID,
  f.value:countryiso3code::STRING AS COUNTRY_ISO3,
  f.value:country:value::STRING   AS COUNTRY_NAME,
  f.value:date::NUMBER            AS YEAR,
  f.value:value::FLOAT            AS VALUE
FROM (
  SELECT V, SRC_FILE, REGEXP_SUBSTR(SRC_FILE, 'indicator=([A-Z0-9.]+)/', 1, 1, 'e') AS INDICATOR_ID
  FROM RAW.WB_INDICATOR_RAW
  WHERE IS_ARRAY(V)
  QUALIFY DENSE_RANK() OVER (PARTITION BY INDICATOR_ID ORDER BY FILE_LAST_MODIFIED DESC, SRC_FILE DESC) = 1
) r,
LATERAL FLATTEN(input => r.V) f;

CREATE TABLE IF NOT EXISTS OPS.ARRIVALS (
  SOURCE STRING, SRC_FILE STRING, ROWS_LOADED NUMBER, RECORDED_AT TIMESTAMP_LTZ
);
CREATE TABLE IF NOT EXISTS OPS.BUILD_LOG (BUILT_AT TIMESTAMP_LTZ, DETAILS VARIANT);
