-- P11 data quality checks. Run as P11_OWNER after a build.
-- The questions a person asks when a dashboard number looks wrong, in the order they usually ask them.

USE ROLE P11_OWNER;
USE WAREHOUSE P11_WH;
USE DATABASE P11_MARKETS;

-- 1. What arrived, and which version is live per country (expect one live version per configured country).
SELECT COUNTRY_ISO3, COUNT(DISTINCT SOURCE_VERSION) AS VERSIONS_LOADED, MAX(SOURCE_VERSION) AS LIVE_VERSION, COUNT(*) AS RAW_ROWS
FROM RAW.WFP_PRICE_V
GROUP BY COUNTRY_ISO3
ORDER BY COUNTRY_ISO3;

-- 2. Load errors in the last 7 days (expect none with LOAD_FAILED or PARTIALLY_LOADED).
SELECT TABLE_NAME, FILE_NAME, STATUS, ROW_COUNT, FIRST_ERROR_MESSAGE, LAST_LOAD_TIME
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'RAW.WFP_PRICE_RAW', START_TIME => DATEADD(day, -7, CURRENT_TIMESTAMP())))
WHERE STATUS <> 'Loaded'
UNION ALL
SELECT TABLE_NAME, FILE_NAME, STATUS, ROW_COUNT, FIRST_ERROR_MESSAGE, LAST_LOAD_TIME
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'RAW.ECB_FX_RAW', START_TIME => DATEADD(day, -7, CURRENT_TIMESTAMP())))
WHERE STATUS <> 'Loaded'
UNION ALL
SELECT TABLE_NAME, FILE_NAME, STATUS, ROW_COUNT, FIRST_ERROR_MESSAGE, LAST_LOAD_TIME
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'RAW.WB_INDICATOR_RAW', START_TIME => DATEADD(day, -7, CURRENT_TIMESTAMP())))
WHERE STATUS <> 'Loaded';

-- 3. Every live raw row is accounted for: in CORE, or dropped as a tag row or a non-positive price.
SELECT
  (SELECT COUNT(*) FROM RAW.WFP_PRICE_LATEST_V)                                           AS LIVE_RAW_ROWS,
  (SELECT COUNT(*) FROM CORE.FOOD_PRICE)                                                  AS CORE_ROWS,
  (SELECT COUNT_IF(STARTSWITH(DATE, '#')) FROM RAW.WFP_PRICE_LATEST_V)                    AS TAG_ROWS,
  (SELECT COUNT_IF(TRY_TO_DOUBLE(PRICE) IS NULL OR TRY_TO_DOUBLE(PRICE) <= 0)
     FROM RAW.WFP_PRICE_LATEST_V WHERE NOT STARTSWITH(DATE, '#'))                         AS UNUSABLE_PRICES,
  LIVE_RAW_ROWS - CORE_ROWS - TAG_ROWS - UNUSABLE_PRICES                                  AS UNEXPLAINED;   -- expect 0

-- 4. Units the pipeline cannot compare by weight or volume (expect only counts and services; new names need review).
SELECT u.UNIT, u.IS_COMPARABLE, COUNT(*) AS ROWS_WITH_UNIT
FROM CORE.FOOD_PRICE p
JOIN CORE.UNIT_MAP u USING (UNIT)
GROUP BY u.UNIT, u.IS_COMPARABLE
ORDER BY u.IS_COMPARABLE, ROWS_WITH_UNIT DESC;

-- 5. FX reconciliation where both ECB and WFP rates exist (expect |difference| under 2 percent).
SELECT CURRENCY, MONTH, ROUND(ECB_UNITS_PER_USD, 3) AS ECB, ROUND(WFP_UNITS_PER_USD, 3) AS WFP, ROUND(ECB_WFP_DIFF_PCT, 2) AS DIFF_PCT
FROM CORE.FX_MONTHLY
WHERE ECB_WFP_DIFF_PCT IS NOT NULL AND ABS(ECB_WFP_DIFF_PCT) >= 2
ORDER BY ABS(ECB_WFP_DIFF_PCT) DESC
LIMIT 50;

-- 6. Comparable prices without a rate (expect 0 rows: a missing rate means a month with no WFP USD prices and no ECB rate).
SELECT COUNTRY_ISO3, MONTH, COUNT(*) AS ROWS_WITHOUT_FX
FROM CORE.FOOD_PRICE
WHERE IS_COMPARABLE AND PRICE_USD_PER_BASE IS NULL
GROUP BY COUNTRY_ISO3, MONTH
ORDER BY MONTH DESC;

-- 7. Grain of the fact (expect 0 rows).
SELECT PRICE_KEY, COUNT(*) FROM MART.FACT_FOOD_PRICE GROUP BY PRICE_KEY HAVING COUNT(*) > 1 LIMIT 20;

-- 8. Plausibility: retail rice and maize in USD per kg, latest 12 months (expect roughly 0.2 to 2).
SELECT c.COUNTRY_NAME, d.COMMODITY, ROUND(MEDIAN(f.PRICE_USD_PER_BASE), 3) AS MEDIAN_USD_PER_KG, COUNT(*) AS OBSERVATIONS
FROM MART.FACT_FOOD_PRICE f
JOIN MART.DIM_COUNTRY c USING (COUNTRY_ISO3)
JOIN MART.DIM_COMMODITY d USING (COMMODITY_ID)
WHERE f.PRICE_TYPE = 'Retail' AND f.BASE_UNIT = 'KG'
  AND (d.COMMODITY ILIKE 'rice%' OR d.COMMODITY ILIKE 'maize%')
  AND f.MONTH_START >= DATEADD(month, -12, (SELECT MAX(MONTH_START) FROM MART.FACT_FOOD_PRICE))
GROUP BY c.COUNTRY_NAME, d.COMMODITY
ORDER BY c.COUNTRY_NAME, d.COMMODITY;

-- 9. Metric parity: the semantic view and plain SQL must agree (expect 0 rows).
WITH semantic AS (
  SELECT * FROM SEMANTIC_VIEW(
    SEM.FOOD_PRICES
    DIMENSIONS countries.country_name, prices.price_year
    METRICS prices.median_price_usd, prices.price_observations
  )
),
direct AS (
  SELECT c.COUNTRY_NAME, YEAR(f.MONTH_START) AS PRICE_YEAR,
         MEDIAN(f.PRICE_USD_PER_BASE) AS MEDIAN_PRICE_USD, COUNT(f.PRICE_USD_PER_BASE) AS PRICE_OBSERVATIONS
  FROM MART.FACT_FOOD_PRICE f JOIN MART.DIM_COUNTRY c USING (COUNTRY_ISO3)
  GROUP BY c.COUNTRY_NAME, YEAR(f.MONTH_START)
)
SELECT d.*, s.MEDIAN_PRICE_USD AS SEMANTIC_MEDIAN, s.PRICE_OBSERVATIONS AS SEMANTIC_OBSERVATIONS
FROM direct d
FULL OUTER JOIN semantic s ON s.COUNTRY_NAME = d.COUNTRY_NAME AND s.PRICE_YEAR = d.PRICE_YEAR
WHERE s.COUNTRY_NAME IS NULL OR d.COUNTRY_NAME IS NULL
   OR ABS(s.MEDIAN_PRICE_USD - d.MEDIAN_PRICE_USD) > 1e-9 OR s.PRICE_OBSERVATIONS <> d.PRICE_OBSERVATIONS;

-- 10. Builds and their cost driver (expect one build per day with new files, none on other days).
SELECT BUILT_AT, DETAILS FROM OPS.BUILD_LOG ORDER BY BUILT_AT DESC LIMIT 10;
SELECT NAME, STATE, SCHEDULED_TIME, ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(TASK_NAME => 'BUILD_MARKETS', SCHEDULED_TIME_RANGE_START => DATEADD(day, -7, CURRENT_TIMESTAMP())))
ORDER BY SCHEDULED_TIME DESC;
