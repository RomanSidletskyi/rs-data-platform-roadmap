-- P11 Azure stage and pipes. Run as P11_OWNER via run_sql.sh after 03_grant_snowflake_access.sh.
-- The COPY bodies are the ones in core/20_load_internal.sql; keep them identical.

USE ROLE P11_OWNER;
USE WAREHOUSE P11_WH;
USE DATABASE P11_MARKETS;

CREATE OR REPLACE STAGE RAW.LANDING_STAGE
  URL = 'azure://<storage-account>.blob.core.windows.net/landing/markets/'
  STORAGE_INTEGRATION = P11_AZURE_STORAGE_INT
  COMMENT = 'wfp/, ecb/, worldbank/ written by the P11 function';

LIST @RAW.LANDING_STAGE;

CREATE PIPE IF NOT EXISTS RAW.WFP_PIPE AUTO_INGEST = TRUE INTEGRATION = 'P11_AZURE_QUEUE_INT' AS
COPY INTO RAW.WFP_PRICE_RAW
  FROM @RAW.LANDING_STAGE/wfp/
  FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_CSV_HEADER')
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
  INCLUDE_METADATA = (SRC_FILE = METADATA$FILENAME, SRC_ROW = METADATA$FILE_ROW_NUMBER,
                      FILE_LAST_MODIFIED = METADATA$FILE_LAST_MODIFIED, LOADED_AT = METADATA$START_SCAN_TIME)
  ON_ERROR = SKIP_FILE;

CREATE PIPE IF NOT EXISTS RAW.ECB_PIPE AUTO_INGEST = TRUE INTEGRATION = 'P11_AZURE_QUEUE_INT' AS
COPY INTO RAW.ECB_FX_RAW
  FROM @RAW.LANDING_STAGE/ecb/
  FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_CSV_HEADER')
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
  INCLUDE_METADATA = (SRC_FILE = METADATA$FILENAME, SRC_ROW = METADATA$FILE_ROW_NUMBER,
                      FILE_LAST_MODIFIED = METADATA$FILE_LAST_MODIFIED, LOADED_AT = METADATA$START_SCAN_TIME)
  ON_ERROR = SKIP_FILE;

CREATE PIPE IF NOT EXISTS RAW.WB_PIPE AUTO_INGEST = TRUE INTEGRATION = 'P11_AZURE_QUEUE_INT' AS
COPY INTO RAW.WB_INDICATOR_RAW (V, SRC_FILE, FILE_LAST_MODIFIED, LOADED_AT)
  FROM (SELECT $1, METADATA$FILENAME, METADATA$FILE_LAST_MODIFIED, METADATA$START_SCAN_TIME FROM @RAW.LANDING_STAGE/worldbank/)
  FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_JSON_ARRAY')
  ON_ERROR = SKIP_FILE;

-- Files that landed before the pipes existed are not in the queue: load them once (last 7 days).
ALTER PIPE RAW.WFP_PIPE REFRESH;
ALTER PIPE RAW.ECB_PIPE REFRESH;
ALTER PIPE RAW.WB_PIPE REFRESH;

SELECT SYSTEM$PIPE_STATUS('RAW.WFP_PIPE');
