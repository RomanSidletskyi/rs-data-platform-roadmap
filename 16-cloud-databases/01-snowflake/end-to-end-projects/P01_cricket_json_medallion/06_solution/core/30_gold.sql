-- P01 gold tables (filled by the task graph) and analytical views. Run as P01_OWNER.

USE ROLE P01_OWNER;
USE WAREHOUSE P01_WH;
USE DATABASE P01_CRICKET;

CREATE TABLE IF NOT EXISTS MART.DIM_PLAYER (
  PLAYER_ID    STRING,
  PLAYER_NAME  STRING,
  FIRST_MATCH  DATE,
  LAST_MATCH   DATE,
  MATCHES      NUMBER
);

CREATE TABLE IF NOT EXISTS MART.FACT_BATTING_INNINGS (
  MATCH_ID     STRING,
  MATCH_DATE   DATE,
  INNINGS_NO   NUMBER,
  BATTING_TEAM STRING,
  PLAYER_ID    STRING,
  PLAYER_NAME  STRING,
  RUNS         NUMBER,
  BALLS_FACED  NUMBER,
  FOURS        NUMBER,
  SIXES        NUMBER,
  IS_OUT       BOOLEAN,
  HOW_OUT      STRING,
  STRIKE_RATE  NUMBER(8, 2)
);

CREATE TABLE IF NOT EXISTS MART.FACT_BOWLING_INNINGS (
  MATCH_ID      STRING,
  MATCH_DATE    DATE,
  INNINGS_NO    NUMBER,
  BOWLING_TEAM  STRING,
  PLAYER_ID     STRING,
  PLAYER_NAME   STRING,
  LEGAL_BALLS   NUMBER,
  RUNS_CONCEDED NUMBER,
  WICKETS       NUMBER,
  ECONOMY       NUMBER(8, 2)
);

CREATE OR REPLACE VIEW MART.V_MATCH AS
SELECT MATCH_ID, MATCH_DATE, YEAR(MATCH_DATE) AS MATCH_YEAR, SEASON, TEAM_1, TEAM_2, VENUE, CITY, EVENT_NAME,
       TOSS_WINNER, TOSS_DECISION, WINNER, WIN_BY_RUNS, WIN_BY_WICKETS, RESULT, METHOD, PLAYER_OF_MATCH
FROM STG.MATCH;

CREATE OR REPLACE VIEW MART.V_TEAM_RESULTS AS
WITH team_matches AS (
  SELECT MATCH_ID, YEAR(MATCH_DATE) AS MATCH_YEAR, TEAM_1 AS TEAM, WINNER, RESULT FROM STG.MATCH
  UNION ALL
  SELECT MATCH_ID, YEAR(MATCH_DATE), TEAM_2, WINNER, RESULT FROM STG.MATCH
)
SELECT
  TEAM,
  MATCH_YEAR,
  COUNT(*)                                      AS MATCHES,
  COUNT_IF(WINNER = TEAM)                       AS WINS,
  COUNT_IF(WINNER IS NOT NULL AND WINNER <> TEAM) AS LOSSES,
  COUNT_IF(RESULT IN ('no result', 'tie'))      AS NO_RESULT_OR_TIE,
  ROUND(100 * DIV0(COUNT_IF(WINNER = TEAM), COUNT_IF(WINNER IS NOT NULL)), 1) AS WIN_PCT_DECIDED
FROM team_matches
GROUP BY TEAM, MATCH_YEAR;

