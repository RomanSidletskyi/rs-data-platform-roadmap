GRANT SELECT ON TABLE MART.FACT_BOWLING_INNINGS  TO ROLE P01_READER;
GRANT SELECT ON VIEW  MART.V_MATCH               TO ROLE P01_READER;
GRANT SELECT ON VIEW  MART.V_TEAM_RESULTS        TO ROLE P01_READER;
