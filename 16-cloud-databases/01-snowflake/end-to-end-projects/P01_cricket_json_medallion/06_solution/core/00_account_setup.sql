-- P01 account-level setup. Run once as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS P01_OWNER;
CREATE ROLE IF NOT EXISTS P01_READER;
GRANT ROLE P01_READER TO ROLE P01_OWNER;
GRANT ROLE P01_OWNER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P01_OWNER TO USER IDENTIFIER($my_user);
GRANT ROLE P01_READER TO USER IDENTIFIER($my_user);

CREATE RESOURCE MONITOR IF NOT EXISTS P01_RM
  WITH CREDIT_QUOTA = 3
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS P01_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 900
  RESOURCE_MONITOR = P01_RM
  COMMENT = 'P01 exploration, dashboards, ad hoc';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P01_WH TO ROLE P01_OWNER;
GRANT USAGE ON WAREHOUSE P01_WH TO ROLE P01_READER;

CREATE DATABASE IF NOT EXISTS P01_CRICKET COMMENT = 'P01 Cricsheet ODI medallion';
GRANT OWNERSHIP ON DATABASE P01_CRICKET TO ROLE P01_OWNER COPY CURRENT GRANTS;

-- The task graph is serverless; these privileges let the owner create and run it.
GRANT EXECUTE TASK, EXECUTE MANAGED TASK ON ACCOUNT TO ROLE P01_OWNER;
