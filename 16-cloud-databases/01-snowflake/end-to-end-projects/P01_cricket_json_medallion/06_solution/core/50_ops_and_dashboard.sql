-- =====================================================================
-- Dashboard tiles. Role P01_READER.
-- =====================================================================
USE ROLE P01_READER;
USE WAREHOUSE P01_WH;

-- Top run scorers per year
SELECT YEAR(MATCH_DATE) AS MATCH_YEAR, PLAYER_NAME, SUM(RUNS) AS RUNS, COUNT(*) AS INNINGS,
       ROUND(DIV0(SUM(RUNS), COUNT_IF(IS_OUT)), 2) AS AVERAGE,
       ROUND(100 * DIV0(SUM(RUNS), SUM(BALLS_FACED)), 2) AS STRIKE_RATE
FROM MART.FACT_BATTING_INNINGS
GROUP BY 1, 2
QUALIFY ROW_NUMBER() OVER (PARTITION BY MATCH_YEAR ORDER BY RUNS DESC) <= 10
ORDER BY MATCH_YEAR DESC, RUNS DESC;

-- Most economical bowlers, minimum 300 legal balls
SELECT PLAYER_NAME, SUM(LEGAL_BALLS) AS BALLS, SUM(WICKETS) AS WICKETS,
       ROUND(6 * DIV0(SUM(RUNS_CONCEDED), SUM(LEGAL_BALLS)), 2) AS ECONOMY
FROM MART.FACT_BOWLING_INNINGS
GROUP BY PLAYER_NAME
HAVING SUM(LEGAL_BALLS) >= 300
ORDER BY ECONOMY
LIMIT 20;

-- Team win rate per year
SELECT TEAM, MATCH_YEAR, MATCHES, WINS, WIN_PCT_DECIDED
FROM MART.V_TEAM_RESULTS
WHERE MATCHES >= 5
ORDER BY MATCH_YEAR DESC, WIN_PCT_DECIDED DESC;

-- Does winning the toss help? By toss decision
SELECT TOSS_DECISION,
       COUNT(*) AS MATCHES,
       ROUND(100 * DIV0(COUNT_IF(WINNER = TOSS_WINNER), COUNT_IF(WINNER IS NOT NULL)), 1) AS TOSS_WINNER_WIN_PCT
FROM MART.V_MATCH
GROUP BY TOSS_DECISION;
