USE ROLE P01_OWNER;
USE WAREHOUSE P01_WH;

-- Files on the stage that never reached RAW (for example skipped as malformed). Refresh the directory first.
CREATE OR REPLACE VIEW OPS.V_STAGE_FILES_NOT_LOADED AS
SELECT d.RELATIVE_PATH, d.SIZE, d.LAST_MODIFIED
FROM DIRECTORY(@RAW.MATCH_STAGE) d
WHERE NOT EXISTS (
  SELECT 1 FROM RAW.MATCH_RAW r
  WHERE SPLIT_PART(r.SRC_FILE, '/', -1) = SPLIT_PART(d.RELATIVE_PATH, '/', -1)
);
GRANT SELECT ON VIEW OPS.V_STAGE_FILES_NOT_LOADED TO ROLE P01_READER;

-- Start the whole graph now instead of waiting for the schedule.
-- EXECUTE TASK OPS.LOAD_RAW;

-- Graph runs: one row per run of the whole graph.
SELECT ROOT_TASK_NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, FIRST_ERROR_TASK_NAME, FIRST_ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.COMPLETE_TASK_GRAPHS(ROOT_TASK_NAME => 'LOAD_RAW'))
ORDER BY SCHEDULED_TIME DESC
LIMIT 10;

-- Individual task runs within the graph
SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(SCHEDULED_TIME_RANGE_START => DATEADD('hour', -6, CURRENT_TIMESTAMP())))
WHERE DATABASE_NAME = 'P01_CRICKET'
ORDER BY SCHEDULED_TIME DESC;

SELECT * FROM OPS.RUN_LOG ORDER BY RUN_AT DESC LIMIT 20;

-- Which files did the last COPY load or skip?
SELECT FILE_NAME, STATUS, ROW_COUNT, FIRST_ERROR_MESSAGE, LAST_LOAD_TIME
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
  TABLE_NAME => 'P01_CRICKET.RAW.MATCH_RAW',
  START_TIME => DATEADD('hour', -6, CURRENT_TIMESTAMP())))
ORDER BY LAST_LOAD_TIME DESC
LIMIT 50;

