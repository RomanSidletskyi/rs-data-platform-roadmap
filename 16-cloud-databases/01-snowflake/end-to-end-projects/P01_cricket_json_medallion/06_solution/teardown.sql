DROP WAREHOUSE IF EXISTS P01_WH;
DROP RESOURCE MONITOR IF EXISTS P01_RM;
DROP ROLE IF EXISTS P01_READER;
DROP ROLE IF EXISTS P01_OWNER;

SHOW WAREHOUSES LIKE 'P01_%';
SHOW ROLES LIKE 'P01_%';
