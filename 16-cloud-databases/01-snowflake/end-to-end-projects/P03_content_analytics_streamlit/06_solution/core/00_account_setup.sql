-- P03 account-level setup. Run once as ACCOUNTADMIN.
-- Three roles separate data, application, and audience:
--   P03_OWNER      loads and models data, owns RAW, STG, MART
--   P03_APP_OWNER  owns the Streamlit app; can only read MART (the app runs with this role's rights)
--   P03_VIEWER     can open the app; has no direct access to any table

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS P03_OWNER;
CREATE ROLE IF NOT EXISTS P03_APP_OWNER;
CREATE ROLE IF NOT EXISTS P03_VIEWER;
GRANT ROLE P03_OWNER     TO ROLE SYSADMIN;
GRANT ROLE P03_APP_OWNER TO ROLE SYSADMIN;
GRANT ROLE P03_VIEWER    TO ROLE SYSADMIN;

-- For a solo learner all three go to you; switch roles to see each point of view.
SET my_user = CURRENT_USER();
GRANT ROLE P03_OWNER     TO USER IDENTIFIER($my_user);
GRANT ROLE P03_APP_OWNER TO USER IDENTIFIER($my_user);
GRANT ROLE P03_VIEWER    TO USER IDENTIFIER($my_user);

CREATE RESOURCE MONITOR IF NOT EXISTS P03_RM
  WITH CREDIT_QUOTA = 3
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

-- Loading and the app share one XS warehouse. Each open app session keeps it resumed.
CREATE WAREHOUSE IF NOT EXISTS P03_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300
  RESOURCE_MONITOR = P03_RM
  COMMENT = 'P03 loading and Streamlit app';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P03_WH TO ROLE P03_OWNER;
GRANT USAGE ON WAREHOUSE P03_WH TO ROLE P03_APP_OWNER;

CREATE DATABASE IF NOT EXISTS P03_CONTENT COMMENT = 'P03 Wikipedia content analytics';
GRANT OWNERSHIP ON DATABASE P03_CONTENT TO ROLE P03_OWNER COPY CURRENT GRANTS;
