-- P03 data quality checks. Run as P03_OWNER after 20_load_and_model.sql.

USE ROLE P03_OWNER;
USE WAREHOUSE P03_WH;
USE DATABASE P03_CONTENT;

WITH days AS (
  SELECT PROJECT, MIN(DAY) AS FIRST_DAY, MAX(DAY) AS LAST_DAY, COUNT(DISTINCT DAY) AS DAYS
  FROM STG.TOP_ARTICLE_DAILY
  GROUP BY 1
),
checks AS (
  SELECT 'missing_days_in_top_lists' AS CHECK_NAME, COALESCE(SUM(DATEDIFF('day', FIRST_DAY, LAST_DAY) + 1 - DAYS), 0) AS FAILURES
  FROM days

  UNION ALL
  SELECT 'top_day_without_project_total', COUNT(*)
  FROM (SELECT DISTINCT PROJECT, DAY FROM STG.TOP_ARTICLE_DAILY) t
  WHERE NOT EXISTS (SELECT 1 FROM STG.PROJECT_DAILY p WHERE p.PROJECT = t.PROJECT AND p.DAY = t.DAY)

  UNION ALL
  SELECT 'duplicate_article_per_day', COUNT(*)
  FROM (SELECT PROJECT, DAY, ARTICLE FROM MART.ARTICLE_DAILY GROUP BY 1, 2, 3 HAVING COUNT(*) > 1)

  UNION ALL
  SELECT 'main_page_or_special_in_mart', COUNT(*)
  FROM MART.ARTICLE_DAILY a
  JOIN STG.PROJECT pr ON pr.PROJECT = a.PROJECT
  WHERE a.ARTICLE = pr.MAIN_PAGE
     OR (CONTAINS(a.ARTICLE, ':') AND SPLIT_PART(a.ARTICLE, ':', 1) IN ('Special', 'Spezial', 'Спеціальна'))

  UNION ALL
  SELECT 'article_views_exceed_project_total', COUNT(*)
  FROM MART.ARTICLE_DAILY WHERE SHARE_OF_PROJECT > 1

  UNION ALL
  SELECT 'non_positive_views', COUNT(*)
  FROM STG.TOP_ARTICLE_DAILY WHERE VIEWS <= 0

  UNION ALL
  SELECT 'unknown_project', COUNT(*)
  FROM (SELECT DISTINCT PROJECT FROM STG.TOP_ARTICLE_DAILY) t
  WHERE NOT EXISTS (SELECT 1 FROM STG.PROJECT p WHERE p.PROJECT = t.PROJECT)
)
SELECT CHECK_NAME, FAILURES, IFF(FAILURES = 0, 'PASS', 'FAIL') AS RESULT
FROM checks
ORDER BY RESULT, CHECK_NAME;

-- Not a pass or fail rule, but worth reading: how much of each list the filter removed.
SELECT t.PROJECT, t.DAY, COUNT(*) AS IN_TOP_LIST, COUNT(a.ARTICLE) AS CONTENT_ARTICLES
FROM STG.TOP_ARTICLE_DAILY t
LEFT JOIN MART.ARTICLE_DAILY a ON a.PROJECT = t.PROJECT AND a.DAY = t.DAY AND a.ARTICLE = t.ARTICLE
GROUP BY 1, 2
ORDER BY 2 DESC, 1
LIMIT 9;
