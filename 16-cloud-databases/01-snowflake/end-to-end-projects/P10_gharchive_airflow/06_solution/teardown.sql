-- P10 teardown. Run as ACCOUNTADMIN after `docker compose down -v` in airflow/.
-- Cloud resources are separate: az group delete --name "$P10_RG", or the commands at the end of aws/01_provision.sh.

USE ROLE ACCOUNTADMIN;

DROP DATABASE IF EXISTS P10_GH;
DROP USER IF EXISTS P10_AIRFLOW_SVC;
DROP INTEGRATION IF EXISTS P10_AZURE_STORAGE_INT;
DROP INTEGRATION IF EXISTS P10_AWS_STORAGE_INT;
DROP WAREHOUSE IF EXISTS P10_WH;
DROP RESOURCE MONITOR IF EXISTS P10_RM;
DROP ROLE IF EXISTS P10_READER;
DROP ROLE IF EXISTS P10_PIPELINE;
DROP ROLE IF EXISTS P10_OWNER;

SHOW USERS LIKE 'P10_%';
SHOW INTEGRATIONS LIKE 'P10_%';
