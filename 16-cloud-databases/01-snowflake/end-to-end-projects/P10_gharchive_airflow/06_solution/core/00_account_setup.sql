-- P10 account-level setup. Run once as ACCOUNTADMIN through run_sql.sh, which fills <airflow-public-key>.
--   P10_OWNER     owns the database, stages, tables, and procedures
--   P10_PIPELINE  what Airflow uses: call the procedures, read the logs, PUT to the internal landing stage
--   P10_READER    reads marts

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS P10_OWNER;
CREATE ROLE IF NOT EXISTS P10_PIPELINE;
CREATE ROLE IF NOT EXISTS P10_READER;
GRANT ROLE P10_READER TO ROLE P10_OWNER;
GRANT ROLE P10_PIPELINE TO ROLE P10_OWNER;
GRANT ROLE P10_OWNER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P10_OWNER TO USER IDENTIFIER($my_user);

-- A backfill runs many hours in parallel; the daily quota stops a runaway backfill, not a normal day.
CREATE RESOURCE MONITOR IF NOT EXISTS P10_RM
  WITH CREDIT_QUOTA = 4
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 75 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS P10_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800
  RESOURCE_MONITOR = P10_RM
  COMMENT = 'P10 loads, transformations, unloads';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P10_WH TO ROLE P10_OWNER;
GRANT USAGE ON WAREHOUSE P10_WH TO ROLE P10_PIPELINE;
GRANT USAGE ON WAREHOUSE P10_WH TO ROLE P10_READER;

CREATE DATABASE IF NOT EXISTS P10_GH COMMENT = 'P10 GH Archive orchestrated by Airflow';
GRANT OWNERSHIP ON DATABASE P10_GH TO ROLE P10_OWNER COPY CURRENT GRANTS;

-- Airflow signs in as a service user: no password, key pair only, one role.
CREATE USER IF NOT EXISTS P10_AIRFLOW_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = P10_PIPELINE
  DEFAULT_WAREHOUSE = P10_WH
  RSA_PUBLIC_KEY = '<airflow-public-key>'
  COMMENT = 'P10 Airflow scheduler';
ALTER USER P10_AIRFLOW_SVC SET RSA_PUBLIC_KEY = '<airflow-public-key>';
GRANT ROLE P10_PIPELINE TO USER P10_AIRFLOW_SVC;
