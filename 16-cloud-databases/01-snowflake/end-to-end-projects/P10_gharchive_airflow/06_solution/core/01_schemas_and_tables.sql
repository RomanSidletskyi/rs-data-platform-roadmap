-- P10 schemas, stages, and tables. Run as P10_OWNER after 00_account_setup.sql.
-- The stages start internal, so the whole pipeline runs without a cloud account.
-- azure/11_stages.sql or aws/11_stages.sql replace them with external stages of the same names.

USE ROLE P10_OWNER;
USE WAREHOUSE P10_WH;
USE DATABASE P10_GH;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS STG;
CREATE SCHEMA IF NOT EXISTS MART;
CREATE SCHEMA IF NOT EXISTS OPS;
CREATE SCHEMA IF NOT EXISTS ARCHIVE;

-- One JSON event per line, gzip as published by GH Archive.
CREATE FILE FORMAT IF NOT EXISTS RAW.FF_GH_JSON TYPE = JSON COMPRESSION = GZIP;
CREATE FILE FORMAT IF NOT EXISTS ARCHIVE.FF_PARQUET TYPE = PARQUET;
CREATE FILE FORMAT IF NOT EXISTS ARCHIVE.FF_MANIFEST TYPE = JSON COMPRESSION = NONE;

CREATE STAGE IF NOT EXISTS RAW.LANDING_STAGE COMMENT = 'gharchive/dt=YYYY-MM-DD/YYYY-MM-DD-H.json.gz';
CREATE STAGE IF NOT EXISTS ARCHIVE.ARCHIVE_STAGE COMMENT = 'events/dt=YYYY-MM-DD/*.parquet and _manifests/';

-- RAW is a reloadable copy of the landing files: transient, no Time Travel, purged after the day is archived.
CREATE TRANSIENT TABLE IF NOT EXISTS RAW.GH_EVENT_RAW (
  EVENT_HOUR TIMESTAMP_NTZ NOT NULL COMMENT 'UTC hour of the GH Archive file; the unit of reload',
  V          VARIANT,
  SRC_FILE   STRING,
  SRC_ROW    NUMBER,
  LOADED_AT  TIMESTAMP_LTZ
) DATA_RETENTION_TIME_IN_DAYS = 0;

-- STG: one typed row per event. Hot window only; older verified days live in the archive.
CREATE TABLE IF NOT EXISTS STG.GH_EVENT (
  EVENT_ID     NUMBER(38, 0) NOT NULL,
  EVENT_HOUR   TIMESTAMP_NTZ NOT NULL,
  EVENT_DAY    DATE          NOT NULL,
  CREATED_AT   TIMESTAMP_NTZ,
  EVENT_TYPE   STRING,
  ACTION       STRING,
  ACTOR_ID     NUMBER,
  ACTOR_LOGIN  STRING,
  IS_BOT       BOOLEAN,
  REPO_ID      NUMBER,
  REPO_NAME    STRING,
  ORG_LOGIN    STRING,
  PR_NUMBER    NUMBER,
  PR_OUTCOME   STRING COMMENT 'merged | closed_unmerged | closed_unknown; NULL for other actions',
  ISSUE_NUMBER NUMBER,
  PUSH_COMMITS NUMBER COMMENT 'NULL since GitHub removed payload.size from PushEvent in October 2025',
  REF_TYPE     STRING,
  RELEASE_TAG  STRING,
  LOADED_AT    TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS MART.EVENT_TYPE_DAILY (
  EVENT_DAY  DATE,
  EVENT_TYPE STRING,
  EVENTS     NUMBER,
  ACTORS     NUMBER,
  REPOS      NUMBER,
  BOT_EVENTS NUMBER,
  BUILT_AT   TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS MART.REPO_DAILY (
  EVENT_DAY     DATE,
  REPO_ID       NUMBER,
  REPO_NAME     STRING,
  EVENTS        NUMBER,
  STARS         NUMBER,
  FORKS         NUMBER,
  PUSHES        NUMBER,
  PRS_OPENED    NUMBER,
  PRS_MERGED    NUMBER,
  ISSUES_OPENED NUMBER,
  RELEASES      NUMBER,
  HUMAN_ACTORS  NUMBER,
  BOT_EVENTS    NUMBER,
  BUILT_AT      TIMESTAMP_LTZ
);

CREATE OR REPLACE VIEW MART.TRENDING_REPOS_7D COMMENT = 'Most starred repositories over the last 7 loaded days' AS
SELECT
  REPO_ID,
  MAX_BY(REPO_NAME, EVENT_DAY) AS REPO_NAME,
  SUM(STARS)                   AS STARS_7D,
  SUM(FORKS)                   AS FORKS_7D,
  SUM(PRS_MERGED)              AS PRS_MERGED_7D,
  SUM(RELEASES)                AS RELEASES_7D
FROM MART.REPO_DAILY
WHERE EVENT_DAY > DATEADD(day, -7, (SELECT MAX(EVENT_DAY) FROM MART.REPO_DAILY))
GROUP BY REPO_ID
QUALIFY ROW_NUMBER() OVER (ORDER BY STARS_7D DESC, FORKS_7D DESC) <= 100;

-- OPS: the state the orchestrator and the procedures share. Completeness is read from here, not from Airflow.
CREATE TABLE IF NOT EXISTS OPS.HOUR_LOG (
  EVENT_HOUR     TIMESTAMP_NTZ NOT NULL,
  EVENT_DAY      DATE          NOT NULL,
  SRC_FILE       STRING,
  RAW_ROWS       NUMBER,
  STG_ROWS       NUMBER,
  OUTSIDE_HOUR   NUMBER COMMENT 'events whose created_at is not inside the file hour',
  LOAD_COUNT     NUMBER COMMENT 'how many times the hour was loaded: retries and reprocessing',
  LOAD_QUERY_ID  STRING,
  LOADED_AT      TIMESTAMP_LTZ,
  BUILT_AT       TIMESTAMP_LTZ,
  AIRFLOW_RUN_ID STRING
);

CREATE TABLE IF NOT EXISTS OPS.DAY_LOG (
  EVENT_DAY      DATE NOT NULL,
  STG_ROWS       NUMBER,
  STG_ID_HASH    NUMBER,
  MART_BUILT_AT  TIMESTAMP_LTZ,
  ARCHIVE_ROWS   NUMBER,
  ARCHIVE_ID_HASH NUMBER,
  ARCHIVE_FILES  NUMBER,
  ARCHIVE_BYTES  NUMBER,
  VERIFIED       BOOLEAN,
  ARCHIVED_AT    TIMESTAMP_LTZ,
  PURGED_AT      TIMESTAMP_LTZ,
  AIRFLOW_RUN_ID STRING
);

-- Ratios of fields the marts depend on, per day. A sudden change means the source changed, not the pipeline.
CREATE TABLE IF NOT EXISTS OPS.SOURCE_PROFILE_DAILY (
  EVENT_DAY   DATE,
  CHECK_NAME  STRING,
  NUMERATOR   NUMBER,
  DENOMINATOR NUMBER,
  BUILT_AT    TIMESTAMP_LTZ
);

