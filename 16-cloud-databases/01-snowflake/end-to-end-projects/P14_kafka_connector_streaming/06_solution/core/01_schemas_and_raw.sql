-- P14 schemas and the connector-owned raw table. Run as P14_OWNER (switches to P14_CONNECTOR once).

USE ROLE P14_OWNER;
USE WAREHOUSE P14_TRANSFORM_WH;
USE DATABASE P14_WIKI_STREAM;

CREATE SCHEMA IF NOT EXISTS RAW  COMMENT = 'Rows written by the Kafka connector';
CREATE SCHEMA IF NOT EXISTS STG  COMMENT = 'Typed, one row per event_id';
CREATE SCHEMA IF NOT EXISTS MART COMMENT = 'Consumer-shaped models';
CREATE SCHEMA IF NOT EXISTS OPS  COMMENT = 'Offset integrity, freshness, latency, alerts';

GRANT USAGE ON DATABASE P14_WIKI_STREAM TO ROLE P14_CONNECTOR;
GRANT USAGE ON SCHEMA RAW TO ROLE P14_CONNECTOR;
GRANT CREATE TABLE ON SCHEMA RAW TO ROLE P14_CONNECTOR;

-- The connector must own its target table; creating it here lets us enable change tracking for the stream.
USE ROLE P14_CONNECTOR;
CREATE TABLE IF NOT EXISTS P14_WIKI_STREAM.RAW.WIKI_RECENTCHANGE_RAW (
  RECORD_METADATA VARIANT,
  RECORD_CONTENT  VARIANT
)
CHANGE_TRACKING = TRUE
COMMENT = 'Kafka records: value in RECORD_CONTENT, topic/partition/offset/timestamps in RECORD_METADATA';

USE ROLE P14_OWNER;
-- Least privilege: the connector writes into one existing table and creates nothing else.
REVOKE CREATE TABLE ON SCHEMA RAW FROM ROLE P14_CONNECTOR;

GRANT USAGE ON DATABASE P14_WIKI_STREAM TO ROLE P14_READER;
GRANT USAGE ON SCHEMA MART TO ROLE P14_READER;
GRANT USAGE ON SCHEMA OPS  TO ROLE P14_READER;

SHOW GRANTS TO ROLE P14_CONNECTOR;
