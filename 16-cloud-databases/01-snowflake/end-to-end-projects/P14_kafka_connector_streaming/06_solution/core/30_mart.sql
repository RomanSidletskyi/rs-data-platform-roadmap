-- P14 serving layer. Same minute mart as P04, plus a live view straight over RAW. Run as P14_OWNER.

USE ROLE P14_OWNER;
USE WAREHOUSE P14_TRANSFORM_WH;
USE DATABASE P14_WIKI_STREAM;

CREATE OR REPLACE DYNAMIC TABLE MART.EDITS_PER_MINUTE
  TARGET_LAG = '5 minutes'
  WAREHOUSE = P14_TRANSFORM_WH
  REFRESH_MODE = INCREMENTAL
  COMMENT = 'Grain: minute x wiki x change type x bot flag'
AS
SELECT
  DATE_TRUNC('minute', EVENT_TS) AS MINUTE_TS,
  WIKI,
  CHANGE_TYPE,
  IS_BOT,
  COUNT(*)                       AS CHANGE_COUNT,
  SUM(LENGTH_DELTA)              AS BYTES_DELTA
FROM STG.WIKI_CHANGE
WHERE EVENT_TS IS NOT NULL
GROUP BY 1, 2, 3, 4;

-- Seconds-fresh view for incident watching: reads RAW directly, so it is not deduplicated.
CREATE OR REPLACE VIEW MART.V_LIVE_LAST_5_MINUTES AS
SELECT
  DATE_TRUNC('second', TO_TIMESTAMP_LTZ(RECORD_METADATA:CreateTime::NUMBER, 3)) AS KAFKA_SECOND,
  RECORD_CONTENT:wiki::STRING                                              AS WIKI,
  COUNT(*)                                                                 AS CHANGES
FROM RAW.WIKI_RECENTCHANGE_RAW
WHERE RECORD_METADATA:CreateTime::NUMBER >= DATE_PART(EPOCH_MILLISECOND, DATEADD('minute', -5, CURRENT_TIMESTAMP()))
GROUP BY 1, 2;

CREATE OR REPLACE VIEW MART.V_TOP_PAGES_LAST_HOUR AS
SELECT
  WIKI,
  TITLE,
  COUNT(*)                  AS CHANGE_COUNT,
  COUNT(DISTINCT USER_NAME) AS DISTINCT_USERS,
  COUNT_IF(IS_BOT)          AS BOT_CHANGES,
  MAX(EVENT_TS)             AS LAST_CHANGE_TS
FROM STG.WIKI_CHANGE
WHERE EVENT_TS >= DATEADD('hour', -1, CURRENT_TIMESTAMP())
GROUP BY WIKI, TITLE
QUALIFY ROW_NUMBER() OVER (ORDER BY COUNT(*) DESC) <= 50;

-- The reader role reads MART views; view owner rights cover RAW and STG access.
GRANT SELECT ON DYNAMIC TABLE MART.EDITS_PER_MINUTE TO ROLE P14_READER;
GRANT SELECT ON VIEW MART.V_LIVE_LAST_5_MINUTES TO ROLE P14_READER;
GRANT SELECT ON VIEW MART.V_TOP_PAGES_LAST_HOUR TO ROLE P14_READER;

SHOW DYNAMIC TABLES LIKE 'EDITS_PER_MINUTE' IN SCHEMA MART;
