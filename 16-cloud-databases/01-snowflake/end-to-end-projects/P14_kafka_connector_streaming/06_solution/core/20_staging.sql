-- P14 staging: stream on the connector table, serverless task, deduplicating MERGE. Run as P14_OWNER.
-- Downstream logic matches P04 on purpose, so P04/P14/P15 comparisons isolate the ingestion design.

USE ROLE P14_OWNER;
USE WAREHOUSE P14_TRANSFORM_WH;
USE DATABASE P14_WIKI_STREAM;

CREATE TABLE IF NOT EXISTS STG.WIKI_CHANGE (
  EVENT_ID          STRING NOT NULL,
  RC_ID             NUMBER,
  EVENT_TS          TIMESTAMP_TZ,
  WIKI              STRING,
  SERVER_NAME       STRING,
  CHANGE_TYPE       STRING,
  NAMESPACE         NUMBER,
  TITLE             STRING,
  USER_NAME         STRING,
  IS_BOT            BOOLEAN,
  IS_MINOR          BOOLEAN,
  LENGTH_OLD        NUMBER,
  LENGTH_NEW        NUMBER,
  LENGTH_DELTA      NUMBER,
  KAFKA_PARTITION   NUMBER,
  KAFKA_OFFSET      NUMBER,
  KAFKA_TS          TIMESTAMP_LTZ,
  CONNECTOR_PUSH_TS TIMESTAMP_LTZ,
  STAGED_AT         TIMESTAMP_LTZ
)
COMMENT = 'One row per EVENT_ID; enforced by the MERGE and a data quality check.';

CREATE STREAM IF NOT EXISTS STG.WIKI_RAW_STREAM
  ON TABLE RAW.WIKI_RECENTCHANGE_RAW
  APPEND_ONLY = TRUE
  SHOW_INITIAL_ROWS = TRUE;

CREATE OR REPLACE TASK STG.LOAD_WIKI_CHANGE
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  SCHEDULE = '1 MINUTE'
  ALLOW_OVERLAPPING_EXECUTION = FALSE
  COMMENT = 'Deduplicate new connector rows into STG.WIKI_CHANGE'
  WHEN SYSTEM$STREAM_HAS_DATA('P14_WIKI_STREAM.STG.WIKI_RAW_STREAM')
AS
MERGE INTO STG.WIKI_CHANGE AS T
USING (
  SELECT
    RECORD_CONTENT:meta:id::STRING                              AS EVENT_ID,
    TRY_TO_NUMBER(RECORD_CONTENT:id::STRING)                    AS RC_ID,
    TRY_TO_TIMESTAMP_TZ(RECORD_CONTENT:meta:dt::STRING)         AS EVENT_TS,
    RECORD_CONTENT:wiki::STRING                                 AS WIKI,
    RECORD_CONTENT:server_name::STRING                          AS SERVER_NAME,
    RECORD_CONTENT:type::STRING                                 AS CHANGE_TYPE,
    TRY_TO_NUMBER(RECORD_CONTENT:namespace::STRING)             AS NAMESPACE,
    RECORD_CONTENT:title::STRING                                AS TITLE,
    RECORD_CONTENT:user::STRING                                 AS USER_NAME,
    TRY_TO_BOOLEAN(RECORD_CONTENT:bot::STRING)                  AS IS_BOT,
    TRY_TO_BOOLEAN(RECORD_CONTENT:minor::STRING)                AS IS_MINOR,
    TRY_TO_NUMBER(RECORD_CONTENT:length:old::STRING)            AS LENGTH_OLD,
    TRY_TO_NUMBER(RECORD_CONTENT:length:new::STRING)            AS LENGTH_NEW,
    RECORD_METADATA:partition::NUMBER                           AS KAFKA_PARTITION,
    RECORD_METADATA:offset::NUMBER                              AS KAFKA_OFFSET,
    TO_TIMESTAMP_LTZ(RECORD_METADATA:CreateTime::NUMBER, 3)     AS KAFKA_TS,
    TO_TIMESTAMP_LTZ(RECORD_METADATA:SnowflakeConnectorPushTime::NUMBER, 3) AS CONNECTOR_PUSH_TS
  FROM STG.WIKI_RAW_STREAM
  WHERE RECORD_CONTENT:meta:id::STRING IS NOT NULL
  -- Source replays after reconnect produce the same event at new offsets; keep the first.
  QUALIFY ROW_NUMBER() OVER (
    PARTITION BY RECORD_CONTENT:meta:id::STRING
    ORDER BY RECORD_METADATA:partition::NUMBER, RECORD_METADATA:offset::NUMBER
  ) = 1
) AS S
ON T.EVENT_ID = S.EVENT_ID
WHEN NOT MATCHED THEN INSERT (
  EVENT_ID, RC_ID, EVENT_TS, WIKI, SERVER_NAME, CHANGE_TYPE, NAMESPACE, TITLE, USER_NAME,
  IS_BOT, IS_MINOR, LENGTH_OLD, LENGTH_NEW, LENGTH_DELTA,
  KAFKA_PARTITION, KAFKA_OFFSET, KAFKA_TS, CONNECTOR_PUSH_TS, STAGED_AT
) VALUES (
  S.EVENT_ID, S.RC_ID, S.EVENT_TS, S.WIKI, S.SERVER_NAME, S.CHANGE_TYPE, S.NAMESPACE, S.TITLE, S.USER_NAME,
  S.IS_BOT, S.IS_MINOR, S.LENGTH_OLD, S.LENGTH_NEW, S.LENGTH_NEW - COALESCE(S.LENGTH_OLD, 0),
  S.KAFKA_PARTITION, S.KAFKA_OFFSET, S.KAFKA_TS, S.CONNECTOR_PUSH_TS, CURRENT_TIMESTAMP()
);

ALTER TASK STG.LOAD_WIKI_CHANGE RESUME;
EXECUTE TASK STG.LOAD_WIKI_CHANGE;
