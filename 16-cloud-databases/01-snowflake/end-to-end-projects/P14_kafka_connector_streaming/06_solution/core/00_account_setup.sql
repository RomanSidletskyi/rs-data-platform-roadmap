-- P14 account-level setup. Run once as ACCOUNTADMIN.
-- Placeholders filled by run_sql.sh: <your-verified-email>, <connector-public-key>.

USE ROLE ACCOUNTADMIN;

-- Roles: OWNER administers, CONNECTOR is the only identity Kafka Connect uses, READER consumes.
CREATE ROLE IF NOT EXISTS P14_OWNER;
CREATE ROLE IF NOT EXISTS P14_CONNECTOR;
CREATE ROLE IF NOT EXISTS P14_READER;
GRANT ROLE P14_READER TO ROLE P14_OWNER;
GRANT ROLE P14_CONNECTOR TO ROLE P14_OWNER;
GRANT ROLE P14_OWNER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P14_OWNER TO USER IDENTIFIER($my_user);
GRANT ROLE P14_CONNECTOR TO USER IDENTIFIER($my_user);
GRANT ROLE P14_READER TO USER IDENTIFIER($my_user);

-- Service user for the connector: key-pair only, no password, no interactive login.
CREATE USER IF NOT EXISTS P14_KAFKA_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = P14_CONNECTOR
  RSA_PUBLIC_KEY = '<connector-public-key>'
  COMMENT = 'Kafka Connect Snowflake sink for P14';
GRANT ROLE P14_CONNECTOR TO USER P14_KAFKA_SVC;

-- Warehouses only cover staging/mart work: Snowpipe Streaming itself needs no warehouse.
CREATE RESOURCE MONITOR IF NOT EXISTS P14_RM
  WITH CREDIT_QUOTA = 5
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS P14_TRANSFORM_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 600
  RESOURCE_MONITOR = P14_RM
  COMMENT = 'P14 dynamic table refresh, alert, ad hoc engineering';

CREATE WAREHOUSE IF NOT EXISTS P14_BI_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300
  RESOURCE_MONITOR = P14_RM
  COMMENT = 'P14 dashboards';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P14_TRANSFORM_WH TO ROLE P14_OWNER;
GRANT USAGE, OPERATE ON WAREHOUSE P14_BI_WH TO ROLE P14_OWNER;
GRANT USAGE ON WAREHOUSE P14_BI_WH TO ROLE P14_READER;

CREATE DATABASE IF NOT EXISTS P14_WIKI_STREAM COMMENT = 'P14 Kafka connector with Snowpipe Streaming';
GRANT OWNERSHIP ON DATABASE P14_WIKI_STREAM TO ROLE P14_OWNER COPY CURRENT GRANTS;

GRANT EXECUTE TASK, EXECUTE MANAGED TASK, EXECUTE ALERT ON ACCOUNT TO ROLE P14_OWNER;

CREATE NOTIFICATION INTEGRATION IF NOT EXISTS P14_EMAIL_INT
  TYPE = EMAIL
  ENABLED = TRUE
  ALLOWED_RECIPIENTS = ('<your-verified-email>');
GRANT USAGE ON INTEGRATION P14_EMAIL_INT TO ROLE P14_OWNER;

DESC USER P14_KAFKA_SVC;   -- RSA_PUBLIC_KEY_FP must be set
