-- P14 dashboard tiles and operational queries.

USE DATABASE P14_WIKI_STREAM;

-- =====================================================================
-- Dashboard tiles. Role P14_READER, warehouse P14_BI_WH.
-- =====================================================================
USE ROLE P14_READER;
USE WAREHOUSE P14_BI_WH;

-- Tile 1: live changes per second, last 5 minutes, top wikis (line chart)
SELECT KAFKA_SECOND, WIKI, CHANGES
FROM MART.V_LIVE_LAST_5_MINUTES
WHERE WIKI IN (
  SELECT WIKI FROM MART.V_LIVE_LAST_5_MINUTES GROUP BY WIKI ORDER BY SUM(CHANGES) DESC LIMIT 5
)
ORDER BY KAFKA_SECOND;

-- Tile 2: edits per minute, last hour (from the deduplicated mart)
SELECT MINUTE_TS, SUM(CHANGE_COUNT) AS CHANGES, SUM(IFF(IS_BOT, CHANGE_COUNT, 0)) AS BOT_CHANGES
FROM MART.EDITS_PER_MINUTE
WHERE MINUTE_TS >= DATEADD('hour', -1, CURRENT_TIMESTAMP())
GROUP BY MINUTE_TS
ORDER BY MINUTE_TS;

-- Tile 3: hot pages
SELECT WIKI, TITLE, CHANGE_COUNT, DISTINCT_USERS, BOT_CHANGES FROM MART.V_TOP_PAGES_LAST_HOUR ORDER BY CHANGE_COUNT DESC LIMIT 20;

-- Tile 4: offset integrity, freshness, latency
SELECT * FROM OPS.V_OFFSET_INTEGRITY ORDER BY KAFKA_PARTITION;
SELECT * FROM OPS.V_PIPELINE_FRESHNESS;
SELECT * FROM OPS.V_LATENCY_LAST_HOUR;

-- =====================================================================
-- Operational queries. Role P14_OWNER.
-- =====================================================================
USE ROLE P14_OWNER;
USE WAREHOUSE P14_TRANSFORM_WH;

-- One channel per topic partition; the offset token is the last committed Kafka offset.
SHOW CHANNELS IN TABLE RAW.WIKI_RECENTCHANGE_RAW;

-- Rows from the last minute, to see the connector working
SELECT RECORD_METADATA:partition::NUMBER AS P, RECORD_METADATA:offset::NUMBER AS O,
       RECORD_CONTENT:wiki::STRING AS WIKI, RECORD_CONTENT:title::STRING AS TITLE
FROM RAW.WIKI_RECENTCHANGE_RAW
WHERE RECORD_METADATA:CreateTime::NUMBER >= DATE_PART(EPOCH_MILLISECOND, DATEADD('minute', -1, CURRENT_TIMESTAMP()))
ORDER BY O DESC
LIMIT 20;

SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
  TASK_NAME => 'LOAD_WIKI_CHANGE',
  SCHEDULED_TIME_RANGE_START => DATEADD('hour', -1, CURRENT_TIMESTAMP())))
ORDER BY SCHEDULED_TIME DESC;

SELECT NAME, STATE, REFRESH_ACTION, REFRESH_START_TIME, REFRESH_END_TIME
FROM TABLE(INFORMATION_SCHEMA.DYNAMIC_TABLE_REFRESH_HISTORY(NAME => 'P14_WIKI_STREAM.MART.EDITS_PER_MINUTE'))
ORDER BY REFRESH_START_TIME DESC
LIMIT 10;

-- Credits. Snowpipe Streaming appears in ACCOUNT_USAGE with a lag of up to a few hours.
SELECT SERVICE_TYPE, NAME, SUM(CREDITS_USED) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
WHERE START_TIME >= DATEADD('day', -1, CURRENT_TIMESTAMP())
  AND (SERVICE_TYPE ILIKE '%STREAMING%' OR NAME ILIKE 'P14_%')
GROUP BY 1, 2
ORDER BY CREDITS DESC;

SELECT 'warehouse' AS COMPONENT, WAREHOUSE_NAME AS NAME, SUM(CREDITS_USED) AS CREDITS
FROM TABLE(INFORMATION_SCHEMA.WAREHOUSE_METERING_HISTORY(DATE_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP())))
WHERE WAREHOUSE_NAME LIKE 'P14_%'
GROUP BY WAREHOUSE_NAME
UNION ALL
SELECT 'serverless_task', TASK_NAME, SUM(CREDITS_USED)
FROM TABLE(INFORMATION_SCHEMA.SERVERLESS_TASK_HISTORY(DATE_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP())))
GROUP BY TASK_NAME;
