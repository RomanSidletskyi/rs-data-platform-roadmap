-- P08 Azure stage and four auto-ingest pipes on one queue. Run as P08_OWNER after access has propagated.

USE ROLE P08_OWNER;
USE WAREHOUSE P08_WH;
USE DATABASE P08_SOCIAL;

CREATE STAGE IF NOT EXISTS RAW.BSKY_STAGE
  URL = 'azure://<storage-account>.blob.core.windows.net/landing/bsky/'
  STORAGE_INTEGRATION = P08_AZURE_STORAGE_INT
  FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_NDJSON')
  COMMENT = 'collection=<name>/dt=YYYY-MM-DD/hour=HH/*.json.gz';

LIST @RAW.BSKY_STAGE/collection=post/;

-- Every notification from the queue is offered to every pipe on the integration;
-- a pipe loads a file only if the file is under the path in its COPY statement.
CREATE PIPE IF NOT EXISTS RAW.POST_PIPE AUTO_INGEST = TRUE INTEGRATION = 'P08_AZURE_QUEUE_INT' AS
COPY INTO RAW.POST_RAW (PAYLOAD, SRC_FILE, SRC_FILE_ROW, LOADED_AT)
FROM (SELECT $1, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, METADATA$START_SCAN_TIME FROM @RAW.BSKY_STAGE/collection=post/)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_NDJSON') ON_ERROR = SKIP_FILE;

CREATE PIPE IF NOT EXISTS RAW.LIKE_PIPE AUTO_INGEST = TRUE INTEGRATION = 'P08_AZURE_QUEUE_INT' AS
COPY INTO RAW.LIKE_RAW (PAYLOAD, SRC_FILE, SRC_FILE_ROW, LOADED_AT)
FROM (SELECT $1, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, METADATA$START_SCAN_TIME FROM @RAW.BSKY_STAGE/collection=like/)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_NDJSON') ON_ERROR = SKIP_FILE;

CREATE PIPE IF NOT EXISTS RAW.REPOST_PIPE AUTO_INGEST = TRUE INTEGRATION = 'P08_AZURE_QUEUE_INT' AS
COPY INTO RAW.REPOST_RAW (PAYLOAD, SRC_FILE, SRC_FILE_ROW, LOADED_AT)
FROM (SELECT $1, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, METADATA$START_SCAN_TIME FROM @RAW.BSKY_STAGE/collection=repost/)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_NDJSON') ON_ERROR = SKIP_FILE;

CREATE PIPE IF NOT EXISTS RAW.FOLLOW_PIPE AUTO_INGEST = TRUE INTEGRATION = 'P08_AZURE_QUEUE_INT' AS
COPY INTO RAW.FOLLOW_RAW (PAYLOAD, SRC_FILE, SRC_FILE_ROW, LOADED_AT)
FROM (SELECT $1, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, METADATA$START_SCAN_TIME FROM @RAW.BSKY_STAGE/collection=follow/)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_NDJSON') ON_ERROR = SKIP_FILE;

-- Files that landed before a pipe existed were never offered to it.
ALTER PIPE RAW.POST_PIPE REFRESH;
ALTER PIPE RAW.LIKE_PIPE REFRESH;
ALTER PIPE RAW.REPOST_PIPE REFRESH;
ALTER PIPE RAW.FOLLOW_PIPE REFRESH;

SHOW PIPES IN SCHEMA RAW;
