-- P08 ingestion evidence at volume: files per pipe, file sizes, latency per hop, Snowpipe and task cost. Run as P08_OWNER.

USE ROLE P08_OWNER;
USE WAREHOUSE P08_WH;
USE DATABASE P08_SOCIAL;

-- Files and sizes per raw table: the main lever for Snowpipe cost and latency.
CREATE OR REPLACE VIEW OPS.V_FILES_LAST_HOUR AS
SELECT 'post' AS COLLECTION, * FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'RAW.POST_RAW', START_TIME => DATEADD(hour, -1, CURRENT_TIMESTAMP())))
UNION ALL
SELECT 'like', * FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'RAW.LIKE_RAW', START_TIME => DATEADD(hour, -1, CURRENT_TIMESTAMP())))
UNION ALL
SELECT 'repost', * FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'RAW.REPOST_RAW', START_TIME => DATEADD(hour, -1, CURRENT_TIMESTAMP())))
UNION ALL
SELECT 'follow', * FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'RAW.FOLLOW_RAW', START_TIME => DATEADD(hour, -1, CURRENT_TIMESTAMP())));

CREATE OR REPLACE VIEW OPS.V_FILE_PROFILE AS
SELECT
  COLLECTION,
  COUNT(*)                                       AS FILES,
  SUM(ROW_COUNT)                                 AS ROWS_LOADED,
  ROUND(AVG(FILE_SIZE) / 1024, 1)                AS AVG_FILE_KB,
  ROUND(AVG(ROW_COUNT))                          AS AVG_ROWS_PER_FILE,
  COUNT_IF(STATUS <> 'Loaded')                   AS NOT_LOADED
FROM OPS.V_FILES_LAST_HOUR
GROUP BY COLLECTION;

-- Latency per hop for the last hour: event -> file loaded by the pipe -> row in STG.
CREATE OR REPLACE VIEW OPS.V_LATENCY_LAST_HOUR AS
SELECT
  COLLECTION,
  COUNT(*) AS EVENTS,
  APPROX_PERCENTILE(DATEDIFF('second', EVENT_TIME, CONVERT_TIMEZONE('UTC', LOADED_AT)::TIMESTAMP_NTZ), 0.5)  AS P50_EVENT_TO_RAW_S,
  APPROX_PERCENTILE(DATEDIFF('second', EVENT_TIME, CONVERT_TIMEZONE('UTC', LOADED_AT)::TIMESTAMP_NTZ), 0.95) AS P95_EVENT_TO_RAW_S,
  APPROX_PERCENTILE(DATEDIFF('second', EVENT_TIME, CONVERT_TIMEZONE('UTC', STG_LOADED_AT)::TIMESTAMP_NTZ), 0.95) AS P95_EVENT_TO_STG_S
FROM STG.EVENT
WHERE STG_LOADED_AT >= DATEADD(hour, -1, CURRENT_TIMESTAMP())
GROUP BY COLLECTION;

-- Duplicates removed: rows loaded into RAW versus rows inserted into STG, per hour.
CREATE OR REPLACE VIEW OPS.V_DEDUP_LAST_DAY AS
WITH raw_rows AS (
  SELECT DATE_TRUNC('hour', LOADED_AT) AS HOUR_, COUNT(*) AS N FROM (
    SELECT LOADED_AT FROM RAW.POST_RAW UNION ALL SELECT LOADED_AT FROM RAW.LIKE_RAW
    UNION ALL SELECT LOADED_AT FROM RAW.REPOST_RAW UNION ALL SELECT LOADED_AT FROM RAW.FOLLOW_RAW
  ) WHERE LOADED_AT >= DATEADD(day, -1, CURRENT_TIMESTAMP()) GROUP BY 1
),
stg_rows AS (
  SELECT DATE_TRUNC('hour', LOADED_AT) AS HOUR_, COUNT(*) AS N FROM STG.EVENT
  WHERE LOADED_AT >= DATEADD(day, -1, CURRENT_TIMESTAMP()) GROUP BY 1
)
SELECT r.HOUR_, r.N AS RAW_ROWS, COALESCE(s.N, 0) AS STG_ROWS, r.N - COALESCE(s.N, 0) AS REMOVED_OR_PENDING
FROM raw_rows r LEFT JOIN stg_rows s ON s.HOUR_ = r.HOUR_;

GRANT SELECT ON VIEW OPS.V_FILE_PROFILE      TO ROLE P08_READER;
GRANT SELECT ON VIEW OPS.V_LATENCY_LAST_HOUR TO ROLE P08_READER;

-- Run these by hand during a session.
SELECT * FROM OPS.V_FILE_PROFILE;
SELECT * FROM OPS.V_LATENCY_LAST_HOUR;
SELECT * FROM OPS.V_DEDUP_LAST_DAY ORDER BY HOUR_ DESC;

-- Snowpipe cost and volume per pipe, last 24 hours.
SELECT PIPE_NAME, SUM(CREDITS_USED) AS CREDITS, SUM(BYTES_INSERTED) / POWER(1024, 3) AS GB, SUM(FILES_INSERTED) AS FILES
FROM TABLE(INFORMATION_SCHEMA.PIPE_USAGE_HISTORY(DATE_RANGE_START => DATEADD(day, -1, CURRENT_TIMESTAMP())))
GROUP BY 1 ORDER BY 2 DESC;

-- Serverless task cost, last 24 hours.
SELECT TASK_NAME, SUM(CREDITS_USED) AS CREDITS
FROM TABLE(INFORMATION_SCHEMA.SERVERLESS_TASK_HISTORY(DATE_RANGE_START => DATEADD(day, -1, CURRENT_TIMESTAMP())))
GROUP BY 1;

SELECT PARSE_JSON(SYSTEM$PIPE_STATUS('P08_SOCIAL.RAW.LIKE_PIPE')) AS LIKE_PIPE_STATUS;
