-- P08 pause: stop staging and the dynamic tables. Pipes stay; stop the producer to stop files. Run as P08_OWNER.
-- Pipes keep loading anything still arriving; ALTER PIPE ... SET PIPE_EXECUTION_PAUSED = TRUE stops them too.

USE ROLE P08_OWNER;
USE DATABASE P08_SOCIAL;

ALTER TASK IF EXISTS PIPE.LOAD_EVENTS SUSPEND;
ALTER TASK IF EXISTS PIPE.PURGE_RAW SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS MART.DT_POST_ENGAGEMENT SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS MART.DT_ENGAGEMENT_RECORD SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS MART.DT_POST SUSPEND;
ALTER PIPE IF EXISTS RAW.POST_PIPE   SET PIPE_EXECUTION_PAUSED = TRUE;
ALTER PIPE IF EXISTS RAW.LIKE_PIPE   SET PIPE_EXECUTION_PAUSED = TRUE;
ALTER PIPE IF EXISTS RAW.REPOST_PIPE SET PIPE_EXECUTION_PAUSED = TRUE;
ALTER PIPE IF EXISTS RAW.FOLLOW_PIPE SET PIPE_EXECUTION_PAUSED = TRUE;
ALTER WAREHOUSE P08_WH SUSPEND;
