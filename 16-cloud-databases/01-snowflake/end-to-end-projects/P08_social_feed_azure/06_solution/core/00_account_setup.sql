-- P08 account-level setup. Run once as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS P08_OWNER;
CREATE ROLE IF NOT EXISTS P08_READER;
GRANT ROLE P08_READER TO ROLE P08_OWNER;
GRANT ROLE P08_OWNER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P08_OWNER TO USER IDENTIFIER($my_user);
GRANT ROLE P08_READER TO USER IDENTIFIER($my_user);

-- Covers warehouses only. Snowpipe and serverless tasks are billed outside it: watch OPS views instead.
CREATE RESOURCE MONITOR IF NOT EXISTS P08_RM
  WITH CREDIT_QUOTA = 5
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS P08_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 900
  RESOURCE_MONITOR = P08_RM
  COMMENT = 'P08 dynamic table refreshes, dashboard, ad hoc';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P08_WH TO ROLE P08_OWNER;
GRANT USAGE ON WAREHOUSE P08_WH TO ROLE P08_READER;

CREATE DATABASE IF NOT EXISTS P08_SOCIAL COMMENT = 'P08 Bluesky social feed at volume';
GRANT OWNERSHIP ON DATABASE P08_SOCIAL TO ROLE P08_OWNER COPY CURRENT GRANTS;

GRANT EXECUTE TASK, EXECUTE MANAGED TASK ON ACCOUNT TO ROLE P08_OWNER;
