-- P08 mart: dynamic tables that resolve deletes and count engagement, refreshed every 30 minutes, plus views.
-- Run as P08_OWNER after STG.EVENT has data.

USE ROLE P08_OWNER;
USE WAREHOUSE P08_WH;
USE DATABASE P08_SOCIAL;

-- A delete event carries only the record key. The subject of a deleted like is found through its create event.
CREATE OR REPLACE DYNAMIC TABLE MART.DT_ENGAGEMENT_RECORD
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = P08_WH
  REFRESH_MODE = AUTO
  COMMENT = 'One row per like or repost record, with its subject and deletion time'
AS
SELECT
  c.URI         AS RECORD_URI,
  c.COLLECTION,
  c.DID         AS ACTOR_DID,
  c.SUBJECT_URI AS POST_URI,
  c.EVENT_TIME  AS CREATED_TIME,
  d.EVENT_TIME  AS DELETED_TIME
FROM STG.EVENT c
LEFT JOIN STG.EVENT d
  ON  d.DID = c.DID AND d.COLLECTION = c.COLLECTION AND d.RKEY = c.RKEY AND d.OPERATION = 'delete'
WHERE c.OPERATION = 'create' AND c.COLLECTION IN ('like', 'repost');

CREATE OR REPLACE DYNAMIC TABLE MART.DT_POST
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = P08_WH
  REFRESH_MODE = AUTO
  COMMENT = 'Posts seen while capturing, with deletion time'
AS
SELECT
  c.URI AS POST_URI, c.DID AS AUTHOR_DID, c.TEXT, c.LANG, c.REPLY_PARENT_URI,
  c.EVENT_TIME AS CREATED_TIME, d.EVENT_TIME AS DELETED_TIME
FROM STG.EVENT c
LEFT JOIN STG.EVENT d
  ON d.DID = c.DID AND d.COLLECTION = 'post' AND d.RKEY = c.RKEY AND d.OPERATION = 'delete'
WHERE c.COLLECTION = 'post' AND c.OPERATION = 'create';

-- 30 minutes, as in the original design: fresh enough for trends, cheap enough to leave running during a session.
CREATE OR REPLACE DYNAMIC TABLE MART.DT_POST_ENGAGEMENT
  TARGET_LAG = '30 minutes'
  WAREHOUSE = P08_WH
  REFRESH_MODE = AUTO
  COMMENT = 'Likes, reposts, replies per post, deleted records excluded'
AS
WITH signals AS (
  SELECT POST_URI, IFF(COLLECTION = 'like', 1, 0) AS LIKES, IFF(COLLECTION = 'repost', 1, 0) AS REPOSTS, 0 AS REPLIES, CREATED_TIME
  FROM MART.DT_ENGAGEMENT_RECORD
  WHERE DELETED_TIME IS NULL
  UNION ALL
  SELECT REPLY_PARENT_URI, 0, 0, 1, CREATED_TIME
  FROM MART.DT_POST
  WHERE REPLY_PARENT_URI IS NOT NULL AND DELETED_TIME IS NULL
)
SELECT
  POST_URI,
  SUM(LIKES)        AS LIKES,
  SUM(REPOSTS)      AS REPOSTS,
  SUM(REPLIES)      AS REPLIES,
  MIN(CREATED_TIME) AS FIRST_SIGNAL,
  MAX(CREATED_TIME) AS LAST_SIGNAL
FROM signals
GROUP BY POST_URI;

-- Relative time windows cannot live in a dynamic table (CURRENT_TIMESTAMP is not allowed), so they are views.
CREATE OR REPLACE VIEW MART.V_TOP_POSTS_LAST_HOUR AS
SELECT
  e.POST_URI,
  COUNT_IF(e.COLLECTION = 'like')   AS LIKES_LAST_HOUR,
  COUNT_IF(e.COLLECTION = 'repost') AS REPOSTS_LAST_HOUR,
  ANY_VALUE(p.TEXT)                 AS TEXT,
  ANY_VALUE(p.LANG)                 AS LANG,
  ANY_VALUE(p.CREATED_TIME) IS NOT NULL AS POST_CAPTURED,
  'https://bsky.app/profile/' || SPLIT_PART(e.POST_URI, '/', 3) || '/post/' || SPLIT_PART(e.POST_URI, '/', 5) AS URL
FROM MART.DT_ENGAGEMENT_RECORD e
LEFT JOIN MART.DT_POST p ON p.POST_URI = e.POST_URI
WHERE e.CREATED_TIME >= DATEADD(hour, -1, SYSDATE()) AND e.DELETED_TIME IS NULL
GROUP BY e.POST_URI
ORDER BY LIKES_LAST_HOUR + 2 * REPOSTS_LAST_HOUR DESC
LIMIT 50;

CREATE OR REPLACE VIEW MART.V_ACTIVITY_PER_MINUTE AS
SELECT DATE_TRUNC('minute', EVENT_TIME) AS MINUTE_UTC, COLLECTION, OPERATION, COUNT(*) AS EVENTS
FROM STG.EVENT
WHERE EVENT_TIME >= DATEADD(hour, -3, SYSDATE())
GROUP BY 1, 2, 3;

CREATE OR REPLACE VIEW MART.V_LANGUAGE_SHARE AS
SELECT COALESCE(LANG, 'none') AS LANG, COUNT(*) AS POSTS, ROUND(100 * RATIO_TO_REPORT(COUNT(*)) OVER (), 2) AS PCT
FROM MART.DT_POST
WHERE CREATED_TIME >= DATEADD(hour, -24, SYSDATE())
GROUP BY 1
ORDER BY 2 DESC;

GRANT SELECT ON DYNAMIC TABLE MART.DT_POST_ENGAGEMENT TO ROLE P08_READER;
GRANT SELECT ON DYNAMIC TABLE MART.DT_POST            TO ROLE P08_READER;
GRANT SELECT ON VIEW MART.V_TOP_POSTS_LAST_HOUR       TO ROLE P08_READER;
GRANT SELECT ON VIEW MART.V_ACTIVITY_PER_MINUTE       TO ROLE P08_READER;
GRANT SELECT ON VIEW MART.V_LANGUAGE_SHARE            TO ROLE P08_READER;

SHOW DYNAMIC TABLES IN SCHEMA MART;
SELECT "name", "target_lag", "refresh_mode", "refresh_mode_reason" FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
