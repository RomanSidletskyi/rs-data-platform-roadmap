-- P08 teardown in Snowflake. Run as ACCOUNTADMIN. Delete the cloud resources separately:
--   Azure: az group delete --name "$P08_RG" --yes
--   AWS:   empty and delete the bucket, delete the role p08-snowflake-landing-read

USE ROLE ACCOUNTADMIN;

ALTER TASK IF EXISTS P08_SOCIAL.PIPE.LOAD_EVENTS SUSPEND;
DROP DATABASE IF EXISTS P08_SOCIAL;
DROP INTEGRATION IF EXISTS P08_AZURE_QUEUE_INT;
DROP INTEGRATION IF EXISTS P08_AZURE_STORAGE_INT;
DROP INTEGRATION IF EXISTS P08_AWS_STORAGE_INT;
DROP WAREHOUSE IF EXISTS P08_WH;
DROP RESOURCE MONITOR IF EXISTS P08_RM;
DROP ROLE IF EXISTS P08_READER;
DROP ROLE IF EXISTS P08_OWNER;

SHOW INTEGRATIONS LIKE 'P08_%';
SHOW WAREHOUSES LIKE 'P08_%';
