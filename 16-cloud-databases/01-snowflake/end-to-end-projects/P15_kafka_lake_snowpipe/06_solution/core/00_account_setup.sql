USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS P15_OWNER;
CREATE ROLE IF NOT EXISTS P15_READER;
GRANT ROLE P15_READER TO ROLE P15_OWNER;
GRANT ROLE P15_OWNER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P15_OWNER TO USER IDENTIFIER($my_user);
GRANT ROLE P15_READER TO USER IDENTIFIER($my_user);

CREATE RESOURCE MONITOR IF NOT EXISTS P15_RM
  WITH CREDIT_QUOTA = 5
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS P15_TRANSFORM_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 600
  RESOURCE_MONITOR = P15_RM
  COMMENT = 'P15 dynamic table refresh, alert, replay, ad hoc engineering';

CREATE WAREHOUSE IF NOT EXISTS P15_BI_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300
  RESOURCE_MONITOR = P15_RM
  COMMENT = 'P15 dashboards';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P15_TRANSFORM_WH TO ROLE P15_OWNER;
GRANT USAGE, OPERATE ON WAREHOUSE P15_BI_WH TO ROLE P15_OWNER;
GRANT USAGE ON WAREHOUSE P15_BI_WH TO ROLE P15_READER;

CREATE DATABASE IF NOT EXISTS P15_WIKI_LAKE COMMENT = 'P15 Kafka to lake to Snowpipe';
GRANT OWNERSHIP ON DATABASE P15_WIKI_LAKE TO ROLE P15_OWNER COPY CURRENT GRANTS;

GRANT EXECUTE TASK, EXECUTE MANAGED TASK, EXECUTE ALERT ON ACCOUNT TO ROLE P15_OWNER;

