-- P15 dashboard tiles and operational queries.

USE DATABASE P15_WIKI_LAKE;

-- Dashboard tiles: role P15_READER, warehouse P15_BI_WH.
USE ROLE P15_READER;
USE WAREHOUSE P15_BI_WH;

SELECT MINUTE_TS, SUM(CHANGE_COUNT) AS CHANGES, SUM(IFF(IS_BOT, CHANGE_COUNT, 0)) AS BOT_CHANGES
FROM MART.EDITS_PER_MINUTE
WHERE MINUTE_TS >= DATEADD('hour', -1, CURRENT_TIMESTAMP())
GROUP BY MINUTE_TS
ORDER BY MINUTE_TS;

SELECT WIKI, TITLE, CHANGE_COUNT, DISTINCT_USERS, BOT_CHANGES FROM MART.V_TOP_PAGES_LAST_HOUR ORDER BY CHANGE_COUNT DESC LIMIT 20;
SELECT * FROM OPS.V_OFFSET_INTEGRITY ORDER BY KAFKA_PARTITION;
SELECT * FROM OPS.V_FILE_STATS_LAST_DAY ORDER BY LOAD_HOUR DESC;
SELECT * FROM OPS.V_PIPELINE_FRESHNESS;
SELECT * FROM OPS.V_LATENCY_LAST_HOUR;

-- Operational queries: role P15_OWNER.
USE ROLE P15_OWNER;
USE WAREHOUSE P15_TRANSFORM_WH;

SELECT PARSE_JSON(SYSTEM$PIPE_STATUS('P15_WIKI_LAKE.RAW.WIKI_LAKE_PIPE')) AS PIPE_STATUS;

SELECT FILE_NAME, STATUS, ROW_COUNT, ERROR_COUNT, FIRST_ERROR_MESSAGE, PIPE_RECEIVED_TIME, LAST_LOAD_TIME
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
  TABLE_NAME => 'P15_WIKI_LAKE.RAW.WIKI_RECENTCHANGE_RAW',
  START_TIME => DATEADD('hour', -1, CURRENT_TIMESTAMP())))
ORDER BY LAST_LOAD_TIME DESC;

SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
  TASK_NAME => 'LOAD_WIKI_CHANGE',
  SCHEDULED_TIME_RANGE_START => DATEADD('hour', -1, CURRENT_TIMESTAMP())))
ORDER BY SCHEDULED_TIME DESC;

SELECT 'warehouse' AS COMPONENT, WAREHOUSE_NAME AS NAME, SUM(CREDITS_USED) AS CREDITS
FROM TABLE(INFORMATION_SCHEMA.WAREHOUSE_METERING_HISTORY(DATE_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP())))
WHERE WAREHOUSE_NAME LIKE 'P15_%'
GROUP BY WAREHOUSE_NAME
UNION ALL
SELECT 'snowpipe', PIPE_NAME, SUM(CREDITS_USED)
FROM TABLE(INFORMATION_SCHEMA.PIPE_USAGE_HISTORY(DATE_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP())))
GROUP BY PIPE_NAME
UNION ALL
SELECT 'serverless_task', TASK_NAME, SUM(CREDITS_USED)
FROM TABLE(INFORMATION_SCHEMA.SERVERLESS_TASK_HISTORY(DATE_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP())))
GROUP BY TASK_NAME;
