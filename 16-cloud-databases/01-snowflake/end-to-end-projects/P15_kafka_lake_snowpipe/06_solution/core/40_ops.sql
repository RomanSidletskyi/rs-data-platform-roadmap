-- P15 operational evidence: offset integrity, file sizes, freshness, latency, alert. Run as P15_OWNER.

USE ROLE P15_OWNER;
USE WAREHOUSE P15_TRANSFORM_WH;
USE DATABASE P15_WIKI_LAKE;

-- Duplicates here mean overlapping files (for example a crash between upload and offset commit).
CREATE OR REPLACE VIEW OPS.V_OFFSET_INTEGRITY AS
SELECT
  KAFKA_TOPIC,
  KAFKA_PARTITION,
  COUNT(*)                                                   AS ROWS_LOADED,
  COUNT(DISTINCT KAFKA_OFFSET)                               AS DISTINCT_OFFSETS,
  MIN(KAFKA_OFFSET)                                          AS MIN_OFFSET,
  MAX(KAFKA_OFFSET)                                          AS MAX_OFFSET,
  COUNT(*) - COUNT(DISTINCT KAFKA_OFFSET)                    AS DUPLICATE_OFFSETS,
  (MAX(KAFKA_OFFSET) - MIN(KAFKA_OFFSET) + 1) - COUNT(DISTINCT KAFKA_OFFSET) AS MISSING_OFFSETS,
  COUNT_IF(PAYLOAD IS NULL)                                  AS UNPARSEABLE_VALUES
FROM RAW.WIKI_RECENTCHANGE_RAW
GROUP BY 1, 2;

-- Small files are the main cost and latency trade-off of lake-first ingestion.
CREATE OR REPLACE VIEW OPS.V_FILE_STATS_LAST_DAY AS
SELECT
  DATE_TRUNC('hour', LOADED_AT)       AS LOAD_HOUR,
  COUNT(DISTINCT SRC_FILE)            AS FILES,
  COUNT(*)                            AS ROWS_LOADED,
  ROUND(COUNT(*) / NULLIF(COUNT(DISTINCT SRC_FILE), 0)) AS AVG_ROWS_PER_FILE
FROM RAW.WIKI_RECENTCHANGE_RAW
WHERE LOADED_AT >= DATEADD('day', -1, CURRENT_TIMESTAMP())
GROUP BY 1;

CREATE OR REPLACE VIEW OPS.V_PIPELINE_FRESHNESS AS
WITH last_updates AS (
  SELECT 'RAW' AS LAYER, MAX(LOADED_AT) AS LAST_UPDATE_AT FROM RAW.WIKI_RECENTCHANGE_RAW
  UNION ALL
  SELECT 'STG', MAX(STAGED_AT) FROM STG.WIKI_CHANGE
)
SELECT LAYER, LAST_UPDATE_AT, DATEDIFF('second', LAST_UPDATE_AT, CURRENT_TIMESTAMP()) AS SECONDS_SINCE_UPDATE
FROM last_updates;

-- Kafka to raw includes the record-time window, upload, storage event, and Snowpipe load.
CREATE OR REPLACE VIEW OPS.V_LATENCY_LAST_HOUR AS
SELECT
  COUNT(*)                                                                     AS EVENTS,
  APPROX_PERCENTILE(DATEDIFF('millisecond', EVENT_TS, KAFKA_TS), 0.50) / 1000  AS P50_EVENT_TO_KAFKA_S,
  APPROX_PERCENTILE(DATEDIFF('millisecond', EVENT_TS, KAFKA_TS), 0.95) / 1000  AS P95_EVENT_TO_KAFKA_S,
  APPROX_PERCENTILE(DATEDIFF('second', KAFKA_TS, LOADED_AT), 0.50)             AS P50_KAFKA_TO_RAW_S,
  APPROX_PERCENTILE(DATEDIFF('second', KAFKA_TS, LOADED_AT), 0.95)             AS P95_KAFKA_TO_RAW_S,
  APPROX_PERCENTILE(DATEDIFF('second', EVENT_TS, STAGED_AT), 0.50)             AS P50_EVENT_TO_STG_S,
  APPROX_PERCENTILE(DATEDIFF('second', EVENT_TS, STAGED_AT), 0.95)             AS P95_EVENT_TO_STG_S
FROM STG.WIKI_CHANGE
WHERE STAGED_AT >= DATEADD('hour', -1, CURRENT_TIMESTAMP());

GRANT SELECT ON VIEW OPS.V_OFFSET_INTEGRITY    TO ROLE P15_READER;
GRANT SELECT ON VIEW OPS.V_FILE_STATS_LAST_DAY TO ROLE P15_READER;
GRANT SELECT ON VIEW OPS.V_PIPELINE_FRESHNESS  TO ROLE P15_READER;
GRANT SELECT ON VIEW OPS.V_LATENCY_LAST_HOUR   TO ROLE P15_READER;

CREATE OR REPLACE ALERT OPS.ALERT_RAW_STALE
  WAREHOUSE = P15_TRANSFORM_WH
  SCHEDULE = '10 MINUTE'
  IF (EXISTS (
    SELECT 1 FROM OPS.V_PIPELINE_FRESHNESS
    WHERE LAYER = 'RAW' AND SECONDS_SINCE_UPDATE > 600
  ))
  THEN
    CALL SYSTEM$SEND_EMAIL(
      'P15_EMAIL_INT',
      '<your-verified-email>',
      'P15: lake ingestion stale',
      'No new raw rows for more than 10 minutes. Check the lake writer, consumer lag, storage events, and SYSTEM$PIPE_STATUS.'
    );

ALTER ALERT OPS.ALERT_RAW_STALE RESUME;
