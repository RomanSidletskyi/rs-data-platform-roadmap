-- P15 data quality checks. Run as P15_OWNER after stopping producer and lake writer and waiting one task run.

USE ROLE P15_OWNER;
USE WAREHOUSE P15_TRANSFORM_WH;
USE DATABASE P15_WIKI_LAKE;

WITH checks AS (
  SELECT 'raw_duplicate_partition_offset' AS CHECK_NAME, COALESCE(SUM(DUPLICATE_OFFSETS), 0) AS FAILURES
  FROM OPS.V_OFFSET_INTEGRITY

  UNION ALL
  SELECT 'raw_missing_offsets', COALESCE(SUM(MISSING_OFFSETS), 0)
  FROM OPS.V_OFFSET_INTEGRITY

  UNION ALL
  SELECT 'stg_duplicate_event_id', COUNT(*)
  FROM (SELECT EVENT_ID FROM STG.WIKI_CHANGE GROUP BY EVENT_ID HAVING COUNT(*) > 1)

  UNION ALL
  SELECT 'stg_null_event_ts', COUNT(*) FROM STG.WIKI_CHANGE WHERE EVENT_TS IS NULL

  UNION ALL
  SELECT 'raw_events_missing_in_stg', COUNT(*)
  FROM (
    SELECT DISTINCT PAYLOAD:meta:id::STRING AS EVENT_ID
    FROM RAW.WIKI_RECENTCHANGE_RAW
    WHERE PAYLOAD:meta:id::STRING IS NOT NULL
      AND LOADED_AT < DATEADD('minute', -3, CURRENT_TIMESTAMP())
  ) r
  WHERE NOT EXISTS (SELECT 1 FROM STG.WIKI_CHANGE s WHERE s.EVENT_ID = r.EVENT_ID)
)
SELECT CHECK_NAME, FAILURES, IFF(FAILURES = 0, 'PASS', 'FAIL') AS RESULT
FROM checks
ORDER BY RESULT, CHECK_NAME;

-- Unparseable values are kept, not lost: list them for review.
SELECT KAFKA_PARTITION, KAFKA_OFFSET, LEFT(VALUE_RAW, 200) AS VALUE_RAW, SRC_FILE
FROM RAW.WIKI_RECENTCHANGE_RAW
WHERE PAYLOAD IS NULL;
