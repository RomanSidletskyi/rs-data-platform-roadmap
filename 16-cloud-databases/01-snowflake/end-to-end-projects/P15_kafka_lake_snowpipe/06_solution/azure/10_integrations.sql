-- P15 Azure integrations. Run as ACCOUNTADMIN via run_sql.sh after azure/01_provision.sh.

USE ROLE ACCOUNTADMIN;

CREATE STORAGE INTEGRATION IF NOT EXISTS P15_AZURE_STORAGE_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'AZURE'
  ENABLED = TRUE
  AZURE_TENANT_ID = '<tenant-id>'
  STORAGE_ALLOWED_LOCATIONS = ('azure://<storage-account>.blob.core.windows.net/landing/kafka/');

CREATE NOTIFICATION INTEGRATION IF NOT EXISTS P15_AZURE_QUEUE_INT
  ENABLED = TRUE
  TYPE = QUEUE
  NOTIFICATION_PROVIDER = AZURE_STORAGE_QUEUE
  AZURE_STORAGE_QUEUE_PRIMARY_URI = 'https://<storage-account>.queue.core.windows.net/snowpipe-p15'
  AZURE_TENANT_ID = '<tenant-id>';

-- Open AZURE_CONSENT_URL from each, accept, copy AZURE_MULTI_TENANT_APP_NAME for azure/02_grant_snowflake_access.sh.
DESC INTEGRATION P15_AZURE_STORAGE_INT;
DESC INTEGRATION P15_AZURE_QUEUE_INT;

GRANT USAGE ON INTEGRATION P15_AZURE_STORAGE_INT TO ROLE P15_OWNER;
GRANT USAGE ON INTEGRATION P15_AZURE_QUEUE_INT   TO ROLE P15_OWNER;
