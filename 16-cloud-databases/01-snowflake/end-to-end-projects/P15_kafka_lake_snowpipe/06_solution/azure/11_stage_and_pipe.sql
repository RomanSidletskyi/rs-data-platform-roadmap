-- P15 Azure stage and auto-ingest pipe. Run as P15_OWNER via run_sql.sh after role assignments propagated.

USE ROLE P15_OWNER;
USE WAREHOUSE P15_TRANSFORM_WH;
USE DATABASE P15_WIKI_LAKE;

CREATE STAGE IF NOT EXISTS RAW.LAKE_STAGE
  URL = 'azure://<storage-account>.blob.core.windows.net/landing/kafka/'
  STORAGE_INTEGRATION = P15_AZURE_STORAGE_INT
  FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_KAFKA_NDJSON')
  COMMENT = 'Lake files written by the lake writer: topic=/dt=/hour=/partition=/';

LIST @RAW.LAKE_STAGE/topic=wiki.recentchange/;

SELECT METADATA$FILENAME, $1:kafka:partition::NUMBER AS P, $1:kafka:offset::NUMBER AS O, $1:value:wiki::STRING AS WIKI
FROM @RAW.LAKE_STAGE/topic=wiki.recentchange/ (FILE_FORMAT => 'RAW.FF_KAFKA_NDJSON')
LIMIT 10;

CREATE PIPE IF NOT EXISTS RAW.WIKI_LAKE_PIPE
  AUTO_INGEST = TRUE
  INTEGRATION = 'P15_AZURE_QUEUE_INT'
  COMMENT = 'lake kafka/topic=wiki.recentchange -> RAW.WIKI_RECENTCHANGE_RAW'
AS
COPY INTO RAW.WIKI_RECENTCHANGE_RAW
  (PAYLOAD, VALUE_RAW, KAFKA_TOPIC, KAFKA_PARTITION, KAFKA_OFFSET, KAFKA_TS, SRC_FILE, LOADED_AT)
FROM (
  SELECT
    $1:value,
    $1:value_raw::STRING,
    $1:kafka:topic::STRING,
    $1:kafka:partition::NUMBER,
    $1:kafka:offset::NUMBER,
    TO_TIMESTAMP_LTZ($1:kafka:timestamp::NUMBER, 3),
    METADATA$FILENAME,
    METADATA$START_SCAN_TIME
  FROM @RAW.LAKE_STAGE/topic=wiki.recentchange/
)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_KAFKA_NDJSON')
ON_ERROR = SKIP_FILE;

ALTER PIPE RAW.WIKI_LAKE_PIPE REFRESH;
SELECT PARSE_JSON(SYSTEM$PIPE_STATUS('P15_WIKI_LAKE.RAW.WIKI_LAKE_PIPE')) AS PIPE_STATUS;
