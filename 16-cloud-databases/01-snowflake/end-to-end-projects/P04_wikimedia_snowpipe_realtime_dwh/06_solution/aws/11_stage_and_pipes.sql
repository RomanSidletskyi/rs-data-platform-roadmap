-- P04 AWS stage and auto-ingest pipes. Run as P04_OWNER.
-- Replace <bucket>. No notification integration: Snowflake provides an SQS queue per pipe set.

USE ROLE P04_OWNER;
USE WAREHOUSE P04_TRANSFORM_WH;
USE DATABASE P04_WIKI_RT;

CREATE STAGE IF NOT EXISTS RAW.LANDING_STAGE
  URL = 's3://<bucket>/landing/'
  STORAGE_INTEGRATION = P04_AWS_STORAGE_INT
  FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_WIKI_JSON')
  COMMENT = 'Landing prefix root: wiki/ and wiki_manifest/';

CREATE PIPE IF NOT EXISTS RAW.WIKI_RECENTCHANGE_PIPE
  AUTO_INGEST = TRUE
  COMMENT = 'landing/wiki -> RAW.WIKI_RECENTCHANGE_RAW'
AS
COPY INTO RAW.WIKI_RECENTCHANGE_RAW (PAYLOAD, SRC_FILE, SRC_FILE_ROW, SRC_FILE_LAST_MODIFIED, LOADED_AT)
FROM (
  SELECT $1, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, METADATA$FILE_LAST_MODIFIED, METADATA$START_SCAN_TIME
  FROM @RAW.LANDING_STAGE/wiki/
)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_WIKI_JSON')
ON_ERROR = SKIP_FILE;

CREATE PIPE IF NOT EXISTS OPS.PRODUCER_MANIFEST_PIPE
  AUTO_INGEST = TRUE
  COMMENT = 'landing/wiki_manifest -> OPS.PRODUCER_MANIFEST'
AS
COPY INTO OPS.PRODUCER_MANIFEST (PAYLOAD, SRC_FILE, LOADED_AT)
FROM (
  SELECT $1, METADATA$FILENAME, METADATA$START_SCAN_TIME
  FROM @RAW.LANDING_STAGE/wiki_manifest/
)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_WIKI_JSON')
ON_ERROR = SKIP_FILE;

-- notification_channel is the SQS ARN for aws/02_connect_snowflake.sh; both pipes normally share it.
SHOW PIPES IN DATABASE P04_WIKI_RT;

-- Stop here, run aws/02_connect_snowflake.sh, then continue: LIST fails until the role trust is updated.
LIST @RAW.LANDING_STAGE/wiki/;

ALTER PIPE RAW.WIKI_RECENTCHANGE_PIPE REFRESH;
ALTER PIPE OPS.PRODUCER_MANIFEST_PIPE REFRESH;
