-- P04 teardown: removes every Snowflake object the project created. Run as ACCOUNTADMIN.
-- Cloud resources are removed separately (see 06_solution/README.md, section Cleanup).

USE ROLE ACCOUNTADMIN;

-- Dropping the database removes pipes, stream, task, dynamic table, views, alert, and tables.
DROP DATABASE IF EXISTS P04_WIKI_RT;

DROP WAREHOUSE IF EXISTS P04_TRANSFORM_WH;
DROP WAREHOUSE IF EXISTS P04_BI_WH;
DROP RESOURCE MONITOR IF EXISTS P04_RM;

DROP INTEGRATION IF EXISTS P04_AZURE_STORAGE_INT;
DROP INTEGRATION IF EXISTS P04_AZURE_QUEUE_INT;
DROP INTEGRATION IF EXISTS P04_AWS_STORAGE_INT;
DROP INTEGRATION IF EXISTS P04_EMAIL_INT;

DROP ROLE IF EXISTS P04_READER;
DROP ROLE IF EXISTS P04_OWNER;

-- Verify nothing named P04_ remains.
SHOW WAREHOUSES LIKE 'P04_%';
SHOW INTEGRATIONS LIKE 'P04_%';
SHOW ROLES LIKE 'P04_%';
