USE ROLE P04_OWNER;
USE WAREHOUSE P04_TRANSFORM_WH;
USE DATABASE P04_WIKI_RT;

-- Manifest files vs rows actually loaded. Full scan of raw: fine for a lab, replace with an audit table at scale.
CREATE OR REPLACE VIEW OPS.V_FILE_RECONCILIATION AS
WITH manifest AS (
  SELECT
    PAYLOAD:file_basename::STRING                         AS FILE_BASENAME,
    PAYLOAD:file_name::STRING                             AS FILE_NAME,
    PAYLOAD:row_count::NUMBER                             AS EXPECTED_ROWS,
    TRY_TO_TIMESTAMP_TZ(PAYLOAD:file_written_at::STRING)  AS FILE_WRITTEN_AT,
    PAYLOAD:producer_id::STRING                           AS PRODUCER_ID
  FROM OPS.PRODUCER_MANIFEST
  QUALIFY ROW_NUMBER() OVER (PARTITION BY PAYLOAD:file_basename::STRING ORDER BY LOADED_AT) = 1
),
loaded AS (
  -- Match on the unique base name: the path prefix in METADATA$FILENAME depends on the stage URL.
  SELECT
    SPLIT_PART(SRC_FILE, '/', -1) AS FILE_BASENAME,
    COUNT(*)                      AS LOADED_ROWS,
    MIN(LOADED_AT)                AS FIRST_LOADED_AT
  FROM RAW.WIKI_RECENTCHANGE_RAW
  GROUP BY 1
)
SELECT
  COALESCE(m.FILE_BASENAME, l.FILE_BASENAME) AS FILE_BASENAME,
  m.FILE_NAME,
  m.PRODUCER_ID,
  m.EXPECTED_ROWS,
  l.LOADED_ROWS,
  m.FILE_WRITTEN_AT,
  l.FIRST_LOADED_AT,
  DATEDIFF('second', m.FILE_WRITTEN_AT, l.FIRST_LOADED_AT) AS FILE_TO_RAW_SECONDS,
  CASE
    WHEN m.FILE_BASENAME IS NULL THEN 'UNEXPECTED_FILE'
    WHEN l.FILE_BASENAME IS NULL
         AND m.FILE_WRITTEN_AT < DATEADD('minute', -15, CURRENT_TIMESTAMP()) THEN 'MISSING'
    WHEN l.FILE_BASENAME IS NULL THEN 'PENDING'
    WHEN l.LOADED_ROWS <> m.EXPECTED_ROWS THEN 'ROW_COUNT_MISMATCH'
    ELSE 'OK'
  END AS RECON_STATUS
FROM manifest m
FULL OUTER JOIN loaded l
  ON m.FILE_BASENAME = l.FILE_BASENAME;

CREATE OR REPLACE VIEW OPS.V_PIPELINE_FRESHNESS AS
WITH last_updates AS (
  SELECT 'RAW' AS LAYER, MAX(LOADED_AT) AS LAST_UPDATE_AT FROM RAW.WIKI_RECENTCHANGE_RAW
  UNION ALL
  SELECT 'STG', MAX(STAGED_AT) FROM STG.WIKI_CHANGE
  UNION ALL
  SELECT 'MANIFEST', MAX(LOADED_AT) FROM OPS.PRODUCER_MANIFEST
)
SELECT
  LAYER,
  LAST_UPDATE_AT,
  DATEDIFF('second', LAST_UPDATE_AT, CURRENT_TIMESTAMP()) AS SECONDS_SINCE_UPDATE
FROM last_updates;

-- Late events (drill M7) inflate these numbers on purpose: they measure event time, not load time.
CREATE OR REPLACE VIEW OPS.V_LATENCY_LAST_HOUR AS
SELECT
  COUNT(*)                                                           AS EVENTS,
  APPROX_PERCENTILE(DATEDIFF('second', EVENT_TS, LOADED_AT), 0.50)   AS P50_EVENT_TO_RAW_S,
  APPROX_PERCENTILE(DATEDIFF('second', EVENT_TS, LOADED_AT), 0.95)   AS P95_EVENT_TO_RAW_S,
  APPROX_PERCENTILE(DATEDIFF('second', LOADED_AT, STAGED_AT), 0.50)  AS P50_RAW_TO_STG_S,
  APPROX_PERCENTILE(DATEDIFF('second', LOADED_AT, STAGED_AT), 0.95)  AS P95_RAW_TO_STG_S,
  APPROX_PERCENTILE(DATEDIFF('second', EVENT_TS, STAGED_AT), 0.50)   AS P50_EVENT_TO_STG_S,
  APPROX_PERCENTILE(DATEDIFF('second', EVENT_TS, STAGED_AT), 0.95)   AS P95_EVENT_TO_STG_S
FROM STG.WIKI_CHANGE
WHERE STAGED_AT >= DATEADD('hour', -1, CURRENT_TIMESTAMP());

CREATE OR REPLACE VIEW OPS.V_FILE_LATENCY_LAST_HOUR AS
SELECT
  COUNT(*)                                         AS FILES,
  APPROX_PERCENTILE(FILE_TO_RAW_SECONDS, 0.50)     AS P50_FILE_TO_RAW_S,
  APPROX_PERCENTILE(FILE_TO_RAW_SECONDS, 0.95)     AS P95_FILE_TO_RAW_S,
  MAX(FILE_TO_RAW_SECONDS)                         AS MAX_FILE_TO_RAW_S
FROM OPS.V_FILE_RECONCILIATION
WHERE FIRST_LOADED_AT >= DATEADD('hour', -1, CURRENT_TIMESTAMP());

GRANT SELECT ON VIEW OPS.V_FILE_RECONCILIATION    TO ROLE P04_READER;
GRANT SELECT ON VIEW OPS.V_PIPELINE_FRESHNESS     TO ROLE P04_READER;
GRANT SELECT ON VIEW OPS.V_LATENCY_LAST_HOUR      TO ROLE P04_READER;
GRANT SELECT ON VIEW OPS.V_FILE_LATENCY_LAST_HOUR TO ROLE P04_READER;

-- Runs on the same warehouse as the dynamic table so most checks reuse an already running warehouse.
CREATE OR REPLACE ALERT OPS.ALERT_RAW_STALE
  WAREHOUSE = P04_TRANSFORM_WH
  SCHEDULE = '10 MINUTE'
  IF (EXISTS (
    SELECT 1
    FROM OPS.V_PIPELINE_FRESHNESS
    WHERE LAYER = 'RAW'
      AND SECONDS_SINCE_UPDATE > 600
  ))
  THEN
    CALL SYSTEM$SEND_EMAIL(
      'P04_EMAIL_INT',
      '<your-verified-email>',
      'P04: raw layer is stale',
      'No new raw rows for more than 10 minutes. Check the producer, SYSTEM$PIPE_STATUS, and OPS.V_FILE_RECONCILIATION.'
    );

ALTER ALERT OPS.ALERT_RAW_STALE RESUME;
