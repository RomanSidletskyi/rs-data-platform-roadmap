-- P04 dashboard tiles and operational queries. Run as P04_READER for tiles, P04_OWNER for ops.

USE DATABASE P04_WIKI_RT;

-- =====================================================================
-- Dashboard tiles (Snowsight: one query per tile). Role P04_READER, warehouse P04_BI_WH.
-- =====================================================================
USE ROLE P04_READER;
USE WAREHOUSE P04_BI_WH;

-- Tile 1: edits per minute, top 8 wikis, last 60 minutes (line chart: MINUTE_TS x CHANGES by WIKI)
WITH top_wikis AS (
  SELECT WIKI
  FROM MART.EDITS_PER_MINUTE
  WHERE MINUTE_TS >= DATEADD('minute', -60, CURRENT_TIMESTAMP())
  GROUP BY WIKI
  ORDER BY SUM(CHANGE_COUNT) DESC
  LIMIT 8
)
SELECT e.MINUTE_TS, e.WIKI, SUM(e.CHANGE_COUNT) AS CHANGES
FROM MART.EDITS_PER_MINUTE e
JOIN top_wikis t ON t.WIKI = e.WIKI
WHERE e.MINUTE_TS >= DATEADD('minute', -60, CURRENT_TIMESTAMP())
GROUP BY e.MINUTE_TS, e.WIKI
ORDER BY e.MINUTE_TS;

-- Tile 2: bot share by wiki (bar chart)
SELECT WIKI, CHANGES, BOT_CHANGES, ROUND(BOT_SHARE * 100, 1) AS BOT_SHARE_PCT
FROM MART.V_BOT_SHARE_LAST_HOUR
ORDER BY CHANGES DESC
LIMIT 15;

-- Tile 3: hot pages (table)
SELECT WIKI, TITLE, CHANGE_COUNT, DISTINCT_USERS, BOT_CHANGES, LAST_CHANGE_TS
FROM MART.V_TOP_PAGES_LAST_HOUR
ORDER BY CHANGE_COUNT DESC
LIMIT 20;

-- Tile 4: freshness scorecard
SELECT LAYER, LAST_UPDATE_AT, SECONDS_SINCE_UPDATE FROM OPS.V_PIPELINE_FRESHNESS;

-- Tile 5: latency scorecard
SELECT * FROM OPS.V_LATENCY_LAST_HOUR;
SELECT * FROM OPS.V_FILE_LATENCY_LAST_HOUR;

-- Tile 6: reconciliation summary
SELECT RECON_STATUS, COUNT(*) AS FILES, SUM(EXPECTED_ROWS) AS EXPECTED_ROWS, SUM(LOADED_ROWS) AS LOADED_ROWS
FROM OPS.V_FILE_RECONCILIATION
GROUP BY RECON_STATUS
ORDER BY RECON_STATUS;

-- =====================================================================
-- Operational queries. Role P04_OWNER.
-- =====================================================================
USE ROLE P04_OWNER;
USE WAREHOUSE P04_TRANSFORM_WH;

-- Pipe health: executionState, pendingFileCount, lastIngestedTimestamp, lastReceivedMessageTimestamp
SELECT PARSE_JSON(SYSTEM$PIPE_STATUS('P04_WIKI_RT.RAW.WIKI_RECENTCHANGE_PIPE')) AS DATA_PIPE_STATUS;
SELECT PARSE_JSON(SYSTEM$PIPE_STATUS('P04_WIKI_RT.OPS.PRODUCER_MANIFEST_PIPE')) AS MANIFEST_PIPE_STATUS;

-- Files loaded or rejected in the last hour
SELECT FILE_NAME, STATUS, ROW_COUNT, ROW_PARSED, ERROR_COUNT, FIRST_ERROR_MESSAGE, PIPE_RECEIVED_TIME, LAST_LOAD_TIME
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
  TABLE_NAME => 'P04_WIKI_RT.RAW.WIKI_RECENTCHANGE_RAW',
  START_TIME => DATEADD('hour', -1, CURRENT_TIMESTAMP())))
ORDER BY LAST_LOAD_TIME DESC;

-- Errors Snowpipe hit in the last hour
SELECT *
FROM TABLE(INFORMATION_SCHEMA.VALIDATE_PIPE_LOAD(
  PIPE_NAME  => 'P04_WIKI_RT.RAW.WIKI_RECENTCHANGE_PIPE',
  START_TIME => DATEADD('hour', -1, CURRENT_TIMESTAMP())));

-- Task runs
SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
  TASK_NAME => 'LOAD_WIKI_CHANGE',
  SCHEDULED_TIME_RANGE_START => DATEADD('hour', -1, CURRENT_TIMESTAMP())))
ORDER BY SCHEDULED_TIME DESC;

-- Dynamic table refreshes
SELECT NAME, STATE, REFRESH_ACTION, REFRESH_START_TIME, REFRESH_END_TIME, DATA_TIMESTAMP
FROM TABLE(INFORMATION_SCHEMA.DYNAMIC_TABLE_REFRESH_HISTORY(
  NAME => 'P04_WIKI_RT.MART.EDITS_PER_MINUTE'))
ORDER BY REFRESH_START_TIME DESC
LIMIT 20;

-- Alert runs
SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, SQL_ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.ALERT_HISTORY(
  SCHEDULED_TIME_RANGE_START => DATEADD('hour', -2, CURRENT_TIMESTAMP())))
ORDER BY SCHEDULED_TIME DESC;

-- Credits in the last 24 hours, per component
SELECT 'warehouse' AS COMPONENT, WAREHOUSE_NAME AS NAME, SUM(CREDITS_USED) AS CREDITS
FROM TABLE(INFORMATION_SCHEMA.WAREHOUSE_METERING_HISTORY(DATE_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP())))
WHERE WAREHOUSE_NAME LIKE 'P04_%'
GROUP BY WAREHOUSE_NAME
UNION ALL
SELECT 'snowpipe', PIPE_NAME, SUM(CREDITS_USED)
FROM TABLE(INFORMATION_SCHEMA.PIPE_USAGE_HISTORY(DATE_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP())))
GROUP BY PIPE_NAME
UNION ALL
SELECT 'serverless_task', TASK_NAME, SUM(CREDITS_USED)
FROM TABLE(INFORMATION_SCHEMA.SERVERLESS_TASK_HISTORY(DATE_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP())))
GROUP BY TASK_NAME;
