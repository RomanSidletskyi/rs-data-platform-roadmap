-- P04 pause: stop every scheduled or event-driven object after a lab session. Run as P04_OWNER.

USE ROLE P04_OWNER;
USE DATABASE P04_WIKI_RT;

ALTER ALERT IF EXISTS OPS.ALERT_RAW_STALE SUSPEND;
ALTER TASK IF EXISTS STG.LOAD_WIKI_CHANGE SUSPEND;
ALTER DYNAMIC TABLE IF EXISTS MART.EDITS_PER_MINUTE SUSPEND;
-- Paused pipes keep receiving notifications and process them on resume.
ALTER PIPE IF EXISTS RAW.WIKI_RECENTCHANGE_PIPE SET PIPE_EXECUTION_PAUSED = TRUE;
ALTER PIPE IF EXISTS OPS.PRODUCER_MANIFEST_PIPE SET PIPE_EXECUTION_PAUSED = TRUE;

-- Verify: tasks suspended, dynamic table SUSPENDED, pipes PAUSED.
SHOW TASKS IN DATABASE P04_WIKI_RT;
SHOW DYNAMIC TABLES IN DATABASE P04_WIKI_RT;
SELECT PARSE_JSON(SYSTEM$PIPE_STATUS('P04_WIKI_RT.RAW.WIKI_RECENTCHANGE_PIPE')):executionState::STRING AS DATA_PIPE;
SELECT PARSE_JSON(SYSTEM$PIPE_STATUS('P04_WIKI_RT.OPS.PRODUCER_MANIFEST_PIPE')):executionState::STRING AS MANIFEST_PIPE;

-- Last: fails harmlessly if the warehouse is already suspended.
ALTER WAREHOUSE P04_TRANSFORM_WH SUSPEND;
