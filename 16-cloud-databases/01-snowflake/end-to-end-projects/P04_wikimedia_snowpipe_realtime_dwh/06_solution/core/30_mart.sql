-- P04 serving layer: dynamic table for minute aggregates, views for time-relative questions. Run as P04_OWNER.

USE ROLE P04_OWNER;
USE WAREHOUSE P04_TRANSFORM_WH;
USE DATABASE P04_WIKI_RT;

-- Lag is a cost dial: each refresh resumes the warehouse for at least 60 s.
CREATE OR REPLACE DYNAMIC TABLE MART.EDITS_PER_MINUTE
  TARGET_LAG = '5 minutes'
  WAREHOUSE = P04_TRANSFORM_WH
  REFRESH_MODE = INCREMENTAL
  COMMENT = 'Grain: minute x wiki x change type x bot flag'
AS
SELECT
  DATE_TRUNC('minute', EVENT_TS) AS MINUTE_TS,
  WIKI,
  CHANGE_TYPE,
  IS_BOT,
  COUNT(*)                       AS CHANGE_COUNT,
  SUM(LENGTH_DELTA)              AS BYTES_DELTA
FROM STG.WIKI_CHANGE
WHERE EVENT_TS IS NOT NULL
GROUP BY 1, 2, 3, 4;

-- Depends on CURRENT_TIMESTAMP, so it is a view, not a dynamic table.
CREATE OR REPLACE VIEW MART.V_TOP_PAGES_LAST_HOUR AS
SELECT
  WIKI,
  TITLE,
  COUNT(*)                  AS CHANGE_COUNT,
  COUNT(DISTINCT USER_NAME) AS DISTINCT_USERS,
  COUNT_IF(IS_BOT)          AS BOT_CHANGES,
  MAX(EVENT_TS)             AS LAST_CHANGE_TS
FROM STG.WIKI_CHANGE
WHERE EVENT_TS >= DATEADD('hour', -1, CURRENT_TIMESTAMP())
GROUP BY WIKI, TITLE
QUALIFY ROW_NUMBER() OVER (ORDER BY COUNT(*) DESC) <= 50;

CREATE OR REPLACE VIEW MART.V_BOT_SHARE_LAST_HOUR AS
SELECT
  WIKI,
  SUM(CHANGE_COUNT)                                           AS CHANGES,
  SUM(IFF(IS_BOT, CHANGE_COUNT, 0))                           AS BOT_CHANGES,
  DIV0(SUM(IFF(IS_BOT, CHANGE_COUNT, 0)), SUM(CHANGE_COUNT))  AS BOT_SHARE
FROM MART.EDITS_PER_MINUTE
WHERE MINUTE_TS >= DATEADD('hour', -1, CURRENT_TIMESTAMP())
GROUP BY WIKI
HAVING SUM(CHANGE_COUNT) >= 20;

GRANT SELECT ON DYNAMIC TABLE MART.EDITS_PER_MINUTE TO ROLE P04_READER;
GRANT SELECT ON VIEW MART.V_TOP_PAGES_LAST_HOUR TO ROLE P04_READER;
GRANT SELECT ON VIEW MART.V_BOT_SHARE_LAST_HOUR TO ROLE P04_READER;

-- REFRESH_MODE = INCREMENTAL fails at creation if the query cannot refresh incrementally; check the reason here.
SHOW DYNAMIC TABLES LIKE 'EDITS_PER_MINUTE' IN SCHEMA MART;
