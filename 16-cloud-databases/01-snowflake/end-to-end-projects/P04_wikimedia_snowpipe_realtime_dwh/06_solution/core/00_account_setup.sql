-- P04 account-level setup. Run once as ACCOUNTADMIN.
-- Replace <your-verified-email> before running the last section.

USE ROLE ACCOUNTADMIN;

-- Roles
CREATE ROLE IF NOT EXISTS P04_OWNER;
CREATE ROLE IF NOT EXISTS P04_READER;
GRANT ROLE P04_READER TO ROLE P04_OWNER;
GRANT ROLE P04_OWNER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P04_OWNER TO USER IDENTIFIER($my_user);
GRANT ROLE P04_READER TO USER IDENTIFIER($my_user);

-- Cost guardrail: applies to warehouses only, not to Snowpipe or serverless tasks.
CREATE RESOURCE MONITOR IF NOT EXISTS P04_RM
  WITH CREDIT_QUOTA = 5
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS P04_TRANSFORM_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 600
  RESOURCE_MONITOR = P04_RM
  COMMENT = 'P04 dynamic table refresh, alert, ad hoc engineering';

CREATE WAREHOUSE IF NOT EXISTS P04_BI_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300
  RESOURCE_MONITOR = P04_RM
  COMMENT = 'P04 dashboards';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P04_TRANSFORM_WH TO ROLE P04_OWNER;
GRANT USAGE, OPERATE ON WAREHOUSE P04_BI_WH TO ROLE P04_OWNER;
GRANT USAGE ON WAREHOUSE P04_BI_WH TO ROLE P04_READER;

-- Database owned by the project role
CREATE DATABASE IF NOT EXISTS P04_WIKI_RT COMMENT = 'P04 Wikimedia near-real-time DWH';
GRANT OWNERSHIP ON DATABASE P04_WIKI_RT TO ROLE P04_OWNER COPY CURRENT GRANTS;

-- Account privileges needed by the pipeline objects
GRANT EXECUTE TASK, EXECUTE MANAGED TASK, EXECUTE ALERT ON ACCOUNT TO ROLE P04_OWNER;

-- Email notifications for the freshness alert. Recipients must be verified emails of users in this account.
CREATE NOTIFICATION INTEGRATION IF NOT EXISTS P04_EMAIL_INT
  TYPE = EMAIL
  ENABLED = TRUE
  ALLOWED_RECIPIENTS = ('<your-verified-email>');
GRANT USAGE ON INTEGRATION P04_EMAIL_INT TO ROLE P04_OWNER;
