-- P07 objects: stages, raw table, and the tables the Snowpark pipeline writes into. Run as P07_OWNER.
-- Tables are defined here, not by the pipeline: the schema is a contract, and save_as_table only appends.

USE ROLE P07_OWNER;
USE WAREHOUSE P07_WH;
USE DATABASE P07_RETAIL;

CREATE SCHEMA IF NOT EXISTS RAW  COMMENT = 'Monthly files as delivered';
CREATE SCHEMA IF NOT EXISTS STG  COMMENT = 'Classified lines and rejects';
CREATE SCHEMA IF NOT EXISTS MART COMMENT = 'Daily sales, product months, customer RFM';
CREATE SCHEMA IF NOT EXISTS OPS  COMMENT = 'Code stage, procedure, task, run log, month status';

CREATE FILE FORMAT IF NOT EXISTS RAW.FF_CSV
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE;

CREATE STAGE IF NOT EXISTS RAW.RETAIL_STAGE
  FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_CSV')
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'month=YYYY-MM/online_retail_<sheet>.csv.gz';

CREATE STAGE IF NOT EXISTS OPS.CODE_STAGE
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'retail_pipeline.zip imported by the stored procedure';

CREATE TABLE IF NOT EXISTS RAW.ONLINE_RETAIL (
  INVOICE      STRING,
  STOCK_CODE   STRING,
  DESCRIPTION  STRING,
  QUANTITY     NUMBER,
  INVOICE_DATE TIMESTAMP_NTZ,
  PRICE        NUMBER(12, 3),
  CUSTOMER_ID  NUMBER,
  COUNTRY      STRING,
  MONTH        STRING,
  SRC_FILE     STRING,
  LOADED_AT    TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS STG.SALES_LINE (
  INVOICE STRING, STOCK_CODE STRING, DESCRIPTION STRING, QUANTITY NUMBER, INVOICE_DATE TIMESTAMP_NTZ,
  PRICE NUMBER(12, 3), CUSTOMER_ID NUMBER, COUNTRY STRING,
  IS_RETURN BOOLEAN, LINE_TYPE STRING, REVENUE NUMBER(18, 3), SALE_DATE DATE, MONTH STRING
);

CREATE TABLE IF NOT EXISTS STG.REJECTED_LINE (
  INVOICE STRING, STOCK_CODE STRING, DESCRIPTION STRING, QUANTITY NUMBER, INVOICE_DATE TIMESTAMP_NTZ,
  PRICE NUMBER(12, 3), CUSTOMER_ID NUMBER, COUNTRY STRING,
  IS_RETURN BOOLEAN, LINE_TYPE STRING, REVENUE NUMBER(18, 3), SALE_DATE DATE, REJECT_REASON STRING, MONTH STRING
);

CREATE TABLE IF NOT EXISTS MART.DAILY_SALES (
  SALE_DATE DATE, COUNTRY STRING, INVOICES NUMBER, CUSTOMERS NUMBER, UNITS_SOLD NUMBER,
  GROSS_REVENUE NUMBER(18, 3), RETURNS_REVENUE NUMBER(18, 3), NET_REVENUE NUMBER(18, 3), FEE_REVENUE NUMBER(18, 3)
);

CREATE TABLE IF NOT EXISTS MART.PRODUCT_MONTHLY (
  MONTH_START DATE, STOCK_CODE STRING, DESCRIPTION STRING, UNITS_SOLD NUMBER, UNITS_RETURNED NUMBER,
  NET_REVENUE NUMBER(18, 3)
);

CREATE TABLE IF NOT EXISTS MART.CUSTOMER_RFM (
  CUSTOMER_ID NUMBER, LAST_PURCHASE DATE, FREQUENCY NUMBER, MONETARY NUMBER(18, 3), AS_OF DATE,
  RECENCY_DAYS NUMBER, R_SCORE NUMBER, F_SCORE NUMBER, M_SCORE NUMBER, SEGMENT STRING
);

CREATE TABLE IF NOT EXISTS OPS.MONTH_STATUS (
  MONTH        STRING,
  PROCESSED_AT TIMESTAMP_LTZ,
  ACCEPTED     NUMBER,
  REJECTED     NUMBER
);

CREATE TABLE IF NOT EXISTS OPS.RUN_LOG (
  RUN_AT TIMESTAMP_LTZ,
  STEP   STRING,
  NOTE   STRING
);

GRANT USAGE ON DATABASE P07_RETAIL TO ROLE P07_READER;
GRANT USAGE ON SCHEMA MART TO ROLE P07_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA MART TO ROLE P07_READER;
