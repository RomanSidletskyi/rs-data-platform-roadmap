-- P07 account-level setup. Run once as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS P07_OWNER;
CREATE ROLE IF NOT EXISTS P07_READER;
GRANT ROLE P07_READER TO ROLE P07_OWNER;
GRANT ROLE P07_OWNER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P07_OWNER TO USER IDENTIFIER($my_user);
GRANT ROLE P07_READER TO USER IDENTIFIER($my_user);

CREATE RESOURCE MONITOR IF NOT EXISTS P07_RM
  WITH CREDIT_QUOTA = 3
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

-- Snowpark DataFrame work runs here whether started from a laptop or from the stored procedure.
CREATE WAREHOUSE IF NOT EXISTS P07_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800
  RESOURCE_MONITOR = P07_RM
  COMMENT = 'P07 Snowpark pipeline and ad hoc';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P07_WH TO ROLE P07_OWNER;
GRANT USAGE ON WAREHOUSE P07_WH TO ROLE P07_READER;

CREATE DATABASE IF NOT EXISTS P07_RETAIL COMMENT = 'P07 UCI Online Retail II with Snowpark';
GRANT OWNERSHIP ON DATABASE P07_RETAIL TO ROLE P07_OWNER COPY CURRENT GRANTS;

GRANT EXECUTE TASK, EXECUTE MANAGED TASK ON ACCOUNT TO ROLE P07_OWNER;
