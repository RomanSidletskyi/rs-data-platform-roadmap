-- P07 checks. Run as P07_OWNER after the pipeline.

USE ROLE P07_OWNER;
USE WAREHOUSE P07_WH;
USE DATABASE P07_RETAIL;

WITH raw_distinct AS (
  SELECT MONTH, COUNT(*) AS N
  FROM (SELECT DISTINCT INVOICE, STOCK_CODE, DESCRIPTION, QUANTITY, INVOICE_DATE, PRICE, CUSTOMER_ID, COUNTRY, MONTH FROM RAW.ONLINE_RETAIL)
  GROUP BY 1
),
processed AS (
  SELECT MONTH, SUM(N) AS N FROM (
    SELECT MONTH, COUNT(*) AS N FROM STG.SALES_LINE GROUP BY 1
    UNION ALL
    SELECT MONTH, COUNT(*) FROM STG.REJECTED_LINE GROUP BY 1
  ) GROUP BY 1
),
checks AS (
  -- Every distinct raw line is either accepted or rejected, in every month.
  SELECT 'lines_lost_or_invented' AS CHECK_NAME, COUNT(*) AS FAILURES
  FROM raw_distinct r FULL OUTER JOIN processed p ON p.MONTH = r.MONTH
  WHERE r.N IS DISTINCT FROM p.N

  UNION ALL
  SELECT 'pending_months', COUNT(*)
  FROM (SELECT DISTINCT MONTH FROM RAW.ONLINE_RETAIL) r
  WHERE NOT EXISTS (SELECT 1 FROM OPS.MONTH_STATUS s WHERE s.MONTH = r.MONTH)

  UNION ALL
  SELECT 'daily_net_differs_from_lines', COUNT(*)
  FROM (
    SELECT SALE_DATE, COUNTRY, SUM(IFF(LINE_TYPE = 'product', REVENUE, 0)) AS NET
    FROM STG.SALES_LINE GROUP BY 1, 2
  ) l
  FULL OUTER JOIN MART.DAILY_SALES d ON d.SALE_DATE = l.SALE_DATE AND d.COUNTRY = l.COUNTRY
  WHERE l.NET IS DISTINCT FROM d.NET_REVENUE

  UNION ALL
  SELECT 'accepted_line_with_non_positive_price', COUNT(*) FROM STG.SALES_LINE WHERE PRICE <= 0

  UNION ALL
  SELECT 'return_with_positive_quantity', COUNT(*) FROM STG.SALES_LINE WHERE IS_RETURN AND QUANTITY > 0

  UNION ALL
  SELECT 'rfm_score_out_of_range', COUNT(*)
  FROM MART.CUSTOMER_RFM WHERE R_SCORE NOT BETWEEN 1 AND 5 OR F_SCORE NOT BETWEEN 1 AND 5 OR M_SCORE NOT BETWEEN 1 AND 5
)
SELECT CHECK_NAME, FAILURES, IFF(FAILURES = 0, 'PASS', 'FAIL') AS RESULT
FROM checks
ORDER BY RESULT, CHECK_NAME;

-- Read, do not just pass: where the dirt is.
SELECT REJECT_REASON, COUNT(*) AS LINES, SUM(REVENUE) AS REVENUE FROM STG.REJECTED_LINE GROUP BY 1 ORDER BY 2 DESC;
-- COUNT(DISTINCT a, b, ...) would skip rows with any NULL column, so duplicates are counted against a DISTINCT subquery.
SELECT r.MONTH, r.ROWS_ - d.N AS DUPLICATE_ROWS
FROM (SELECT MONTH, COUNT(*) AS ROWS_ FROM RAW.ONLINE_RETAIL GROUP BY 1) r
JOIN (
  SELECT MONTH, COUNT(*) AS N
  FROM (SELECT DISTINCT INVOICE, STOCK_CODE, DESCRIPTION, QUANTITY, INVOICE_DATE, PRICE, CUSTOMER_ID, COUNTRY, MONTH FROM RAW.ONLINE_RETAIL)
  GROUP BY 1
) d ON d.MONTH = r.MONTH
ORDER BY 2 DESC
LIMIT 5;
SELECT SEGMENT, COUNT(*) AS CUSTOMERS, ROUND(SUM(MONETARY)) AS REVENUE FROM MART.CUSTOMER_RFM GROUP BY 1 ORDER BY 3 DESC;
