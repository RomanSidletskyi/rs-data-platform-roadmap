-- P05 teardown. Run as ACCOUNTADMIN. Dropping the database removes tasks, streams, and dynamic tables.

USE ROLE ACCOUNTADMIN;

ALTER TASK IF EXISTS P05_CDC.PIPE.CDC_ROOT SUSPEND;
DROP DATABASE IF EXISTS P05_CDC;
DROP WAREHOUSE IF EXISTS P05_WH;
DROP RESOURCE MONITOR IF EXISTS P05_RM;
DROP ROLE IF EXISTS P05_READER;
DROP ROLE IF EXISTS P05_OWNER;

SHOW WAREHOUSES LIKE 'P05_%';
SHOW ROLES LIKE 'P05_%';
