-- P05 checks. Run as P05_OWNER after at least one graph run.

USE ROLE P05_OWNER;
USE WAREHOUSE P05_WH;
USE DATABASE P05_CDC;

WITH checks AS (
  SELECT 'mart_differs_from_source' AS CHECK_NAME, COUNT(*) AS FAILURES FROM OPS.V_RECONCILIATION

  UNION ALL
  SELECT 'fact_differs_from_current_order_state', COUNT(*)
  FROM (
    SELECT ORDER_KEY, ORDER_STATUS, LINE_COUNT, NET_REVENUE FROM CORE.V_ORDER_CURRENT
    EXCEPT
    SELECT ORDER_KEY, ORDER_STATUS, LINE_COUNT, NET_REVENUE FROM CORE.FACT_ORDER
  )

  UNION ALL
  SELECT 'fact_order_not_in_source', COUNT(*)
  FROM CORE.FACT_ORDER f
  WHERE NOT EXISTS (SELECT 1 FROM SRC.ORDERS o WHERE o.O_ORDERKEY = f.ORDER_KEY)

  UNION ALL
  SELECT 'duplicate_fact_order', COUNT(*)
  FROM (SELECT ORDER_KEY FROM CORE.FACT_ORDER GROUP BY 1 HAVING COUNT(*) > 1)

  UNION ALL
  SELECT 'customer_balance_differs', COUNT(*)
  FROM CORE.DIM_CUSTOMER d
  JOIN SRC.CUSTOMER c ON c.C_CUSTKEY = d.CUSTOMER_KEY
  WHERE d.ACCOUNT_BALANCE IS DISTINCT FROM c.C_ACCTBAL OR d.MARKET_SEGMENT IS DISTINCT FROM c.C_MKTSEGMENT

  UNION ALL
  SELECT 'orders_without_lines', COUNT(*)
  FROM CORE.FACT_ORDER WHERE LINE_COUNT = 0
)
SELECT CHECK_NAME, FAILURES, IFF(FAILURES = 0, 'PASS', 'FAIL') AS RESULT
FROM checks
ORDER BY RESULT, CHECK_NAME;
