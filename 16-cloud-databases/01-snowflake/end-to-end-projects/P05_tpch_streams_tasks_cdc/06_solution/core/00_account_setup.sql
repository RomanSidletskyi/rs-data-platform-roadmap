-- P05 account-level setup. Run once as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;

-- Most accounts already have this shared database. If not, uncomment:
-- CREATE DATABASE IF NOT EXISTS SNOWFLAKE_SAMPLE_DATA FROM SHARE SFC_SAMPLES.SAMPLE_DATA;

CREATE ROLE IF NOT EXISTS P05_OWNER;
CREATE ROLE IF NOT EXISTS P05_READER;
GRANT ROLE P05_READER TO ROLE P05_OWNER;
GRANT ROLE P05_OWNER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE P05_OWNER TO USER IDENTIFIER($my_user);
GRANT ROLE P05_READER TO USER IDENTIFIER($my_user);

CREATE RESOURCE MONITOR IF NOT EXISTS P05_RM
  WITH CREDIT_QUOTA = 3
  FREQUENCY = DAILY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

-- Used for setup, the simulator, the dynamic table comparison, and ad hoc queries. Tasks are serverless.
CREATE WAREHOUSE IF NOT EXISTS P05_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 900
  RESOURCE_MONITOR = P05_RM
  COMMENT = 'P05 setup, simulator, dynamic tables, ad hoc';

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE P05_WH TO ROLE P05_OWNER;
GRANT USAGE ON WAREHOUSE P05_WH TO ROLE P05_READER;

CREATE DATABASE IF NOT EXISTS P05_CDC COMMENT = 'P05 TPC-H change data capture with streams and tasks';
GRANT OWNERSHIP ON DATABASE P05_CDC TO ROLE P05_OWNER COPY CURRENT GRANTS;

GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE P05_OWNER;
GRANT EXECUTE TASK, EXECUTE MANAGED TASK ON ACCOUNT TO ROLE P05_OWNER;
