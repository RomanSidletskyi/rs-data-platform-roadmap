-- P05 task graph, all tasks in schema PIPE (a graph must live in one schema). Run as P05_OWNER.
--
--   PIPE.CDC_ROOT (every 5 minutes, only when a source stream has data)
--     |-- PIPE.LOAD_DIM_CUSTOMER    MERGE from the customer stream (stream metadata technique)
--     |-- PIPE.LOAD_FACT_ORDER      affected keys from two streams, recompute from current state
--           |-- PIPE.LOAD_DAILY_REVENUE   affected dates from the fact stream, recompute those dates
--   PIPE.FINALIZE_RUN (finalizer)  reconciliation and run log, after success or failure

USE ROLE P05_OWNER;
USE WAREHOUSE P05_WH;
USE DATABASE P05_CDC;

ALTER TASK IF EXISTS PIPE.CDC_ROOT SUSPEND;

-- WHEN is evaluated in the cloud services layer: no compute starts when all streams are empty.
CREATE OR REPLACE TASK PIPE.CDC_ROOT
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  SCHEDULE = '5 MINUTE'
  SUSPEND_TASK_AFTER_NUM_FAILURES = 3
  COMMENT = 'Root: starts the graph when the order system changed'
  WHEN SYSTEM$STREAM_HAS_DATA('P05_CDC.SRC.CUSTOMER_STREAM')
    OR SYSTEM$STREAM_HAS_DATA('P05_CDC.SRC.ORDERS_STREAM')
    OR SYSTEM$STREAM_HAS_DATA('P05_CDC.SRC.LINEITEM_STREAM')
AS
  INSERT INTO OPS.RUN_LOG
  SELECT CURRENT_TIMESTAMP(), SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'), 'CDC_ROOT', NULL, 'changes detected';

CREATE OR REPLACE TASK PIPE.LOAD_DIM_CUSTOMER
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  COMMENT = 'SCD1 customer dimension from the customer stream, soft deletes'
  AFTER PIPE.CDC_ROOT
AS
EXECUTE IMMEDIATE $$
DECLARE
  changed NUMBER DEFAULT 0;
BEGIN
  -- A standard stream returns the net change per row: an update is a DELETE of the old image plus an INSERT
  -- of the new one, both with METADATA$ISUPDATE = TRUE. Dropping the old image leaves one row per key.
  MERGE INTO CORE.DIM_CUSTOMER t
  USING (
    SELECT s.C_CUSTKEY, s.C_NAME, n.N_NAME, s.C_MKTSEGMENT, s.C_ACCTBAL, s.METADATA$ACTION AS ACT
    FROM SRC.CUSTOMER_STREAM s
    LEFT JOIN SRC.NATION n ON n.N_NATIONKEY = s.C_NATIONKEY
    WHERE NOT (s.METADATA$ACTION = 'DELETE' AND s.METADATA$ISUPDATE)
  ) s
  ON t.CUSTOMER_KEY = s.C_CUSTKEY
  WHEN MATCHED AND s.ACT = 'DELETE' THEN UPDATE SET
    IS_DELETED = TRUE, UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN MATCHED THEN UPDATE SET
    CUSTOMER_NAME = s.C_NAME, NATION = s.N_NAME, MARKET_SEGMENT = s.C_MKTSEGMENT,
    ACCOUNT_BALANCE = s.C_ACCTBAL, IS_DELETED = FALSE, UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED AND s.ACT = 'INSERT' THEN INSERT
    (CUSTOMER_KEY, CUSTOMER_NAME, NATION, MARKET_SEGMENT, ACCOUNT_BALANCE, IS_DELETED, UPDATED_AT)
    VALUES (s.C_CUSTKEY, s.C_NAME, s.N_NAME, s.C_MKTSEGMENT, s.C_ACCTBAL, FALSE, CURRENT_TIMESTAMP());
  changed := SQLROWCOUNT;

  INSERT INTO OPS.RUN_LOG
  SELECT CURRENT_TIMESTAMP(), SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'), 'LOAD_DIM_CUSTOMER', :changed, NULL;
END;
$$;

CREATE OR REPLACE TASK PIPE.LOAD_FACT_ORDER
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  COMMENT = 'Recompute every order touched by an order or line change'
  AFTER PIPE.CDC_ROOT
AS
EXECUTE IMMEDIATE $$
DECLARE
  affected NUMBER DEFAULT 0;
  changed  NUMBER DEFAULT 0;
BEGIN
  BEGIN TRANSACTION;

  -- One statement reads both streams; both offsets advance together when the transaction commits.
  DELETE FROM CORE.AFFECTED_ORDER;
  INSERT INTO CORE.AFFECTED_ORDER
    SELECT O_ORDERKEY FROM SRC.ORDERS_STREAM
    UNION
    SELECT L_ORDERKEY FROM SRC.LINEITEM_STREAM;
  affected := SQLROWCOUNT;

  -- Recompute instead of applying deltas: running this twice gives the same result.
  MERGE INTO CORE.FACT_ORDER t
  USING (
    SELECT k.ORDER_KEY AS AFFECTED_KEY, v.*
    FROM CORE.AFFECTED_ORDER k
    LEFT JOIN (
      SELECT * FROM CORE.V_ORDER_CURRENT
      WHERE ORDER_KEY IN (SELECT ORDER_KEY FROM CORE.AFFECTED_ORDER)
    ) v ON v.ORDER_KEY = k.ORDER_KEY
  ) s
  ON t.ORDER_KEY = s.AFFECTED_KEY
  WHEN MATCHED AND s.ORDER_KEY IS NULL THEN DELETE
  -- Skip no-op updates: every updated row would otherwise show up in FACT_ORDER_STREAM and cost work downstream.
  WHEN MATCHED AND (
       t.ORDER_STATUS   IS DISTINCT FROM s.ORDER_STATUS
    OR t.CUSTOMER_KEY   IS DISTINCT FROM s.CUSTOMER_KEY
    OR t.ORDER_DATE     IS DISTINCT FROM s.ORDER_DATE
    OR t.ORDER_PRIORITY IS DISTINCT FROM s.ORDER_PRIORITY
    OR t.LINE_COUNT     IS DISTINCT FROM s.LINE_COUNT
    OR t.QUANTITY       IS DISTINCT FROM s.QUANTITY
    OR t.GROSS_AMOUNT   IS DISTINCT FROM s.GROSS_AMOUNT
    OR t.NET_REVENUE    IS DISTINCT FROM s.NET_REVENUE
  ) THEN UPDATE SET
    CUSTOMER_KEY = s.CUSTOMER_KEY, ORDER_DATE = s.ORDER_DATE, ORDER_STATUS = s.ORDER_STATUS,
    ORDER_PRIORITY = s.ORDER_PRIORITY, LINE_COUNT = s.LINE_COUNT, QUANTITY = s.QUANTITY,
    GROSS_AMOUNT = s.GROSS_AMOUNT, NET_REVENUE = s.NET_REVENUE, UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED AND s.ORDER_KEY IS NOT NULL THEN INSERT
    (ORDER_KEY, CUSTOMER_KEY, ORDER_DATE, ORDER_STATUS, ORDER_PRIORITY, LINE_COUNT, QUANTITY, GROSS_AMOUNT, NET_REVENUE, UPDATED_AT)
    VALUES (s.ORDER_KEY, s.CUSTOMER_KEY, s.ORDER_DATE, s.ORDER_STATUS, s.ORDER_PRIORITY, s.LINE_COUNT, s.QUANTITY,
            s.GROSS_AMOUNT, s.NET_REVENUE, CURRENT_TIMESTAMP());
  changed := SQLROWCOUNT;

  INSERT INTO OPS.RUN_LOG
  SELECT CURRENT_TIMESTAMP(), SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'), 'LOAD_FACT_ORDER', :changed,
         :affected || ' orders affected';
  COMMIT;
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END;
$$;

CREATE OR REPLACE TASK PIPE.LOAD_DAILY_REVENUE
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  COMMENT = 'Recompute the days whose orders changed'
  AFTER PIPE.LOAD_FACT_ORDER
AS
EXECUTE IMMEDIATE $$
DECLARE
  days NUMBER DEFAULT 0;
BEGIN
  BEGIN TRANSACTION;

  -- Deleted orders appear in the stream with their old date, so cancelled orders also mark their day.
  DELETE FROM MART.AFFECTED_DATE;
  INSERT INTO MART.AFFECTED_DATE
  SELECT DISTINCT ORDER_DATE FROM CORE.FACT_ORDER_STREAM;
  days := SQLROWCOUNT;

  DELETE FROM MART.DAILY_REVENUE WHERE ORDER_DATE IN (SELECT ORDER_DATE FROM MART.AFFECTED_DATE);
  INSERT INTO MART.DAILY_REVENUE
  SELECT ORDER_DATE, COUNT(*), COUNT_IF(ORDER_STATUS = 'O'), SUM(LINE_COUNT), SUM(GROSS_AMOUNT), SUM(NET_REVENUE), CURRENT_TIMESTAMP()
  FROM CORE.FACT_ORDER
  WHERE ORDER_DATE IN (SELECT ORDER_DATE FROM MART.AFFECTED_DATE)
  GROUP BY ORDER_DATE;

  INSERT INTO OPS.RUN_LOG
  SELECT CURRENT_TIMESTAMP(), SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'), 'LOAD_DAILY_REVENUE', :days, 'days recomputed';
  COMMIT;
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END;
$$;

-- Runs after every graph run that started, whether it succeeded or failed.
CREATE OR REPLACE TASK PIPE.FINALIZE_RUN
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  COMMENT = 'Reconciliation count and run log after each graph run'
  FINALIZE = PIPE.CDC_ROOT
AS
  INSERT INTO OPS.RUN_LOG
  SELECT CURRENT_TIMESTAMP(), SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID'), 'FINALIZE_RUN',
         (SELECT COUNT(*) FROM OPS.V_RECONCILIATION), 'days where MART differs from SRC';

SELECT SYSTEM$TASK_DEPENDENTS_ENABLE('P05_CDC.PIPE.CDC_ROOT');
SHOW TASKS IN SCHEMA PIPE;
