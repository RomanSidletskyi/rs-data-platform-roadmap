-- P05 operations: stream state, graph runs, serverless cost, run log. Run as P05_OWNER at any time.

USE ROLE P05_OWNER;
USE WAREHOUSE P05_WH;
USE DATABASE P05_CDC;

-- Pending changes per stream. STALE_AFTER: consume before this time or the stream must be recreated.
SHOW STREAMS IN DATABASE P05_CDC;
SELECT "name" AS STREAM_NAME, "table_name", "stale", "stale_after", "mode"
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SELECT
  SYSTEM$STREAM_HAS_DATA('P05_CDC.SRC.CUSTOMER_STREAM')    AS CUSTOMER_PENDING,
  SYSTEM$STREAM_HAS_DATA('P05_CDC.SRC.ORDERS_STREAM')      AS ORDERS_PENDING,
  SYSTEM$STREAM_HAS_DATA('P05_CDC.SRC.LINEITEM_STREAM')    AS LINEITEM_PENDING,
  SYSTEM$STREAM_HAS_DATA('P05_CDC.CORE.FACT_ORDER_STREAM') AS FACT_PENDING;

-- Graph runs: one row per run, with the first failing task.
SELECT ROOT_TASK_NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME,
       DATEDIFF('second', QUERY_START_TIME, COMPLETED_TIME) AS SECONDS,
       FIRST_ERROR_TASK_NAME, FIRST_ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.COMPLETE_TASK_GRAPHS(ROOT_TASK_NAME => 'CDC_ROOT'))
ORDER BY SCHEDULED_TIME DESC
LIMIT 20;

-- Skipped root runs: WHEN was false, no compute used.
SELECT NAME, STATE, COUNT(*) AS RUNS
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
  SCHEDULED_TIME_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP()),
  TASK_NAME => 'CDC_ROOT'))
GROUP BY 1, 2;

-- Serverless task credits in the last 24 hours, per task.
SELECT TASK_NAME, SUM(CREDITS_USED) AS CREDITS
FROM TABLE(INFORMATION_SCHEMA.SERVERLESS_TASK_HISTORY(
  DATE_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP())))
GROUP BY 1
ORDER BY 2 DESC;

SELECT * FROM OPS.RUN_LOG ORDER BY RUN_AT DESC LIMIT 30;
