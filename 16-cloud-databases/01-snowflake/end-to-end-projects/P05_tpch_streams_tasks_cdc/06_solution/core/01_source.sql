-- P05 source: a copy of TPC-H orders for 1997 that the simulator then changes day by day. Run as P05_OWNER.
-- In a real system SRC would be a replica landed by a CDC tool from the order database.

USE ROLE P05_OWNER;
USE WAREHOUSE P05_WH;
USE DATABASE P05_CDC;

CREATE SCHEMA IF NOT EXISTS SRC  COMMENT = 'Replica of the order system; changed only by OPS.SIMULATE_DAY';
CREATE SCHEMA IF NOT EXISTS CORE COMMENT = 'Current-state dimension and fact, maintained incrementally';
CREATE SCHEMA IF NOT EXISTS MART COMMENT = 'Daily revenue: task version and dynamic table version';
CREATE SCHEMA IF NOT EXISTS PIPE COMMENT = 'Task graph: all tasks of one graph must live in one schema';
CREATE SCHEMA IF NOT EXISTS OPS  COMMENT = 'Simulator, run log, reconciliation';

-- IF NOT EXISTS keeps reruns from replacing tables, which would invalidate their streams.
CREATE TABLE IF NOT EXISTS SRC.NATION AS
SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION;

CREATE TABLE IF NOT EXISTS SRC.CUSTOMER AS
SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER;

CREATE TABLE IF NOT EXISTS SRC.ORDERS AS
SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS
WHERE O_ORDERDATE BETWEEN '1997-01-01' AND '1997-12-31';

CREATE TABLE IF NOT EXISTS SRC.LINEITEM AS
SELECT l.*
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM l
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS o ON o.O_ORDERKEY = l.L_ORDERKEY
WHERE o.O_ORDERDATE BETWEEN '1997-01-01' AND '1997-12-31';

CREATE TABLE IF NOT EXISTS OPS.RUN_LOG (
  RUN_AT        TIMESTAMP_LTZ,
  GRAPH_RUN_ID  STRING,
  STEP          STRING,
  ROWS_AFFECTED NUMBER,
  NOTE          STRING
);

-- Streams are created before the initial snapshot of CORE is taken (10_core_mart.sql).
-- A change between stream creation and snapshot is then processed twice, which the idempotent
-- logic tolerates. The other order could lose that change.
CREATE STREAM IF NOT EXISTS SRC.CUSTOMER_STREAM ON TABLE SRC.CUSTOMER COMMENT = 'Consumer: PIPE.LOAD_DIM_CUSTOMER';
CREATE STREAM IF NOT EXISTS SRC.ORDERS_STREAM   ON TABLE SRC.ORDERS   COMMENT = 'Consumer: PIPE.LOAD_FACT_ORDER';
CREATE STREAM IF NOT EXISTS SRC.LINEITEM_STREAM ON TABLE SRC.LINEITEM COMMENT = 'Consumer: PIPE.LOAD_FACT_ORDER';

SELECT 'ORDERS' AS T, COUNT(*) AS ROWS_, MIN(O_ORDERDATE) AS FIRST_DAY, MAX(O_ORDERDATE) AS LAST_DAY FROM SRC.ORDERS
UNION ALL SELECT 'LINEITEM', COUNT(*), NULL, NULL FROM SRC.LINEITEM
UNION ALL SELECT 'CUSTOMER', COUNT(*), NULL, NULL FROM SRC.CUSTOMER;
