-- P05 core and mart: tables, the order definition, and a one-time bootstrap from SRC. Run as P05_OWNER.
-- Run once. Rerunning is safe, but the next graph run then recomputes every order date.

USE ROLE P05_OWNER;
USE WAREHOUSE P05_WH;
USE DATABASE P05_CDC;

CREATE TABLE IF NOT EXISTS CORE.DIM_CUSTOMER (
  CUSTOMER_KEY    NUMBER,
  CUSTOMER_NAME   STRING,
  NATION          STRING,
  MARKET_SEGMENT  STRING,
  ACCOUNT_BALANCE NUMBER(12, 2),
  IS_DELETED      BOOLEAN,
  UPDATED_AT      TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS CORE.FACT_ORDER (
  ORDER_KEY      NUMBER,
  CUSTOMER_KEY   NUMBER,
  ORDER_DATE     DATE,
  ORDER_STATUS   STRING,
  ORDER_PRIORITY STRING,
  LINE_COUNT     NUMBER,
  QUANTITY       NUMBER(18, 2),
  GROSS_AMOUNT   NUMBER(18, 2),
  NET_REVENUE    NUMBER(18, 4),
  UPDATED_AT     TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS MART.DAILY_REVENUE (
  ORDER_DATE   DATE,
  ORDERS       NUMBER,
  OPEN_ORDERS  NUMBER,
  LINES        NUMBER,
  GROSS_AMOUNT NUMBER(18, 2),
  NET_REVENUE  NUMBER(18, 4),
  UPDATED_AT   TIMESTAMP_LTZ
);

-- Work tables: the keys and dates touched by the current graph run.
CREATE TRANSIENT TABLE IF NOT EXISTS CORE.AFFECTED_ORDER (ORDER_KEY NUMBER);
CREATE TRANSIENT TABLE IF NOT EXISTS MART.AFFECTED_DATE (ORDER_DATE DATE);

-- The single definition of an order's current state. Bootstrap, incremental runs, and reconciliation all use it.
CREATE OR REPLACE VIEW CORE.V_ORDER_CURRENT AS
SELECT
  o.O_ORDERKEY                                          AS ORDER_KEY,
  o.O_CUSTKEY                                           AS CUSTOMER_KEY,
  o.O_ORDERDATE                                         AS ORDER_DATE,
  o.O_ORDERSTATUS                                       AS ORDER_STATUS,
  o.O_ORDERPRIORITY                                     AS ORDER_PRIORITY,
  COUNT(l.L_LINENUMBER)                                 AS LINE_COUNT,
  COALESCE(SUM(l.L_QUANTITY), 0)                        AS QUANTITY,
  COALESCE(SUM(l.L_EXTENDEDPRICE), 0)                   AS GROSS_AMOUNT,
  COALESCE(SUM(l.L_EXTENDEDPRICE * (1 - l.L_DISCOUNT)), 0) AS NET_REVENUE
FROM SRC.ORDERS o
LEFT JOIN SRC.LINEITEM l ON l.L_ORDERKEY = o.O_ORDERKEY
GROUP BY 1, 2, 3, 4, 5;

INSERT OVERWRITE INTO CORE.DIM_CUSTOMER
SELECT c.C_CUSTKEY, c.C_NAME, n.N_NAME, c.C_MKTSEGMENT, c.C_ACCTBAL, FALSE, CURRENT_TIMESTAMP()
FROM SRC.CUSTOMER c
LEFT JOIN SRC.NATION n ON n.N_NATIONKEY = c.C_NATIONKEY;

INSERT OVERWRITE INTO CORE.FACT_ORDER
SELECT ORDER_KEY, CUSTOMER_KEY, ORDER_DATE, ORDER_STATUS, ORDER_PRIORITY,
       LINE_COUNT, QUANTITY, GROSS_AMOUNT, NET_REVENUE, CURRENT_TIMESTAMP()
FROM CORE.V_ORDER_CURRENT;

-- Created after the fact bootstrap: the mart starts from the bootstrapped fact, and the stream only carries later changes.
CREATE STREAM IF NOT EXISTS CORE.FACT_ORDER_STREAM ON TABLE CORE.FACT_ORDER COMMENT = 'Consumer: PIPE.LOAD_DAILY_REVENUE';

INSERT OVERWRITE INTO MART.DAILY_REVENUE
SELECT ORDER_DATE, COUNT(*), COUNT_IF(ORDER_STATUS = 'O'), SUM(LINE_COUNT), SUM(GROSS_AMOUNT), SUM(NET_REVENUE), CURRENT_TIMESTAMP()
FROM CORE.FACT_ORDER
GROUP BY ORDER_DATE;

-- Days where the incrementally maintained mart differs from a full recompute over SRC. Expected: no rows.
CREATE OR REPLACE VIEW OPS.V_RECONCILIATION AS
WITH truth AS (
  SELECT ORDER_DATE, COUNT(*) AS ORDERS, SUM(NET_REVENUE) AS NET_REVENUE
  FROM CORE.V_ORDER_CURRENT
  GROUP BY ORDER_DATE
)
SELECT
  COALESCE(t.ORDER_DATE, m.ORDER_DATE) AS ORDER_DATE,
  t.ORDERS      AS SRC_ORDERS,
  m.ORDERS      AS MART_ORDERS,
  t.NET_REVENUE AS SRC_NET_REVENUE,
  m.NET_REVENUE AS MART_NET_REVENUE
FROM truth t
FULL OUTER JOIN MART.DAILY_REVENUE m ON m.ORDER_DATE = t.ORDER_DATE
WHERE t.ORDERS IS DISTINCT FROM m.ORDERS
   OR t.NET_REVENUE IS DISTINCT FROM m.NET_REVENUE;

GRANT USAGE ON DATABASE P05_CDC TO ROLE P05_READER;
GRANT USAGE ON SCHEMA CORE TO ROLE P05_READER;
GRANT USAGE ON SCHEMA MART TO ROLE P05_READER;
GRANT SELECT ON TABLE CORE.DIM_CUSTOMER  TO ROLE P05_READER;
GRANT SELECT ON TABLE CORE.FACT_ORDER    TO ROLE P05_READER;
GRANT SELECT ON TABLE MART.DAILY_REVENUE TO ROLE P05_READER;

SELECT 'DIM_CUSTOMER' AS T, COUNT(*) AS ROWS_ FROM CORE.DIM_CUSTOMER
UNION ALL SELECT 'FACT_ORDER', COUNT(*) FROM CORE.FACT_ORDER
UNION ALL SELECT 'DAILY_REVENUE', COUNT(*) FROM MART.DAILY_REVENUE;
